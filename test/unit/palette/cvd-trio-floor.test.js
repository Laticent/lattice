/** Every trio pair on every palette, both modes, three deficiencies. */
function measure() {
  const out = new Map();
  for (const theme of listAllThemes()) {
    const vars = mergedVars(theme);
    for (const [mode, isDark] of [['light', false], ['dark', true]]) {
      const hex = (t) => {
        const v = resolveTokenExpr(vars[t], vars, isDark);
        return /^#[0-9a-f]{6}$/i.test(String(v).trim()) ? String(v).trim() : null;
      };
      for (let i = 0; i < TRIO.length; i++) {
        for (let j = i + 1; j < TRIO.length; j++) {
          const a = hex(TRIO[i]); const b = hex(TRIO[j]);
          if (!a || !b) continue;
          for (const type of TYPES) {
            out.set(`${theme}|${mode}|${TRIO[i]}^${TRIO[j]}|${type}`,
                    oklabDistance(simulate(a, type), simulate(b, type)));
          }
        }
      }
    }
  }
  return out;
}

const now = measure();

describe('CVD status-trio separation (frozen distances)', () => {
  test('every frozen pair still resolves', () => {
    const missing = [...CVD_FROZEN.keys()].filter((k) => !now.has(k));
    assert.deepEqual(missing, [],
      `frozen CVD pairs no longer produced — a palette or token was renamed:\n  ${missing.join('\n  ')}`);
  });

  test('a pair at or above the collapse floor still clears it', () => {
    const collapsed = [];
    for (const [k, frozen] of CVD_FROZEN) {
      const floor = collapseFloor(k.split('|')[3]);
      if (frozen < floor) continue;
      const v = now.get(k);
      if (v != null && v < floor) collapsed.push(`${k}  ${frozen.toFixed(4)} -> ${v.toFixed(4)} (floor ${floor})`);
    }
    assert.deepEqual(collapsed, [],
      `${collapsed.length} status pair(s) fell through the CVD collapse floor:\n  ${collapsed.join('\n  ')}`);
  });

  test('a pair already below the floor does not erode further', () => {
    const eroded = [];
    for (const [k, frozen] of CVD_FROZEN) {
      if (frozen >= collapseFloor(k.split('|')[3])) continue;
      const v = now.get(k);
      if (v != null && v < frozen - EROSION_TOLERANCE) eroded.push(`${k}  ${frozen.toFixed(4)} -> ${v.toFixed(4)}`);
    }
    assert.deepEqual(eroded, [],
      `${eroded.length} already-collapsed pair(s) eroded further:\n  ${eroded.join('\n  ')}`);
  });

  test('the frozen table is not stale', () => {
    const extra = [...now.keys()].filter((k) => !CVD_FROZEN.has(k));
    assert.deepEqual(extra, [],
      `pairs measured but not frozen — add them:\n  ${extra.join('\n  ')}`);
    assert.equal(CVD_FROZEN.size, now.size);
  });

  test('coverage: every palette is scanned', () => {
    assert.ok(listAllThemes().length >= 30);
    assert.equal(now.size, listAllThemes().length * 2 * 3 * TYPES.length);
    assert.equal(TYPES.length, 4, 'the monochromacy arm must stay in the frozen table');
  });
});
