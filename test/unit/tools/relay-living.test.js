/**
 * Unit: the living handoff comment and the relay board (tools/relay-core.js postLiving /
 * buildLivingBody, tools/relay.js, `npm run card -- --living`). Decision:
 * engineering/decisions/2026-11-22-two-person-relay.md, Tensions 3 and 6.
 *
 * The dangerous directions: a session that does not hold the baton overwrites the holder's
 * handoff, and a second living comment appears so readers find a stale one. Every input is
 * injected, "now" included (HARD RULE #32): no clock, no network, no git.
 */
const { describe, test } = require('node:test');
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const relay = require('../../../tools/relay-core');
const board = require('../../../tools/relay');

const ROOT = path.join(__dirname, '../../..');
const MIN = 60 * 1000;
const T0 = Date.parse('2026-11-22T12:00:00Z');
const ME = 'session_ME01';
const THEM = 'session_TH02';
const CARD = { card: 'continuation', priorities: [{ title: 'wire the board' }] };

function fakeGitHub({ comments = [], headRef = 'claude/x', state = 'open' } = {}) {
  const calls = [];
  const api = (method, p, opts = {}) => {
    calls.push({ method, p, body: opts.body });
    if (method === 'GET' && /pulls\/\d+$/.test(p)) return { state, head: { ref: headRef, sha: 'f00dfeed00' } };
    if (method === 'GET' && p.includes('/comments?')) return comments;
    if (method === 'PATCH') return {};
    if (method === 'POST') return { html_url: 'https://example.test/new' };
    throw new Error(`unexpected ${method} ${p}`);
  };
  return { api, calls };
}
const gitHead = (session, at = T0 - 5 * MIN) => () => ({ exists: true, head: { sha: 'abc1234def', session, actor: null, time: at } });
const post = (o) =>
  relay.postLiving({ pr: 3427, card: CARD, extra: {}, cardText: '```\ncard\n```', signatureLine: '— John Luke Picard · session_ME01', holderName: 'John Luke Picard', env: { LATTICE_SESSION: ME }, now: T0, ...o });

describe('buildLivingBody', () => {
  const body = relay.buildLivingBody({
    cardText: '```\ncard\n```',
    card: CARD,
    extra: { traps: ['ci.yml skips on draft'], unverified: [], claims: ['test:a.test.js#b'] },
    holder: `John Luke Picard · ${ME}`,
    since: 'S',
    checkpoint: 'C',
    head: 'abc1234',
    signatureLine: '— John Luke Picard · session_ME01',
  });
  test('opens with the marker and a BATON block that parseLiving reads back', () => {
    assert.ok(body.startsWith(relay.MARKER));
    assert.deepEqual(relay.parseLiving(body), { released: false, holder: 'John Luke Picard', session: ME, since: 'S' });
    assert.match(body, /^next: P1: wire the board$/m);
  });
  test('lists only non-empty extras, then the signature above the footer', () => {
    assert.match(body, /\*\*TRAPS\*\*\n- ci\.yml skips on draft/);
    assert.doesNotMatch(body, /UNVERIFIED/);
    assert.match(body, /— John Luke Picard · session_ME01\n\n---\n_Generated by \[Claude Code\]/);
  });
});

describe('postLiving', () => {
  test('no living comment yet and I pushed the head: one POST', () => {
    const gh = fakeGitHub();
    const r = post({ api: gh.api, git: gitHead(ME) });
    assert.deepEqual(r, { url: 'https://example.test/new', created: true });
    const writes = gh.calls.filter((c) => c.method !== 'GET');
    assert.equal(writes.length, 1);
    assert.equal(writes[0].p, 'repos/Laticent/lattice/issues/3427/comments');
    assert.match(writes[0].body.body, /^since: 2026-11-22T12:00:00\.000Z$/m);
  });

  test('a living comment exists: PATCH it in place, keep since while I hold it', () => {
    const existing = relay.livingHeader({ baton: 'held', holder: `John Luke Picard · ${ME}`, since: 'EARLIER', checkpoint: 'c', head: 'h', next: 'n' });
    const gh = fakeGitHub({ comments: [{ id: 7, body: existing, updated_at: new Date(T0 - 3 * MIN).toISOString(), html_url: 'u7' }] });
    const r = post({ api: gh.api, git: gitHead(ME) });
    assert.equal(r.created, false);
    const writes = gh.calls.filter((c) => c.method !== 'GET');
    assert.deepEqual(writes.map((w) => `${w.method} ${w.p}`), ['PATCH repos/Laticent/lattice/issues/comments/7']);
    assert.match(writes[0].body.body, /^since: EARLIER$/m);
    assert.match(writes[0].body.body, /^checkpoint: 2026-11-22T12:00:00\.000Z$/m);
  });

  test('another session holds the baton: refused, nothing written', () => {
    const gh = fakeGitHub();
    assert.throws(() => post({ api: gh.api, git: gitHead(THEM) }), (e) => e.code === 1 && /only the holder/.test(e.message));
    assert.equal(gh.calls.filter((c) => c.method !== 'GET').length, 0);
  });

  test('free (lease expired) but I have not pushed: refused, push first', () => {
    const gh = fakeGitHub();
    assert.throws(() => post({ api: gh.api, git: gitHead(THEM, T0 - 120 * MIN) }), (e) => e.code === 1 && /push a commit first/.test(e.message));
    assert.equal(gh.calls.filter((c) => c.method !== 'GET').length, 0);
  });

  test('a closed PR, or no session id: refused', () => {
    assert.throws(() => post({ api: fakeGitHub({ state: 'closed' }).api, git: gitHead(ME) }), /closed/);
    assert.throws(() => post({ api: fakeGitHub().api, git: gitHead(ME), env: {} }), (e) => e.code === 64);
  });
});

describe('npm run relay', () => {
  const living = relay.livingHeader({ baton: 'held', holder: 'x', since: 's', checkpoint: 'c', head: 'h', next: 'run the trio' });
  const api = (method, p) => {
    if (p.includes('/pulls?')) {
      return [
        { number: 1, user: { login: 'saden1' }, head: { ref: 'claude/a', sha: 'aaa' } },
        { number: 2, user: { login: 'dependabot[bot]' }, head: { ref: 'deps', sha: 'bbb' } },
        { number: 3, user: { login: 'saden1' }, head: { ref: 'claude/c', sha: 'ccc' } },
      ];
    }
    if (p.includes('issues/1/comments')) return [{ id: 1, body: living, updated_at: new Date(T0 - 10 * MIN).toISOString(), html_url: 'u1' }];
    if (p.includes('issues/3/comments')) return [{ id: 3, body: 'no marker', updated_at: new Date(T0).toISOString() }];
    if (p.endsWith('commits/aaa')) {
      return { commit: { message: `x\n\nRelay-Actor: James Tiberius Kirk\nClaude-Session: https://claude.ai/code/${THEM}`, committer: { date: new Date(T0 - 20 * MIN).toISOString() } } };
    }
    throw new Error(`unexpected ${method} ${p}`);
  };

  test('one row per PR with a living comment; bots and unmarked PRs skipped', () => {
    const lines = board.board({ api, now: T0 });
    assert.equal(lines.length, 3);
    assert.match(lines[2], /^\| \[#1\]\(u1\) \| `claude\/a` \| James Tiberius Kirk · session_TH02 \| held \| 50 min \| run the trio \|$/);
  });

  test('sign prints the line, or exits 1 when it cannot', () => {
    const out = [];
    assert.equal(board.run(['sign'], { env: { LATTICE_ACTOR: 'kirk', LATTICE_SESSION: THEM }, out: (s) => out.push(s), err: () => {} }), 0);
    assert.deepEqual(out, ['— James Tiberius Kirk · session_TH02']);
    assert.equal(board.run(['sign'], { env: {}, out: () => {}, err: () => {} }), 1);
    assert.equal(board.run(['sign'], { env: { LATTICE_ACTOR: 'spock' }, out: () => {}, err: () => {} }), 1);
  });

  test('GitHub could not be read: exit 3', () => {
    const api3 = () => {
      throw new relay.RelayError('gh api failed');
    };
    assert.equal(board.run([], { api: api3, out: () => {}, err: () => {} }), 3);
  });
});

describe('npm run card -- relay: block', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'living-'));
  const yml = path.join(dir, 'card.yml');
  const base = fs.readFileSync(path.join(ROOT, 'engineering', 'card-examples', 'continuation.yml'), 'utf8');

  test('a relay: block without --living is refused, not silently dropped', () => {
    fs.writeFileSync(yml, `${base}\nrelay:\n  traps:\n    - "ci.yml skips on draft"\n`);
    const r = spawnSync(process.execPath, [path.join(ROOT, 'tools', 'card.js'), yml], { encoding: 'utf8' });
    assert.equal(r.status, 1);
    assert.match(r.stderr, /relay: is read only with --living/);
  });

  test('--living needs a PR number', () => {
    const r = spawnSync(process.execPath, [path.join(ROOT, 'tools', 'card.js'), '--living', 'x', yml], { encoding: 'utf8' });
    assert.equal(r.status, 2);
  });
});
