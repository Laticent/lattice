/**
 * Unit: the living handoff comment and the relay board (tools/relay-core.js postLiving /
 * buildLivingBody, tools/relay.js, `npm run card -- --living`). Decision:
 * engineering/decisions/2026-11-22-two-person-relay.md, Tensions 3 and 6.
 *
 * The dangerous directions: a session that does not hold the baton overwrites the holder's
 * handoff, and a second living comment appears so readers find a stale one. Every input is
 * injected, "now" included (HARD RULE #32): no clock, no network, no git.
 */
const { describe, test } = require('node:test');
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const relay = require('../../../tools/relay-core');
const board = require('../../../tools/relay');

const ROOT = path.join(__dirname, '../../..');
const MIN = 60 * 1000;
const T0 = Date.parse('2026-11-22T12:00:00Z');
const ME = 'session_ME01';
const THEM = 'session_TH02';
const CARD = { card: 'continuation', priorities: [{ title: 'wire the board' }] };

function fakeGitHub({ comments = [], headRef = 'claude/x', state = 'open' } = {}) {
  const calls = [];
  const api = (method, p, opts = {}) => {
    calls.push({ method, p, body: opts.body });
    if (p === 'user') return { login: 'saden1' };
    if (method === 'GET' && /pulls\/\d+$/.test(p)) return { state, head: { ref: headRef, sha: 'f00dfeed00' } };
    if (method === 'GET' && p.includes('/comments?')) return comments;
    if (method === 'PATCH') return {};
    if (method === 'POST') return { html_url: 'https://example.test/new' };
    throw new Error(`unexpected ${method} ${p}`);
  };
  return { api, calls };
}
const gitHead = (session) => () => ({ exists: true, head: { sha: 'abc1234def', session, actor: null } });
const post = (o) =>
  relay.postLiving({ pr: 3427, card: CARD, extra: {}, cardText: '```\ncard\n```', signatureLine: '— John Luke Picard · session_ME01', holderName: 'John Luke Picard', env: { LATTICE_SESSION: ME }, now: T0, ...o });

describe('buildLivingBody', () => {
  const body = relay.buildLivingBody({
    cardText: '```\ncard\n```',
    card: CARD,
    extra: { traps: ['ci.yml skips on draft'], unverified: [], claims: ['test:a.test.js#b'] },
    holder: `John Luke Picard · ${ME}`,
    since: 'S',
    checkpoint: 'C',
    head: 'abc1234',
    signatureLine: '— John Luke Picard · session_ME01',
  });
  test('opens with the marker and a BATON block that parseLiving reads back', () => {
    assert.ok(body.startsWith(relay.MARKER));
    assert.deepEqual(relay.parseLiving(body), { released: false, gate: null, pause: null, holder: 'John Luke Picard', session: ME, since: 'S', head: 'abc1234' });
    assert.match(body, /^next: P1: wire the board$/m);
  });
  test('lists only non-empty extras, then the signature above the footer', () => {
    assert.match(body, /\*\*TRAPS\*\*\n- ci\.yml skips on draft/);
    assert.doesNotMatch(body, /UNVERIFIED/);
    assert.match(body, /— John Luke Picard · session_ME01\n\n---\n_Generated by \[Claude Code\]/);
  });
});

describe('postLiving', () => {
  test('no living comment yet and I pushed the head: one POST', () => {
    const gh = fakeGitHub();
    const r = post({ api: gh.api, git: gitHead(ME) });
    assert.deepEqual(r, { url: 'https://example.test/new', created: true });
    const writes = gh.calls.filter((c) => c.method !== 'GET');
    assert.equal(writes.length, 1);
    assert.equal(writes[0].p, 'repos/Laticent/lattice/issues/3427/comments');
    assert.match(writes[0].body.body, /^since: 2026-11-22T12:00:00\.000Z$/m);
  });

  test('a living comment exists: PATCH it in place, keep since while I hold it', () => {
    const existing = relay.livingHeader({ baton: 'held', holder: `John Luke Picard · ${ME}`, since: 'EARLIER', checkpoint: 'c', head: 'h', next: 'n' });
    const gh = fakeGitHub({ comments: [{ id: 7, user: { login: 'saden1' }, body: existing, updated_at: new Date(T0 - 3 * MIN).toISOString(), html_url: 'u7' }] });
    const r = post({ api: gh.api, git: gitHead(ME) });
    assert.equal(r.created, false);
    const writes = gh.calls.filter((c) => c.method !== 'GET');
    assert.deepEqual(writes.map((w) => `${w.method} ${w.p}`), ['PATCH repos/Laticent/lattice/issues/comments/7']);
    assert.match(writes[0].body.body, /^since: EARLIER$/m);
    assert.match(writes[0].body.body, /^checkpoint: 2026-11-22T12:00:00\.000Z$/m);
  });

  test('another session holds the baton: refused, nothing written', () => {
    const gh = fakeGitHub();
    assert.throws(() => post({ api: gh.api, git: gitHead(THEM) }), (e) => e.code === 1 && /only the holder/.test(e.message));
    assert.equal(gh.calls.filter((c) => c.method !== 'GET').length, 0);
  });

  test('free (released) but I have not pushed: refused, push first', () => {
    const released = relay.livingHeader({ baton: 'released', holder: `James Tiberius Kirk · ${THEM}`, since: 'S', checkpoint: 'c', head: 'abc1234', next: 'n' });
    const gh = fakeGitHub({ comments: [{ id: 8, user: { login: 'saden1' }, body: released, updated_at: new Date(T0 - MIN).toISOString(), html_url: 'u8' }] });
    assert.throws(() => post({ api: gh.api, git: gitHead(THEM) }), (e) => e.code === 1 && /push a commit first/.test(e.message));
    assert.equal(gh.calls.filter((c) => c.method !== 'GET').length, 0);
  });

  test('a new holder starts a new since: the last holder\'s since does not carry over', () => {
    const theirs = relay.livingHeader({ baton: 'released', holder: `James Tiberius Kirk · ${THEM}`, since: 'THEIRS', checkpoint: 'c', head: 'fff0000', next: 'n' });
    const gh = fakeGitHub({ comments: [{ id: 9, user: { login: 'saden1' }, body: theirs, updated_at: new Date(T0 - 2 * MIN).toISOString(), html_url: 'u9' }] });
    post({ api: gh.api, git: gitHead(ME) });
    const patch = gh.calls.find((c) => c.method === 'PATCH');
    assert.match(patch.body.body, /^since: 2026-11-22T12:00:00\.000Z$/m);
    assert.match(patch.body.body, /^holder: John Luke Picard · session_ME01$/m);
  });

  test('a refresh at a head parked at the merge gate keeps it parked (released, gate kept)', () => {
    const parked = relay.setLivingLine(
      relay.livingHeader({ baton: 'released', holder: `John Luke Picard · ${ME}`, since: 'S', checkpoint: 'c', head: 'abc1234', next: 'n' }),
      'gate',
      'parked at abc1234',
    );
    const gh = fakeGitHub({ comments: [{ id: 11, user: { login: 'saden1' }, body: parked, updated_at: new Date(T0 - MIN).toISOString(), html_url: 'u11' }] });
    post({ api: gh.api, git: gitHead(ME) });
    const out = relay.parseLiving(gh.calls.find((c) => c.method === 'PATCH').body.body);
    assert.equal(out.released, true);
    assert.equal(out.gate, 'abc1234');
  });

  test('a closed PR, or no session id: refused', () => {
    assert.throws(() => post({ api: fakeGitHub({ state: 'closed' }).api, git: gitHead(ME) }), /closed/);
    assert.throws(() => post({ api: fakeGitHub().api, git: gitHead(ME), env: {} }), (e) => e.code === 64);
  });
});

describe('npm run relay', () => {
  const living = relay.livingHeader({ baton: 'held', holder: 'x', since: 's', checkpoint: 'c', head: 'h', next: 'run the trio' });
  const api = (method, p) => {
    if (p === 'user') return { login: 'saden1' };
    if (p.includes('/pulls?')) {
      return [
        { number: 1, user: { login: 'saden1' }, head: { ref: 'claude/a', sha: 'aaa' } },
        { number: 2, user: { login: 'dependabot[bot]' }, head: { ref: 'deps', sha: 'bbb' } },
        { number: 3, user: { login: 'saden1' }, head: { ref: 'claude/c', sha: 'ccc' } },
      ];
    }
    if (p.includes('issues/1/comments')) return [{ id: 1, user: { login: 'saden1' }, body: `${living}\n\n**CLAIMS**\n- test:a.test.js#b\n`, updated_at: new Date(T0 - 10 * MIN).toISOString(), html_url: 'u1' }];
    if (p.includes('issues/3/comments')) return [{ id: 3, user: { login: 'saden1' }, body: 'no marker', updated_at: new Date(T0).toISOString() }];
    if (p.includes('commits?sha=aaa&')) {
      // newest first from the tip. The tip merges main (no trailer); its SECOND parent is a side branch
      // carrying another session's trailer, which a first-parent walk must ignore.
      return [
        { sha: 'aaa', parents: [{ sha: 'mid' }, { sha: 'side' }], commit: { message: "Merge branch 'main' into claude/a", committer: { date: new Date(T0 - 21 * MIN).toISOString() } } },
        { sha: 'side', parents: [{ sha: 'base' }], commit: { message: `wip\n\nClaude-Session: https://claude.ai/code/${ME}` } },
        { sha: 'mid', parents: [{ sha: 'base' }], commit: { message: `feat: a\n\nRelay-Actor: James Tiberius Kirk\nClaude-Session: https://claude.ai/code/${THEM}` } },
        { sha: 'base', parents: [{ sha: 'older' }], commit: { message: 'feat: main squash\n\nClaude-Session: https://claude.ai/code/session_MAIN99' } },
      ];
    }
    if (p.includes('/compare/main...aaa')) return { merge_base_commit: { sha: 'base' } };
    if (p.endsWith('git/matching-refs/heads/relay-rescue/claude/a')) return [{ ref: `refs/heads/relay-rescue/claude/a/${ME}` }, { ref: 'refs/heads/relay-rescue/claude/ab/session_X' }];
    throw new Error(`unexpected ${method} ${p}`);
  };

  test('one row per PR with a living comment; bots and unmarked PRs skipped', () => {
    const lines = board.board({ api, now: T0 });
    assert.equal(lines.length, 3);
    assert.match(lines[2], /^\| \[#1\]\(u1\) \| claude\/a \| James Tiberius Kirk · session_TH02 \| held \| 10 min ago \| run the trio \| test:a\.test\.js#b \| 1 waiting \|$/);
  });

  test('a branch parked at the merge gate shows as parked on the board, not "free"', () => {
    const gated = relay.livingHeader({ baton: 'released', holder: `James Tiberius Kirk · ${THEM}`, since: 's', checkpoint: 'c', head: 'aaa0000', next: 'n' });
    const body = relay.setLivingLine(gated, 'gate', 'parked at aaa0000');
    const api2 = (method, p) => {
      if (p.includes('issues/1/comments')) return [{ id: 1, user: { login: 'saden1' }, body, updated_at: new Date(T0 - 10 * MIN).toISOString(), html_url: 'u1' }];
      if (p.includes('/pulls?')) return [{ number: 1, user: { login: 'saden1' }, head: { ref: 'claude/a', sha: 'aaa0000ffff' } }];
      if (p.includes('commits?sha=aaa0000ffff')) return [{ sha: 'aaa0000ffff', parents: [], commit: { message: `x\n\nClaude-Session: https://claude.ai/code/${THEM}`, committer: { date: new Date(T0 - 15 * MIN).toISOString() } } }];
      if (p.includes('git/matching-refs')) return [];
      return api(method, p);
    };
    const lines = board.board({ api: api2, now: T0 });
    assert.match(lines[2], /\| parked at merge gate \|/);
  });

  test('the holder walk stops at the merge base: main\'s squash trailers never name a holder', () => {
    // the branch's own commit has no trailer; the merge base (a main squash) does
    const living2 = relay.livingHeader({ baton: 'held', holder: 'x', since: 's', checkpoint: 'c', head: 'h', next: 'n' });
    const commits = [
      { sha: 'aaa', parents: [{ sha: 'base' }], commit: { message: 'docs: a person\'s web edit' } },
      { sha: 'base', parents: [{ sha: 'older' }], commit: { message: 'feat: main squash\n\nClaude-Session: https://claude.ai/code/session_MAIN99' } },
    ];
    const mk = (compare) => (method, p) => {
      if (p.includes('issues/1/comments')) return [{ id: 1, user: { login: 'saden1' }, body: living2, updated_at: new Date(T0).toISOString(), html_url: 'u1' }];
      if (p.includes('/pulls?')) return [{ number: 1, user: { login: 'saden1' }, base: { ref: 'main' }, head: { ref: 'claude/a', sha: 'aaa' } }];
      if (p.includes('commits?sha=aaa&')) return commits;
      if (p.includes('/compare/')) return compare();
      if (p.includes('git/matching-refs')) return [];
      return api(method, p);
    };
    const row = board.board({ api: mk(() => ({ merge_base_commit: { sha: 'base' } })), now: T0 })[2];
    assert.doesNotMatch(row, /session_MAIN99/);
    assert.match(row, /\| unattributed \| held \|/);
    // the merge base could not be read: the board says it cannot tell, rather than guess
    const unknown = board.board({ api: mk(() => { throw new relay.RelayError('404'); }), now: T0 })[2];
    assert.match(unknown, /\| \? \(run npm run baton -- status\) \|/);
  });

  test('trailer prints the Relay-Actor line from the roster', () => {
    const out = [];
    assert.equal(board.run(['trailer'], { env: { LATTICE_ACTOR: 'picard' }, out: (s) => out.push(s), err: () => {} }), 0);
    assert.deepEqual(out, ['Relay-Actor: John Luke Picard']);
    assert.equal(board.run(['trailer'], { env: {}, out: () => {}, err: () => {} }), 1);
  });

  test('sign prints the line, or exits 1 when it cannot', () => {
    const out = [];
    assert.equal(board.run(['sign'], { env: { LATTICE_ACTOR: 'kirk', LATTICE_SESSION: THEM }, out: (s) => out.push(s), err: () => {} }), 0);
    assert.deepEqual(out, ['— James Tiberius Kirk · session_TH02']);
    assert.equal(board.run(['sign'], { env: {}, out: () => {}, err: () => {} }), 1);
    assert.equal(board.run(['sign'], { env: { LATTICE_ACTOR: 'spock' }, out: () => {}, err: () => {} }), 1);
  });

  test('GitHub could not be read: exit 3', () => {
    const api3 = () => {
      throw new relay.RelayError('gh api failed');
    };
    assert.equal(board.run([], { api: api3, out: () => {}, err: () => {} }), 3);
  });
});

describe('npm run card -- relay: block', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'living-'));
  const yml = path.join(dir, 'card.yml');
  const base = fs.readFileSync(path.join(ROOT, 'engineering', 'card-examples', 'continuation.yml'), 'utf8');

  test('a relay: block without --living is refused, not silently dropped', () => {
    fs.writeFileSync(yml, `${base}\nrelay:\n  traps:\n    - "ci.yml skips on draft"\n`);
    const r = spawnSync(process.execPath, [path.join(ROOT, 'tools', 'card.js'), yml], { encoding: 'utf8' });
    assert.equal(r.status, 1);
    assert.match(r.stderr, /relay: is read only with --living/);
  });

  test('--check validates a relay: block, so the living card can be dry-run before posting', () => {
    fs.writeFileSync(yml, `${base}\nrelay:\n  traps:\n    - "ci.yml skips on draft"\n`);
    const ok = spawnSync(process.execPath, [path.join(ROOT, 'tools', 'card.js'), '--check', yml], { encoding: 'utf8' });
    assert.equal(ok.status, 0, ok.stderr);
    assert.match(ok.stdout, /card: OK \(continuation/);
    fs.writeFileSync(yml, `${base}\nrelay:\n  nonsense:\n    - "x"\n`);
    const bad = spawnSync(process.execPath, [path.join(ROOT, 'tools', 'card.js'), '--check', yml], { encoding: 'utf8' });
    assert.equal(bad.status, 1);
    assert.match(bad.stderr, /relay: is read only with --living/);
  });

  test('--living needs a PR number', () => {
    const r = spawnSync(process.execPath, [path.join(ROOT, 'tools', 'card.js'), '--living', 'x', yml], { encoding: 'utf8' });
    assert.equal(r.status, 2);
  });
});
