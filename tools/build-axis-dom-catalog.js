#!/usr/bin/env node
/**
 * Generates lib/runtime/axis-dom-catalog.generated.js — a plain CJS lookup
 * (component name → { axis, domSelector, soft, hard }) for every component
 * that declares a `density.axis` in its manifest, bundled into
 * dist/lattice-runtime.js so the live preview can find a component's
 * repeated-element collection — and its word budget — without shipping the
 * whole manifest catalog to the browser.
 *
 * `domSelector` is populated ONLY when a component's own manifest declares
 * one (a component whose transform retags the axis elements — e.g.
 * split-compare's options become `.option` divs, not `<li>`); otherwise it
 * is `null` and the runtime falls back to the universal per-axis default
 * (lib/core/collections.js's domItemElements/domRowElements). See
 * engineering/decisions/2026-07-10-overflow-cause-highlighting.md §10.
 *
 * `soft`/`hard` mirror the manifest's own `density.soft`/`density.hard` word
 * budget (null when a manifest omits either) — the Fix-Me overlay's Case B
 * (density-budget fallback, §12) reads them to flag the worst item on a
 * slide with no clip-cell at all.
 *
 * `NO_CASE_B` (below) nulls `soft`/`hard` for a component whose axis text is
 * NEVER the true cause of an overflow, so Case B can't fire on it even
 * though `axis`/`domSelector` still serve Case A's item-level drill-down
 * (§10) unaffected. Red-team finding (2026-07-11, post-merge adversarial
 * review of PR #892): `kanban` renders every text field CSS-truncated
 * (`.kanban-title-text{-webkit-line-clamp:2}`,
 * `.kanban-card-body{text-overflow:ellipsis}` —
 * lib/components/chart/kanban/kanban.styles.css), so a card's word count is
 * decoupled from its rendered height entirely; a genuinely overflowing
 * kanban board is a CARD-COUNT problem (`capacity`, not `density`), which
 * neither case addresses. Without this exclusion, Case B would tag some
 * card's already-invisible text as "Likely fix," misdirecting the author
 * from the real cause.
 *
 * Usage:
 *   node tools/build-axis-dom-catalog.js            regenerate
 *   node tools/build-axis-dom-catalog.js --check     freshness gate (CI)
 */

const fs = require('node:fs');
const path = require('node:path');
const { loadAll } = require('../lib/components');

const ROOT = path.join(__dirname, '..');
const OUT_FILE = path.join(ROOT, 'lib', 'runtime', 'axis-dom-catalog.generated.js');

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const silent = argv.includes('--silent') || check;

const NO_CASE_B = new Set(['kanban']);

function build() {
  const catalog = {};
  for (const m of loadAll()) {
    if (!m.density?.axis) continue;
    const eligible = !NO_CASE_B.has(m.name);
    catalog[m.name] = {
      axis: m.density.axis,
      domSelector: m.density.domSelector || null,
      soft: eligible && Number.isInteger(m.density.soft) ? m.density.soft : null,
      hard: eligible && Number.isInteger(m.density.hard) ? m.density.hard : null,
    };
  }
  const sortedNames = Object.keys(catalog).sort();
  const sorted = {};
  for (const n of sortedNames) sorted[n] = catalog[n];
  return (
    '/* Auto-generated by tools/build-axis-dom-catalog.js — DO NOT EDIT.\n' +
    '   Source: every component manifest\'s density block (lib/components/).\n' +
    '   Rebuild: node tools/build-axis-dom-catalog.js */\n' +
    'module.exports = ' + JSON.stringify(sorted, null, 2) + ';\n'
  );
}

function main() {
  const out = build();
  const entryCount = (out.match(/"axis":/g) || []).length;
  if (check) {
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : '';
    if (current !== out) {
      console.error('[build-axis-dom-catalog] STALE — run `node tools/build-axis-dom-catalog.js` and commit lib/runtime/axis-dom-catalog.generated.js');
      process.exit(1);
    }
    if (!silent) console.log('[build-axis-dom-catalog] up to date.');
    return;
  }
  fs.writeFileSync(OUT_FILE, out);
  if (!silent) console.log(`[build-axis-dom-catalog] wrote ${path.relative(ROOT, OUT_FILE)} (${entryCount} entries)`);
}

main();
