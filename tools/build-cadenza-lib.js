#!/usr/bin/env node
/**
 * Build the Cadenza library's consumable dist/ — the ESM + CJS entries + type
 * declarations that let ROOT CJS `require('@laticent/cadenza')` AND a plain
 * Node-ESM / bundler consumer `import '@laticent/cadenza'`.
 *
 *   docs/src/lib/cadenza/*.ts  (source, docs-side ESM/TS)
 *     →  docs/src/lib/cadenza/dist/index.mjs   (bundled ESM, esbuild)
 *     →  docs/src/lib/cadenza/dist/index.cjs   (bundled CJS, esbuild)
 *     →  docs/src/lib/cadenza/dist/*.d.ts      (declarations, tsc)
 *
 * WHY: Cadenza is docs-side TypeScript with no node-importable artifact, so the
 * CJS export pipeline (lib/export/*, the CLI) can't use it — which is why the
 * read-along work grew hand-mirrors of two pure functions. This build gives
 * Cadenza real library shape (see 2026-07-08-library-shape-cadenza-vetrina.md):
 * an npm-workspace package whose `exports` map sends `require` → dist/index.cjs and
 * `import` → dist/index.mjs, while docs + Vitest import the TS SOURCE through the
 * `@/lib/*` path ALIAS (not the package name) — so the docs runtime is unaffected.
 *
 * Bundler = the in-tree esbuild (engineering/capabilities.md names it the house
 * bundler); declarations = `tsc --emitDeclarationOnly` (esbuild can't emit .d.ts).
 * No new bundler dependency (HARD RULE #15).
 *
 * Flags:
 *   --check    Rebuild into a temp dir and diff the whole tree against the
 *              committed dist/. Exits 1 on drift (the freshness gate).
 *   --silent   Suppress the success log line.
 */

const esbuild = require('esbuild');
const { spawnSync } = require('node:child_process');
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');

const ROOT = path.resolve(__dirname, '..');
const LIB_DIR = path.join(ROOT, 'docs', 'src', 'lib', 'cadenza');
const DIST_DIR = path.join(LIB_DIR, 'dist');
const ENTRY = path.join(LIB_DIR, 'index.ts');
const TSC = path.join(ROOT, 'node_modules', '.bin', 'tsc');

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const silent = argv.includes('--silent') || check;

const CJS_BANNER =
  '/* Auto-generated by tools/build-cadenza-lib.js — DO NOT EDIT.\n' +
  '   Source: docs/src/lib/cadenza/*.ts. Rebuild: npm run cadenza-lib:build */';

/** The non-test source files whose declarations we emit (tests never ship). */
function sourceFiles() {
  return fs
    .readdirSync(LIB_DIR)
    .filter(
      (f) =>
        (f.endsWith('.ts') || f.endsWith('.tsx')) && !f.endsWith('.test.ts') && !f.endsWith('.d.ts'),
    )
    .sort()
    .map((f) => path.join(LIB_DIR, f));
}

// Both module formats: CJS (`require` condition -> dist/index.cjs) + ESM
// (`import`/`module` condition -> dist/index.mjs). Emitting a real .mjs is what makes
// `import '@laticent/cadenza'` resolve for a plain Node-ESM / non-TS-bundler consumer —
// the `import` condition used to point at raw ./index.ts and crashed with a TS extension.
const FORMATS = [
  { format: 'cjs', ext: 'cjs' },
  { format: 'esm', ext: 'mjs' },
];

/** Bundle the barrel into a CJS + an ESM file (zero-dep → everything inlines). */
async function buildBundles(outDir) {
  for (const { format, ext } of FORMATS) {
    await esbuild.build({
      entryPoints: [ENTRY],
      outfile: path.join(outDir, `index.${ext}`),
      bundle: true,
      format,
      platform: 'node',
      target: ['node18'],
      minify: false, // committed, human-readable source
      legalComments: 'none',
      // Pin the TS config INLINE so esbuild never auto-discovers docs/tsconfig.json
      // walking up from the entry. That ambient config `extends astro/tsconfigs/strict`,
      // which resolves in some environments and not others (astro is a docs-only dep) —
      // making the emitted bytes environment-dependent and flapping the freshness gate
      // in CI. An empty raw config makes the output deterministic everywhere.
      tsconfigRaw: '{}',
      banner: { js: CJS_BANNER },
    });
  }
}

/** Emit .d.ts for every non-test source via tsc (no JS, declarations only). */
function buildTypes(outDir) {
  const r = spawnSync(
    TSC,
    [
      '--declaration',
      '--emitDeclarationOnly',
      '--outDir',
      outDir,
      '--rootDir',
      LIB_DIR,
      '--module',
      'esnext',
      '--moduleResolution',
      'bundler',
      '--target',
      'es2022',
      '--strict',
      '--skipLibCheck',
      ...sourceFiles(),
    ],
    { cwd: ROOT, stdio: 'inherit' },
  );
  if (r.status !== 0) throw new Error('tsc declaration emit failed');
}

/** Build both artifacts into `outDir` (esbuild CJS + tsc declarations). */
async function buildInto(outDir) {
  fs.mkdirSync(outDir, { recursive: true });
  await buildBundles(outDir);
  buildTypes(outDir);
}

/**
 * Every file under `dir` as [relPath → contents], recursing subdirs. dist/ is
 * flat today, but recursing means a future nested emit can't slip past the
 * freshness diff as a silent false-negative.
 */
function readTree(dir, base = dir) {
  const out = new Map();
  if (!fs.existsSync(dir)) return out;
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) {
      for (const [rel, contents] of readTree(full, base)) out.set(rel, contents);
    } else {
      out.set(path.relative(base, full), fs.readFileSync(full, 'utf8'));
    }
  }
  return out;
}

function diffTrees(want, have) {
  const drift = [];
  for (const [name, contents] of want) {
    if (!have.has(name)) drift.push(`missing: ${name}`);
    else if (have.get(name) !== contents) drift.push(`changed: ${name}`);
  }
  for (const name of have.keys()) if (!want.has(name)) drift.push(`extra: ${name}`);
  return drift;
}

// The staging directory is HIDDEN (leading dot) so a half-written tree is invisible to the
// repo's source walkers while it exists. `tools/check-ownership.js`'s `listSourceFiles`
// skips dot-prefixed entries, `listFilesByExt` already did, and git ignores the pattern —
// without that, a gate running alongside a build walked into the staging tree and died on a
// `.d.ts` that was being written (#2117). The pid suffix is what makes concurrent builds
// safe; see the staging comment in `main`.
const STAGING_PREFIX = '.dist.tmp-';

/**
 * Remove staging directories left behind by a builder that died before its `finally` —
 * Ctrl-C (SIGINT terminates without unwinding), a SIGKILL, a container teardown.
 *
 * A directory is removed ONLY when the pid in its name is gone, so a CONCURRENT build's
 * working directory is never touched. That is the whole reason the staging path is
 * pid-named rather than randomly named: a random name is equally collision-free and
 * completely unsweepable, because nothing can tell an abandoned one from a live one.
 *
 * EPERM means the pid exists but belongs to someone else — alive, so leave it.
 *
 * THE LIVENESS TEST IS SCOPED TO ONE PID NAMESPACE, which is the assumption to check if this
 * ever runs somewhere unusual. Two containers sharing a bind-mounted checkout have separate
 * pid spaces, so both can hold `.dist.tmp-1234` and each would read the other's as dead. The
 * repo's own workflows — a local checkout, a CI runner, one dev container — all build inside
 * a single namespace, where the test is exact. A suffix that is not a positive integer is
 * never swept, which is the safe direction: it is left, not deleted.
 */
function sweepStaleStaging() {
  const parent = path.dirname(DIST_DIR);
  const prefix = STAGING_PREFIX;
  let entries;
  try {
    entries = fs.readdirSync(parent);
  } catch {
    return; // no parent yet — nothing to sweep
  }
  for (const name of entries) {
    if (!name.startsWith(prefix)) continue;
    const pid = Number(name.slice(prefix.length));
    if (!Number.isInteger(pid) || pid <= 0 || pid === process.pid) continue;
    try {
      process.kill(pid, 0);
      continue; // still running
    } catch (e) {
      if (e.code === 'EPERM') continue; // exists, not ours
    }
    fs.rmSync(path.join(parent, name), { recursive: true, force: true });
  }
}

/**
 * Swap a finished staging tree into place, tolerating a CONCURRENT run of this same
 * builder installing first.
 *
 * The swap is `rm` then `rename`, and those two calls are not one step: with pid-unique
 * staging the two runs no longer corrupt each other's WORK, but they still both aim at
 * one destination, and a run that removed `dist/` and then found it repopulated died on
 * `ENOTEMPTY: rmdir dist`. Measured at 1 failure in 24 runs of a 12-round concurrent
 * pair — better than the 3 in 16 the fixed staging path gave, and still a flake.
 *
 * The resolution is that a LOSS here is not a failure. This build is deterministic, so
 * the tree the winner installed is byte-for-byte the tree we staged; if what is on disk
 * matches what we built, the job is done and whose rename landed it is not interesting.
 * Anything else rethrows, so a real failure (a full disk, a permission change) still
 * reports. Bounded retries rather than a lock: a lockfile needs a stale-lock policy, and
 * this needs none.
 */
function installStaging(staging) {
  const want = readTree(staging);
  for (let attempt = 0; ; attempt++) {
    try {
      fs.rmSync(DIST_DIR, { recursive: true, force: true });
      fs.renameSync(staging, DIST_DIR);
      return;
    } catch (e) {
      let installed;
      try {
        installed = readTree(DIST_DIR);
      } catch {
        installed = null; // mid-swap by the other run — not equal, so retry
      }
      // ONE comparison, not two: `diffTrees` already reports `extra:` for a key present in
      // `have` and missing from `want`, so it is symmetric by construction.
      if (installed && !diffTrees(want, installed).length) return;
      if (attempt >= 4 || !fs.existsSync(staging)) throw e;
    }
  }
}

async function main() {
  if (check) {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'cadenza-lib-'));
    try {
      await buildInto(tmp);
      const drift = diffTrees(readTree(tmp), readTree(DIST_DIR));
      if (drift.length) {
        console.error(
          '[build-cadenza-lib] STALE — run `npm run cadenza-lib:build` and commit docs/src/lib/cadenza/dist:\n  ' +
            drift.join('\n  '),
        );
        process.exit(1);
      }
      if (!silent) console.log('[build-cadenza-lib] up to date.');
    } finally {
      fs.rmSync(tmp, { recursive: true, force: true });
    }
    return;
  }

  // Build into a sibling temp dir and swap in only on success — a failed build
  // (e.g. a source type error) must never leave the committed dist/ deleted.
  // Sibling (not os.tmpdir()) keeps the rename on one filesystem (no EXDEV).
  //
  // The pid SUFFIX is what makes two concurrent runs of this builder safe (#2117). The
  // path used to be a fixed `dist.tmp`, so a second run's opening `rmSync` — or the
  // first's `finally` — deleted the tree the other was mid-write into, and the loser
  // died on `ENOENT: …/dist.tmp/builder.d.ts`. It reads as a genuine failure and it is
  // green on a re-run, which is the worst shape a flake can have. `npm run build` runs
  // the four library builders in the background, so a build overlapping a test run is
  // enough to hit it.
  //
  // A pid is unique among LIVE processes, which is the property this needs, and unlike
  // `mkdtempSync` it stays sweepable: `sweepStaleStaging` can tell a dead run's leftovers
  // from a live run's working directory. That matters because a `finally` does not run on
  // SIGINT — Ctrl-C during a build used to leak a staging dir that the next run's fixed-path
  // `rmSync` happened to clean, and a unique random name would have dropped that property.
  const staging = path.join(path.dirname(DIST_DIR), `${STAGING_PREFIX}${process.pid}`);
  sweepStaleStaging();
  fs.rmSync(staging, { recursive: true, force: true }); // a REUSED pid's leftovers
  try {
    await buildInto(staging);
    installStaging(staging);
  } finally {
    fs.rmSync(staging, { recursive: true, force: true });
  }
  if (!silent) {
    const files = [...readTree(DIST_DIR).keys()];
    console.log(`[build-cadenza-lib] wrote ${path.relative(ROOT, DIST_DIR)}/ (${files.join(', ')})`);
  }
}

main().catch((e) => {
  console.error('[build-cadenza-lib] failed:', e.message);
  process.exit(1);
});
