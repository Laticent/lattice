#!/usr/bin/env node
/**
 * Build the callout placer as a self-contained IIFE string, for the export's serialized bootstrap.
 *
 *   lib/components/chart/_chart-family/callout-browser.js   (the one placer)
 *     -> lib/core/callout-browser-bundle.generated.js       exports CALLOUT_BROWSER_IIFE
 *
 * WHY. A flowchart or state chart is laid out in the browser, so its callout notes are placed there too
 * (callout-browser.js). The Studio's runtime bundles that module through `require`. The CLI export cannot:
 * it embeds the Trama pass with `fn.toString()`, so a chart's pass closes over nothing and a page it runs
 * in has no modules. This is the same placer as source, set on `globalThis.__latticeCalloutPlace` before
 * the pass runs, and `lattice.js` embeds it only for a deck that has a flowchart or state chart WITH
 * callouts, so every other export stays the size it was. Same shape as tools/build-dagre-bundle.js.
 *
 * OUTPUT IS GENERATED, NOT COMMITTED (engineering/decisions/2026-08-17-generated-bundles-uncommitted.md).
 * `prepare` builds it, so a fresh clone and `npm publish` both have it.
 *
 * Flags: --check  fail when the file on disk is not what a build would write.
 */
const path = require('path');
const fs = require('fs');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'lib', 'core', 'callout-browser-bundle.generated.js');
const PLACER = path.join(ROOT, 'lib', 'components', 'chart', '_chart-family', 'callout-browser.js');
const ENTRY = path.join(ROOT, '.callout-browser-entry.tmp.mjs');

function build({ check = false } = {}) {
  fs.writeFileSync(ENTRY, `import { placeCallouts } from ${JSON.stringify(PLACER)};\nglobalThis.__latticeCalloutPlace = placeCallouts;\n`);
  let iife;
  try {
    iife = require('esbuild').buildSync({
      entryPoints: [ENTRY],
      bundle: true,
      minify: true,
      format: 'iife',
      platform: 'browser',
      target: ['chrome109'],
      logLevel: 'error',
      write: false,
      absWorkingDir: ROOT,
    }).outputFiles[0].text;
  } finally {
    fs.rmSync(ENTRY, { force: true });
  }
  const out =
    '/* Auto-generated by tools/build-callout-browser.js — DO NOT EDIT.\n' +
    '   Source: lib/components/chart/_chart-family/callout-browser.js\n' +
    '   Rebuild: node tools/build-callout-browser.js\n' +
    '   SPDX-License-Identifier: AGPL-3.0-only\n*/\n' +
    `module.exports = { CALLOUT_BROWSER_IIFE: ${JSON.stringify(iife)} };\n`;
  if (check) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== out) {
      console.error('callout-browser bundle STALE — run `node tools/build-callout-browser.js`');
      process.exit(1);
    }
    console.log(`callout-browser bundle OK — ${(iife.length / 1024).toFixed(1)} KB IIFE.`);
    return;
  }
  fs.writeFileSync(OUT, out);
  console.log(`[build-callout-browser] lib/core/callout-browser-bundle.generated.js (${(iife.length / 1024).toFixed(1)} KB IIFE)`);
}

if (require.main === module) build({ check: process.argv.includes('--check') });
module.exports = { build, OUT };
