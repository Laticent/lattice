#!/usr/bin/env node
/**
 * Build the Cenno library's consumable dist/: the ESM + CJS entries + type declarations that make
 * it a publishable unit (engineering/decisions/2026-11-16-cenno-popover-library.md).
 *   docs/src/lib/cenno/*.ts  →  dist/index.{mjs,cjs} + dist/*.d.ts
 * One entrypoint, the framework-free core. Cenno has no dependencies; Lattice's chart reveal lives
 * outside the package (lib/runtime/chart-reveal) and is not part of this build.
 * Flags:
 *   --check    Rebuild into a temp dir and diff against dist/. Exits 1 on drift.
 *   --silent   Suppress the success log line.
 */

const { defineLibraryBuild } = require('./lib/build-workspace-lib.js');

defineLibraryBuild({
  name: 'cenno',
  entries: [{ entry: 'index.ts', out: 'index' }],
  banner: (entry) => `/* Auto-generated by tools/build-cenno-lib.js — DO NOT EDIT.\n   Source: docs/src/lib/cenno/${entry}. Rebuild: npm run cenno-lib:build */`,
  platform: 'browser',
}).run();
