#!/usr/bin/env node
/**
 * Write Cenno's per-module size table into its README, or `--check` that the table is current.
 *
 * Cenno has no byte budget. Instead every module states what it buys and what it costs
 * (engineering/decisions/2026-11-16-cenno-popover-library.md §6), and this table is that record:
 * each module minified on its own (its sibling imports kept external, so a row is that module's
 * own code), plus the whole library as one bundle. A PR that grows a row says why in its body.
 *
 * Minified bytes come from the pinned esbuild and are compared exactly. Gzip bytes depend on the
 * zlib Node ships, which can move between Node versions, so `--check` allows 0.1 KB of drift there.
 *
 * Flags:
 *   --check    Exit 1 if the README's table is stale.
 *   --silent   Suppress the success log line.
 */

const esbuild = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');

const DIR = path.join(__dirname, '..', 'docs', 'src', 'lib', 'cenno');
const README = path.join(DIR, 'README.md');
const START = '<!-- cenno-sizes:start (generated by tools/build-cenno-sizes.js; npm run build) -->';
const END = '<!-- cenno-sizes:end -->';

/** Every module, with the job that earns its bytes. */
const MODULES = [
  ['place.ts', 'Where the card goes: flip, shift, size, arrow, hide. Pure arithmetic.'],
  ['measure.ts', 'Reads anchors (elements, points, iframes at any depth), the visual viewport and clipping ancestors.'],
  ['cenno.ts', 'Opens, moves and closes cards: top layer, fullscreen, steady size under pinch, tracking.'],
  ['intent.ts', 'Hover with a grace corridor, focus, press, Escape, outside press, the ARIA wiring.'],
  ['card.ts', 'The optional anatomy (header, body, footer) and the part names.'],
  ['styles.ts', 'The one stylesheet: tokens with system-color fallbacks.'],
];

function measure(entry, external) {
  const out = esbuild.buildSync({
    entryPoints: [path.join(DIR, entry)],
    bundle: true,
    minify: true,
    format: 'esm',
    write: false,
    logLevel: 'silent',
    external: external ? ['./*'] : [],
  }).outputFiles[0].contents;
  return { min: out.length, gz: zlib.gzipSync(out, { level: 9 }).length };
}

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;

function table() {
  const rows = MODULES.map(([file, job]) => ({ file, job, ...measure(file, true) }));
  const total = measure('index.ts', false);
  const lines = [
    START,
    '| Module | What it buys | Minified | Gzip |',
    '|---|---|---:|---:|',
    ...rows.map((r) => `| \`${r.file}\` | ${r.job} | ${r.min} B | ${kb(r.gz)} |`),
    `| **All of it** | One bundle of \`index.ts\` | **${total.min} B** | **${kb(total.gz)}** |`,
    END,
  ];
  return { text: lines.join('\n'), rows, total };
}

function parse(block) {
  const out = new Map();
  for (const m of block.matchAll(/^\| (?:`([^`]+)`|\*\*All of it\*\*) \|.*\| \**(\d+) B\** \| \**([\d.]+) KB\** \|$/gm)) {
    out.set(m[1] ?? 'total', { min: Number(m[2]), gz: Number(m[3]) });
  }
  return out;
}

function main() {
  const check = process.argv.includes('--check');
  const silent = process.argv.includes('--silent');
  const readme = fs.readFileSync(README, 'utf8');
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) {
    console.error(`[build-cenno-sizes] ${path.relative(process.cwd(), README)} has no size-table markers (${START} … ${END}).`);
    process.exit(1);
  }
  const fresh = table();
  if (check) {
    const old = parse(readme.slice(a, b + END.length));
    const want = new Map([...fresh.rows.map((r) => [r.file, r]), ['total', fresh.total]]);
    const stale = [];
    for (const [k, v] of want) {
      const o = old.get(k);
      if (!o || o.min !== v.min || Math.abs(o.gz - Number((v.gz / 1024).toFixed(1))) > 0.1 + 1e-9) stale.push(k);
    }
    if (old.size !== want.size) stale.push('(row set)');
    if (stale.length) {
      console.error(`[build-cenno-sizes] the size table in docs/src/lib/cenno/README.md is stale (${stale.join(', ')}). Run: npm run build`);
      process.exit(1);
    }
    if (!silent) console.log('[build-cenno-sizes] size table current.');
    return;
  }
  const next = readme.slice(0, a) + fresh.text + readme.slice(b + END.length);
  if (next !== readme) fs.writeFileSync(README, next);
  if (!silent) console.log(`[build-cenno-sizes] ${fresh.total.min} B minified, ${kb(fresh.total.gz)} gzip.`);
}

main();
