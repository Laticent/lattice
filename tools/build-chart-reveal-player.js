#!/usr/bin/env node
/**
 * Bundle the chart reveal (lib/runtime/chart-reveal/reveal.mjs + its model + @laticent/cenno) into ONE
 * self-contained IIFE string, for injection into the exported `.html` player
 * (engineering/decisions/2026-11-16-cenno-popover-library.md §7).
 *
 *   lib/runtime/chart-reveal/reveal.mjs (+ model.mjs, + docs/src/lib/cenno from SOURCE)
 *     →  lib/export/chart-reveal-player-bundle.generated.mjs
 *        (`export const CHART_REVEAL_JS = "<iife source>"`)
 *
 * WHY a string constant: the player's runtime is CSP-hashed inline script assembled by
 * `player-core.mjs` and cannot `import`. `player-core` injects this string AHEAD of the player script,
 * the way the narration Guide rides, and ONLY when the deck carries a chart detail
 * (`<template class="chart-detail"`), so a deck without one stays byte-identical (the html-player
 * golden). The IIFE exposes `window.__latticeReveal.mount(host)`; the player calls it from inside its
 * own scope, handing over its stage, the slide on stage and its two-finger guard.
 *
 * reveal.mjs takes Cenno's factory as a parameter (it lives in the shipped lib/, which may load no package
 * the published engine does not install), so this ENTRY is the one place that imports Cenno. It is resolved
 * from SOURCE (the `@laticent/source` export condition), so the bundle never depends
 * on a built, gitignored dist/.
 *
 * Flags: --check (freshness gate, exit 1 on drift), --silent.
 */

const esbuild = require('esbuild');
const path = require('node:path');
const fs = require('node:fs');

const ROOT = path.resolve(__dirname, '..');
const REVEAL_DIR = path.join(ROOT, 'lib', 'runtime', 'chart-reveal');
const OUT_FILE = path.join(ROOT, 'lib', 'export', 'chart-reveal-player-bundle.generated.mjs');

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const silent = argv.includes('--silent') || check;

const ENTRY = `
import { createCenno } from '@laticent/cenno';
import { createChartReveal } from './reveal.mjs';
window.__latticeReveal = { mount: (host) => createChartReveal({ ...host, createCenno }) };
`;

const BUILD_OPTIONS = {
  stdin: { contents: ENTRY, resolveDir: REVEAL_DIR, loader: 'js', sourcefile: 'chart-reveal-player.entry.js' },
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome109', 'safari16', 'firefox115'],
  conditions: ['@laticent/source'],
  minify: true, // the player embeds this verbatim; keep the export small
  legalComments: 'none',
};

async function main() {
  const result = await esbuild.build({ ...BUILD_OPTIONS, write: false });
  const iife = result.outputFiles[0].text;
  const out =
    '// Auto-generated by tools/build-chart-reveal-player.js — DO NOT EDIT.\n' +
    '// Sources: lib/runtime/chart-reveal/reveal.mjs + model.mjs, and docs/src/lib/cenno (from source).\n' +
    '// Rebuild: npm run chart-reveal-player:build\n' +
    `export const CHART_REVEAL_JS = ${JSON.stringify(iife)};\n`;
  if (check) {
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : '';
    if (current !== out) {
      console.error('[build-chart-reveal-player] STALE — run `npm run chart-reveal-player:build` and commit lib/export/chart-reveal-player-bundle.generated.mjs');
      process.exit(1);
    }
    if (!silent) console.log('[build-chart-reveal-player] up to date.');
    return;
  }
  if (!fs.existsSync(OUT_FILE) || fs.readFileSync(OUT_FILE, 'utf8') !== out) fs.writeFileSync(OUT_FILE, out);
  if (!silent) console.log(`[build-chart-reveal-player] wrote ${path.relative(ROOT, OUT_FILE)} (${(iife.length / 1024).toFixed(1)} KB IIFE).`);
}

main().catch((err) => {
  console.error('[build-chart-reveal-player]', err);
  process.exit(1);
});
