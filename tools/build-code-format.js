#!/usr/bin/env node
/**
 * tools/build-code-format.js — the code formatter's BROWSER build: its entry and one chunk per
 * formatter, for the Studio to load when the author formats (docs/src/lib/ensure-code-format.ts).
 *
 *   lib/authoring/code-format/browser.mjs        →  docs/public/playground/fmt/browser.mjs
 *   each `import()` in adapters.mjs               →  docs/public/playground/fmt/chunk-*.mjs
 *   the formatters' WebAssembly                   →  docs/public/playground/fmt/*.wasm
 *
 * ESM with code splitting, so the entry is small and a deck fetches only the chunk for the language
 * it formats (engineering/decisions/2026-10-15-code-plugin.md §6). The WebAssembly files are copied
 * beside the chunks: ruff's is located by the entry's `wasmUrl`, and the Java plugin's by
 * `new URL(…, import.meta.url)` inside its chunk, which resolves to this same directory.
 *
 * Built, not committed (docs/public/playground/ is gitignored, 2026-08-17-generated-bundles-
 * uncommitted.md); docs/scripts/sync-playground-assets.mjs stages the directory beside the engine.
 *
 *   node tools/build-code-format.js           build
 *   node tools/build-code-format.js --check   exit 1 if the built files differ from a fresh build
 */

const esbuild = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const ENTRY = path.join(ROOT, 'lib', 'authoring', 'code-format', 'browser.mjs');
const OUT_DIR = path.join(ROOT, 'docs', 'public', 'playground', 'fmt');
const check = process.argv.includes('--check');
const silent = process.argv.includes('--silent') || check;

/** The WebAssembly the formatters load at run time, by the name their code asks for. */
const WASM = Object.freeze([
  ['ruff_fmt_bg.wasm', path.join(ROOT, 'node_modules', '@wasm-fmt', 'ruff_fmt', 'ruff_fmt_bg.wasm')],
  ['tree-sitter-java_orchard.wasm', path.join(ROOT, 'node_modules', 'prettier-plugin-java', 'dist', 'tree-sitter-java_orchard.wasm')],
  ['web-tree-sitter.wasm', path.join(ROOT, 'node_modules', 'web-tree-sitter', 'web-tree-sitter.wasm')],
]);

/** ruff's package resolves to a build that imports its .wasm as a module; the browser takes the web build. */
const ruffWebPlugin = {
  name: 'ruff-web',
  setup(build) {
    build.onResolve({ filter: /^@wasm-fmt\/ruff_fmt$/ }, () => ({ path: path.join(ROOT, 'node_modules', '@wasm-fmt', 'ruff_fmt', 'ruff_fmt_web.js') }));
  },
};

/**
 * The PHP plugin's UMD wrapper names `fs` and `path` in its CommonJS branch. It calls them only to
 * find composer.json when `phpVersion` is "auto", and the adapter pins the version
 * (lib/authoring/code-format/adapters.mjs PHP_VERSION), so neither runs. Each resolves to an empty
 * module, and the browser test formats a PHP block to prove it (docs/e2e/code-format.spec.ts).
 */
const nodeBuiltinStubPlugin = {
  name: 'node-builtin-stub',
  setup(build) {
    build.onResolve({ filter: /^(fs|path)$/ }, (args) => ({ path: args.path, namespace: 'node-stub' }));
    build.onLoad({ filter: /.*/, namespace: 'node-stub' }, () => ({ contents: 'module.exports = {};', loader: 'js' }));
  },
};

async function buildAll() {
  const result = await esbuild.build({
    entryPoints: { browser: ENTRY },
    bundle: true,
    splitting: true,
    format: 'esm',
    platform: 'browser',
    target: ['chrome109'],
    minify: true,
    legalComments: 'none',
    outdir: OUT_DIR,
    outExtension: { '.js': '.mjs' },
    chunkNames: 'chunk-[hash]',
    plugins: [ruffWebPlugin, nodeBuiltinStubPlugin],
    write: false,
    logLevel: 'silent',
    banner: { js: '/* Auto-generated by tools/build-code-format.js — DO NOT EDIT. Source: lib/authoring/code-format/. */' },
  });
  const files = new Map();
  for (const f of result.outputFiles) files.set(path.basename(f.path), Buffer.from(f.contents));
  for (const [name, from] of WASM) {
    if (!fs.existsSync(from)) throw new Error(`build-code-format: ${path.relative(ROOT, from)} is missing (npm ci?)`);
    files.set(name, fs.readFileSync(from));
  }
  return files;
}

async function main() {
  const built = await buildAll();
  if (check) {
    const current = fs.existsSync(OUT_DIR) ? fs.readdirSync(OUT_DIR) : [];
    const stale = current.length !== built.size || [...built].some(([n, b]) => !fs.existsSync(path.join(OUT_DIR, n)) || !fs.readFileSync(path.join(OUT_DIR, n)).equals(b));
    if (stale) {
      process.stderr.write('[build-code-format] STALE — run `node tools/build-code-format.js`\n');
      process.exit(1);
    }
    return;
  }
  // Rewrite the whole directory, so a chunk a rebuild renamed does not linger.
  fs.rmSync(OUT_DIR, { recursive: true, force: true });
  fs.mkdirSync(OUT_DIR, { recursive: true });
  let bytes = 0;
  for (const [name, buf] of built) {
    fs.writeFileSync(path.join(OUT_DIR, name), buf);
    bytes += buf.length;
  }
  if (!silent) process.stdout.write(`[build-code-format] ${built.size} files → ${path.relative(ROOT, OUT_DIR)}/ (${(bytes / 1024).toFixed(0)} KB)\n`);
}

main().catch((e) => {
  process.stderr.write(`[build-code-format] failed: ${e.message}\n`);
  process.exit(1);
});
