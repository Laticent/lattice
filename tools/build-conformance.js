#!/usr/bin/env node
/**
 * build-conformance.js — generate dist/engineering/conformance.md: what each kind of thing owes,
 * and the live matrix of every instance against every clause.
 *
 * The checklist is GENERATED from the contracts in lib/conformance/kinds/, never written by hand,
 * so it cannot claim a check that does not run (engineering/decisions/2026-10-15-conformance-harness.md
 * §6.1). One section per kind: its clauses (level, what it applies to, what it caught, the doc
 * behind it), then a table with a row per instance and a column per clause, each cell pass (✓),
 * fail (✗), not applicable (–) or known debt (D).
 *
 * Written to dist/ and NOT committed, like the other generated indexes
 * (engineering/decisions/2026-10-09-generated-indexes-uncommitted.md). `npm test` runs the same
 * contracts as a gate (test/unit/conformance/static.test.js); this file is the page a person reads.
 *
 * Usage:
 *   node tools/build-conformance.js          # write dist/engineering/conformance.md
 *   node tools/build-conformance.js --check  # validate every contract's SHAPE; exit 1 on a problem
 */
const fs = require('node:fs');
const path = require('node:path');
const { loadContracts, runContract, readLedger, contractProblems } = require('../lib/conformance');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'dist', 'engineering', 'conformance.md');
const MARK = { pass: '✓', fail: '✗', 'n/a': '–', debt: 'D' };
const cell = (s) => String(s).replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\n/g, ' ');

function render() {
  const ledger = readLedger();
  const lines = [
    '# Conformance — what each kind owes, and where it stands',
    '',
    '<!-- GENERATED by tools/build-conformance.js from lib/conformance/kinds/*.contract.js — do not edit. -->',
    '',
    'One checklist per kind of thing, written once in code (`lib/conformance/kinds/`). Each contract finds its own',
    'instances, so a new one is checked because it exists, not because someone listed it. Design and rules:',
    '`engineering/decisions/2026-10-15-conformance-harness.md` §6. `npm test` runs every static clause',
    '(`test/unit/conformance/static.test.js`); known failures live in `test/conformance/debt.json` with a reason.',
    '',
    `Cells: ${Object.entries(MARK).map(([k, v]) => `${v} ${k}`).join(' · ')}.`,
    '',
  ];
  for (const c of loadContracts()) {
    const run = runContract(c, { ledger });
    const counts = { pass: 0, fail: 0, 'n/a': 0, debt: 0 };
    for (const x of run.cells) counts[x.verdict]++;
    lines.push(`## ${c.title || c.kind} (\`${c.kind}\`) — ${run.instances.length} instances`, '', c.summary || '', '');
    lines.push(`${counts.pass} pass · ${counts.fail} fail · ${counts.debt} debt · ${counts['n/a']} not applicable.`, '');
    if (run.problems.length) lines.push('**Contract problems:**', '', ...run.problems.map((p) => `- ${cell(p)}`), '');
    lines.push('| Clause | Level | Reached | Caught | Why |', '|---|---|---|---|---|');
    for (const cl of c.clauses) {
      const caught = cl.catches.length ? cl.catches.join('; ') : `none — ${cl.catchesNone}`;
      lines.push(`| \`${cl.id}\` | ${cl.level} | ${run.reach[cl.id] ?? 0} | ${cell(caught)} | ${cell(cl.why)} |`);
    }
    lines.push('');
    const short = c.clauses.map((cl) => cl.id.slice(c.kind.length + 1));
    lines.push(`| ${c.kind} | ${short.join(' | ')} |`, `|---|${short.map(() => ':-:').join('|')}|`);
    const byInstance = new Map();
    for (const x of run.cells) {
      if (!byInstance.has(x.instance)) byInstance.set(x.instance, {});
      byInstance.get(x.instance)[x.clause] = x;
    }
    for (const [inst, row] of byInstance) {
      lines.push(`| \`${cell(inst)}\` | ${c.clauses.map((cl) => MARK[row[cl.id]?.verdict] ?? '').join(' | ')} |`);
    }
    const failing = run.cells.filter((x) => x.verdict === 'fail' || x.verdict === 'debt');
    if (failing.length) lines.push('', '**Failing and debt cells:**', '', ...failing.map((x) => `- \`${x.clause}\` × \`${x.instance}\` (${x.verdict}): ${cell(x.reason)}`));
    lines.push('');
  }
  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

function main() {
  if (process.argv.includes('--check')) {
    const problems = loadContracts().flatMap((c) => contractProblems(c));
    if (problems.length) {
      process.stderr.write(`conformance: ${problems.length} contract problem(s):\n${problems.map((p) => `  ${p}`).join('\n')}\n`);
      process.exit(1);
    }
    process.stdout.write('conformance: every contract is well-formed.\n');
    return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, render());
  process.stdout.write(`wrote ${path.relative(ROOT, OUT)}\n`);
}

if (require.main === module) main();

module.exports = { render };
