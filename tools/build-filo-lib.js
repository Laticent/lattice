#!/usr/bin/env node
/**
 * Build the Filo library's consumable dist/ — the ESM + CJS entry + type declarations that
 * make it a publishable unit (engineering/decisions/2026-10-27-filo-undo-history.md §8).
 *   docs/src/lib/filo/*.ts  →  dist/index.{mjs,cjs} + dist/*.d.ts
 * Veduta's recipe (tools/build-veduta-lib.js) with ONE entrypoint: Filo is a framework-free,
 * dependency-free core that knows only text. The `./react` adapter (`useHistory`) the decision
 * note names is not built yet; add `react.ts` here the day it exists. Publishing waits for
 * slices 3 and 4 to be in use (§8).
 * Flags:
 *   --check    Rebuild into a temp dir and diff against dist/. Exits 1 on drift.
 *   --silent   Suppress the success log line.
 */

const { defineLibraryBuild } = require('./lib/build-workspace-lib.js');

defineLibraryBuild({
  name: 'filo',
  entries: [{ entry: 'index.ts', out: 'index' }],
  external: [],
  banner: (entry) => `/* Auto-generated by tools/build-filo-lib.js — DO NOT EDIT.\n   Source: docs/src/lib/filo/${entry}. Rebuild: npm run filo-lib:build */`,
  platform: 'browser',
}).run();
