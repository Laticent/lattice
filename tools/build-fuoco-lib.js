#!/usr/bin/env node
/**
 * Build the Fuoco library's consumable dist/ — the ESM + CJS entries + type declarations that
 * make it a publishable unit (engineering/decisions/2026-10-15-fuoco-focus-sync.md).
 *   docs/src/lib/fuoco/*.ts  →  dist/index.{mjs,cjs} + dist/react.{mjs,cjs} + dist/*.d.ts
 * Vetrina's recipe (tools/build-vetrina-lib.js): two entrypoints, the framework-free core (`.`)
 * and the React adapter (`./react`), with react a peer dependency kept external. Fuoco has no
 * dependencies of its own; Lattice's deck outliner lives outside the package
 * (docs/src/lib/deck-outline) and is not part of this build.
 * Flags:
 *   --check    Rebuild into a temp dir and diff against dist/. Exits 1 on drift.
 *   --silent   Suppress the success log line.
 */

const { defineLibraryBuild } = require('./lib/build-workspace-lib.js');

defineLibraryBuild({
  name: 'fuoco',
  entries: [
    { entry: 'index.ts', out: 'index' },
    { entry: 'react.ts', out: 'react' },
  ],
  external: ['react', 'react-dom'],
  banner: (entry) => `/* Auto-generated by tools/build-fuoco-lib.js — DO NOT EDIT.\n   Source: docs/src/lib/fuoco/${entry}. Rebuild: npm run fuoco-lib:build */`,
  platform: 'browser',
}).run();
