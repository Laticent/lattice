#!/usr/bin/env node

/**
 * build-gotchas-index.js — generate dist/engineering/gotchas.md from engineering/gotchas/ headings.
 *
 * Why this exists: gotchas.md was ONE 290 KB file (75k tokens, measured) that told its
 * reader, in its own opening line, to "read top-to-bottom when something breaks."
 * CLAUDE.md routes here on the single most common trigger there is — something
 * behaving strangely — so the cheapest question in the repo cost more context than
 * the change that prompted it, and the honest alternative was to grep blind.
 *
 * The split: ~150 entries live in 14 topic files; this file's index is one line per
 * entry (~7k tokens), linking straight to the entry. Skim or grep the index, open
 * the ONE topic file it names. (Deliberately approximate — an exact count in a
 * comment is a number nothing regenerates, and it is wrong the next time someone
 * adds a gotcha.)
 *
 * The index is GENERATED because a hand-maintained one drifts, and a stale map is
 * worse than no map: it misdirects confidently and the reader pays for the wrong
 * file anyway. The topic files are the source of truth; this renders them.
 *
 * It is written to dist/engineering/gotchas.md and NOT committed. Built from every topic file,
 * a committed copy is a file every gotcha-adding PR rewrites, which is what the weakened
 * `--check` this file used to carry (#1547) existed to survive. `npm install` (prepare),
 * the SessionStart hook and `npm run build` write it instead. engineering/gotchas.md is
 * now only the hand-written guide that points here.
 * Record: engineering/decisions/2026-10-09-generated-indexes-uncommitted.md.
 *
 * A topic file is:
 *   # Gotchas — <Topic title>        <- the h1 titles the group in the index
 *   ...prose...
 *   ## <symptom>                     <- each h2 is one entry, and one index row
 *
 * Usage:
 *   node tools/build-gotchas-index.js          # write dist/engineering/gotchas.md
 *   node tools/build-gotchas-index.js --check  # validate the TOPIC FILES; exit 1 on a
 *                                              # malformed file or an oversize row
 *
 * Write never fails on a bad topic file: it warns, skips it, and writes the rest, because
 * it runs inside `npm install`. Check is the gate, run by `build:check` through the step's
 * `validates` tag in tools/build.js.
 */

const fs = require('node:fs');
const path = require('node:path');

const ENG = path.join(__dirname, '..', 'engineering');
const DIR = path.join(ENG, 'gotchas');
const OUT = path.join(__dirname, '..', 'dist', 'engineering', 'gotchas.md');
// The hand-written guide. Not an output, but --check reads it for one thing: a gotcha
// written INTO it as a heading. The index is built from engineering/gotchas/ only, so such
// an entry is never listed anywhere, and nothing else would notice.
const GUIDE = path.join(ENG, 'gotchas.md');
const GUIDE_OWN_HEADINGS = new Set(['# Gotchas', '## How to use this file']);

/** Headings in the guide that are not its own — each one is a misplaced gotcha. */
function strayGuideEntries(text) {
  const problems = [];
  let fenced = false;
  for (const line of text.replace(/\r\n?/g, '\n').split('\n')) {
    if (/^\s*(```|~~~)/.test(line)) fenced = !fenced;
    if (fenced || !/^#{1,3} /.test(line) || GUIDE_OWN_HEADINGS.has(line.trim())) continue;
    problems.push(
      `a gotcha was written into engineering/gotchas.md: "${line.trim().slice(0, 70)}" — that file is the guide, ` +
        'and the index is built from engineering/gotchas/ only, so this entry is never listed. Move it into the ' +
        'matching engineering/gotchas/<topic>.md as a level-2 heading.',
    );
  }
  return problems;
}
// Rows link from dist/engineering/ back to the topic files. The prefix is constant, so `ROW_CAP`
// measures the row WITHOUT it: the cap governs the heading an author writes.
const LINK_BASE = '../../engineering/';

const FOOTER =
  '_Generated by `npm run gotchas:index` from the entry headings in `engineering/gotchas/` — ' +
  'add an entry to a topic file; this file is rebuilt on every install and never committed._';

// GitHub decides what a heading anchor is, and 144 index links depend on getting it
// right. `github-slugger` IS that rule (it is what GitHub/remark use), so it is the
// dependency rather than a local transcription — HARD RULE #15.
//
// A hand-rolled version was written first and measured against this one: 38 of 144
// anchors disagreed. Both causes are invisible until you diff them — the reference
// strips NON-ASCII punctuation too (em dash, `→`, curly quotes), and it maps each
// space to its own hyphen instead of collapsing a run, so `Marp / Chromium` is
// `marp--chromium` with two. An ASCII-only class that collapses runs looks correct,
// reviews as correct, and mints a quarter of its links dead.
//
// v2 is ESM and these tools are CJS: `require()` of ESM is stable from Node 22.12,
// which is this package's `engines.node` floor.
const GithubSlugger = require('github-slugger').default ?? require('github-slugger');

/**
 * The anchor GitHub will mint for a heading.
 *
 * The slugger takes RENDERED text, so the inline markup a renderer would have
 * consumed comes off first: a [text](url) link contributes only its text, and
 * code/bold/strike markers vanish. `_` is deliberately left alone — it survives into
 * the anchor (`PORTAL_TOKENS` → `portal_tokens`), so stripping it would mint an
 * anchor GitHub never generates.
 *
 * A FRESH slugger per file, which is why this takes one: GitHub dedupes repeated
 * headings per page (`-1`, `-2`), and a shared instance would carry that counter
 * across files and corrupt every anchor after the first collision.
 */
function slugify(heading, slugger = new GithubSlugger()) {
  const rendered = heading
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[`*~]/g, '')
    .trim();
  return slugger.slug(rendered);
}
// The same renderer the docs are rendered by. Heading extraction has to agree with a
// real parser about what a heading IS — fences, HTML comments, indentation, setext
// underlines, closing sequences — and the cheapest way to agree with a parser is to
// be one (HARD RULE #15).
const MarkdownIt = require('markdown-it');
// `html: true` matters: with HTML off, markdown-it treats an <!-- HTML comment --> as
// ordinary text, so a `##` line INSIDE a commented-out block parses as a heading and the
// index grows a row for an entry no reader can ever see. GitHub renders raw HTML, so the
// comment swallows it. Matching the real renderer is the whole point of parsing here.
const md = new MarkdownIt({ html: true });

/**
 * Every ATX/setext heading in a document, in order, as { level, text }.
 *
 * Each heading carries TWO strings, because the index needs different ones for
 * different jobs. `raw` is the markdown source — it becomes the row LABEL, so
 * `\`foreignObject\`` still renders as code in the index. `text` is the RENDERED text,
 * which is what GitHub SLUGS: a [link](url) contributes only its label, `code`
 * contributes its content, emphasis markers are gone, an inline HTML tag contributes
 * nothing. Feeding the slugger anything else mints anchors GitHub never generates.
 */
function parseHeadings(text) {
  const tokens = md.parse(text, {});
  const out = [];
  for (let i = 0; i < tokens.length; i += 1) {
    const open = tokens[i];
    if (open.type !== 'heading_open') continue;
    const inline = tokens[i + 1];
    if (!inline || inline.type !== 'inline') continue;
    out.push({ level: Number(open.tag.slice(1)), raw: inline.content.trim(), text: renderInline(inline) });
  }
  return out;
}

/** Flatten one inline token to the plain text a renderer would show. */
function renderInline(inline) {
  let text = '';
  for (const child of inline.children ?? []) {
    if (child.type === 'text' || child.type === 'code_inline') text += child.content;
    else if (child.type === 'softbreak' || child.type === 'hardbreak') text += ' ';
    // html_inline, *_open, *_close contribute nothing — the renderer consumes them.
  }
  return text.trim();
}

/**
 * Read every topic file into { slug, title, entries[], anchors }.
 *
 * Headings come from MARKDOWN-IT, not from scanning lines, because the index is the
 * only route to these files now and a heading this function misses is a gotcha that
 * no longer exists. The line-scanning version shipped with a parity-based fence
 * toggle, and an adversarial pass broke it in one line: a fenced example containing
 * an ORPHANED closing fence — which is exactly the shape a gotcha about a swallowed
 * fence quotes — flipped the toggle for the rest of the file and silently dropped
 * every entry after it, while `--check` exited 0. The same scan also disagreed with
 * the real renderer about `## ` inside an HTML comment (phantom row), an indented
 * ATX heading (missed), a setext `---` heading (missed), and a closing-sequence
 * `## Foo ##` (wrong anchor). Parsing with the renderer the docs are rendered by
 * makes that whole class impossible rather than fixing five cases of it.
 */
function collect(dir = DIR) {
  const topics = [];
  const errors = [];
  if (!fs.existsSync(dir)) return { topics, errors: [`missing ${path.relative(ENG, dir)}/`] };
  for (const file of fs.readdirSync(dir).sort()) {
    if (!file.endsWith('.md')) continue;
    // A folder README documents the folder; it is not a topic of gotchas. Without
    // this the tool hard-fails `npm run build` the day someone adds one.
    if (file === 'README.md') continue;
    const text = fs.readFileSync(path.join(dir, file), 'utf8').replace(/\r\n?/g, '\n');

    const headings = parseHeadings(text); // [{ level, text }], document order
    // The row template is `- [label](target)`, so a label can carry brackets only while
    // they stay balanced and never form a `](` — otherwise the link ends early and the
    // rest of the heading spills into the page as literal text with a URL beside it. A
    // heading containing a markdown LINK is the realistic shape; balanced brackets in a
    // code span (`:root[…]`) are fine and keep their formatting.
    const rowSafe = (raw) => {
      if (raw.includes('](')) return false;
      let depth = 0;
      for (const ch of raw) {
        if (ch === '[') depth += 1;
        else if (ch === ']' && --depth < 0) return false;
      }
      return depth === 0;
    };
    const padTrailingEscape = (s) => s.replace(/\\+$/, (run) => (run.length % 2 ? `${run}\\` : run));
    const labelFor = (h) => padTrailingEscape(rowSafe(h.raw) ? h.raw : h.text);
    const h1 = headings.find((h) => h.level === 1);
    if (!h1) {
      errors.push(`${file}: no \`# \` title — the index has nothing to group its entries under`);
      continue;
    }
    // Strip the shared `Gotchas — ` prefix: the index already says these are gotchas.
    const title = labelFor(h1).replace(/^Gotchas\s*[—-]\s*/, '');
    const entries = headings.filter((h) => h.level === 2).map(labelFor);
    if (!entries.length) {
      errors.push(`${file}: no \`## \` entries — every topic file needs at least one`);
      continue;
    }
    const dupes = entries.filter((e, i) => entries.indexOf(e) !== i);
    if (dupes.length) {
      errors.push(`${file}: duplicate entry heading(s) — they would collide on one anchor: ${[...new Set(dupes)].join(' | ')}`);
      continue;
    }
    // Anchors are computed HERE, once per file, feeding the slugger EVERY heading in
    // document order — the exact sequence GitHub sees, so a body `###` that collides
    // with an entry cannot hand the entry an anchor that belongs to the `###`.
    const slugger = new GithubSlugger();
    const anchors = new Map();
    let collision = null;
    for (const h of headings) {
      const want = slugify(h.text); // what this heading slugs to ALONE
      const got = slugify(h.text, slugger); // what it gets in page context
      if (want !== got && !collision) collision = { text: h.text, want, got };
      if (h.level === 2) anchors.set(labelFor(h), got);
    }
    // GitHub resolves a collision by appending -1, -2 in document order — correct, but
    // POSITIONAL: inserting an entry above a colliding sibling silently re-anchors the
    // sibling and rots every deep link to it. Refusing the collision keeps every anchor
    // a pure function of its own heading. There are none today; this keeps it that way.
    if (collision) {
      errors.push(
        `${file}: two headings slug to the same anchor, so GitHub would disambiguate them positionally ` +
          `(\`${collision.want}\` → \`${collision.got}\`) and inserting an entry above one would silently ` +
          `move the other's link. Reword: ${collision.text.slice(0, 80)}`,
      );
      continue;
    }
    topics.push({ slug: file.replace(/\.md$/, ''), file, title, entries, anchors });
  }
  return { topics, errors };
}

/** The one row an entry renders to — written by `render`, measured by `rowCostProblems`. */
function rowFor(topic, entry, base = '') {
  return `- [${entry}](${base}gotchas/${topic.file}#${topic.anchors.get(entry)})`;
}

/** The one heading a topic renders to. */
function headingFor(topic, base = '') {
  return `### [${topic.title}](${base}gotchas/${topic.file})`;
}

/**
 * THE PER-ROW COST CAP — the budget this index can actually be held to.
 *
 * The generated block is 197 rows, 14 topic headings and a footer: 9,409 tokens
 * (o200k_base, at the commit that added this cap), of which the ROWS are 9,117. It grows
 * by one row per gotcha, forever, and until now nothing bounded how wide a row got.
 * `build-decisions-index.js` already carries this instrument for its sibling index; this
 * is the same instrument, on the lever this index actually has.
 *
 * WHY A ROW CAP AND NOT A FILE TOTAL. A file total is an aggregate over EVERY entry, so
 * the PR that trips it is being billed for 196 predecessors' contributions and has no
 * local fix. A per-row cap holds each PR to exactly what it added — the same principle
 * #1547 applied to correctness, applied to cost. It is also merge-safe by construction:
 * two concurrent PRs each adding a gotcha both pass, in either order, which is the one
 * property this generator's whole WRITE-vs-CHECK split exists to preserve (see header).
 * Nothing here — and nothing in this file's TESTS — may assert an aggregate over the
 * corpus, including "the widest row is still close to the cap": a PR that shortens or
 * deletes the widest gotcha heading would fail such an assertion for doing exactly what
 * the cap's own error message asks for.
 *
 * WHAT IS BILLED, AND WHY NOT THE WHOLE ROW. The measured length is `- [HEADING](#ANCHOR)`
 * — the entry heading, twice, because the ANCHOR is that heading slugged. The topic
 * FILENAME the row also carries is deliberately EXCLUDED, for the same reason
 * `build-decisions-index.js` strips the successor pointer: it is shared by every entry
 * under the topic, so billing it makes a row's cost non-local. Measured: rename
 * `css.md` to `styling.md` in one PR and add a near-cap css.md entry in another, and each
 * passes alone while the second to merge fails for its predecessor's rename — the exact
 * #1547 shape this cap exists to avoid, with an error message blaming a heading its
 * author never touched. Excluding the filename makes the billed quantity precisely what
 * the author controls, so the refusal can name one lever and be right every time.
 *
 * WHAT THE NUMBER IS. Measured over the live corpus: billed length p50 150 characters,
 * p90 194, max 274. The cap sits just above today's widest row, so it is a RATCHET at the
 * corpus, never an aspirational target nothing can hit. It leaves a typical entry about
 * 135 characters of heading — already more than a scannable symptom needs.
 *
 * THE HEADROOM IS SMALL, ON PURPOSE, AND THAT HAS A COST. 280 leaves the widest live row
 * six characters, which is THREE characters of heading because the heading is billed
 * twice. An editorial touch to that one heading — a clarity pass, a #21 sweep — will trip
 * the cap and have to shorten it. That is what a ratchet at the corpus means, and the
 * precedent sits just as tight (max 281, cap 285). Raise the cap only with the measurement
 * that justifies it, never to make one edit pass.
 *
 * CHARACTERS, NOT TOKENS. The cap counts characters because that is what an author can see
 * and act on. It is a proxy: across the live corpus a row costs 0.23-0.36 tokens per
 * character, so a 280-character row is roughly 65-100 tokens. Close enough to bound growth,
 * and not the same thing as a token budget.
 */
const ROW_CAP = 280;

/**
 * What one row costs its author: the heading as the link label, and the heading again as
 * the anchor. Deliberately NOT `rowFor` — see the docblock on the topic filename.
 */
function billedRow(topic, entry) {
  return `- [${entry}](#${topic.anchors.get(entry)})`;
}

/** Per-entry, per-row: the check a single PR can be held responsible for. */
function rowCostProblems(topics) {
  const problems = [];
  for (const topic of topics) {
    for (const entry of topic.entries) {
      const billed = billedRow(topic, entry).length;
      if (billed <= ROW_CAP) continue;
      problems.push(
        `${topic.file} » "${entry.slice(0, 80)}${entry.length > 80 ? '…' : ''}": the heading costs ` +
          `${billed} characters of index row, over the ${ROW_CAP} cap. It is rendered TWICE per row ` +
          '(link label, then slugged as the anchor) and paid on every read of the index, so a ' +
          'character here costs two. Shorten it to a symptom a reader can scan and move the ' +
          'detail into the entry body, where nobody pays for it until they open the topic file.',
      );
    }
  }
  return problems;
}

const PREAMBLE = [
  '<!-- Generated by tools/build-gotchas-index.js — DO NOT EDIT, and do not commit (dist/ is ignored). -->',
  '',
  '# Gotchas — the symptom index',
  '',
  'One line per gotcha, grouped by topic, each linking to its entry under `engineering/gotchas/`. ' +
    'Skim or `grep` this for a SYMPTOM, then open the ONE file it names. Have a NAME instead (an API, ' +
    'a CSS property, a selector, an error string)? `grep -rn <term> engineering/gotchas/` — those ' +
    'words are in the entry bodies, which this index does not carry. How to add one: ' +
    '[engineering/gotchas.md](../../engineering/gotchas.md).',
  '',
];

function render(topics) {
  const lines = [...PREAMBLE];
  for (const topic of topics) {
    lines.push(headingFor(topic, LINK_BASE), '');
    for (const entry of topic.entries) lines.push(rowFor(topic, entry, LINK_BASE));
    lines.push('');
  }
  lines.push(FOOTER, '');
  return lines.join('\n');
}

// `dir`/`out` are injectable ONLY so the tests can drive the real CLI path — the exit
// codes, the warnings, the written file — against a fixture corpus.
function main(argv, { dir = DIR, out = OUT, guide = GUIDE } = {}) {
  const check = argv.includes('--check');
  const { topics, errors } = collect(dir);
  const guideText = fs.existsSync(guide) ? fs.readFileSync(guide, 'utf8') : '';
  const problems = [...errors, ...rowCostProblems(topics), ...strayGuideEntries(guideText)];
  const entryCount = topics.reduce((a, t) => a + t.entries.length, 0);

  if (check) {
    if (!problems.length) {
      process.stdout.write(`gotchas-index OK — ${entryCount} entries across ${topics.length} topics, each well-formed.\n`);
      return 0;
    }
    process.stderr.write(`gotchas-index: ${problems.length} problem(s) in engineering/gotchas/:\n`);
    for (const p of problems) process.stderr.write(`  ✗ ${p}\n`);
    return 1;
  }

  // Write never fails on a topic file (see the header): warn, skip, write the rest.
  for (const p of problems) process.stderr.write(`gotchas-index: ⚠ ${p}\n`);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, render(topics));
  process.stdout.write(`gotchas-index: wrote ${entryCount} entries across ${topics.length} topics into ${path.relative(path.join(__dirname, '..'), out)}\n`);
  return 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));
module.exports = { slugify, parseHeadings, collect, render, rowFor, headingFor, billedRow, rowCostProblems, strayGuideEntries, main, FOOTER, ROW_CAP, OUT, LINK_BASE };
