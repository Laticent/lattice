#!/usr/bin/env node
/**
 * Generates docs/src/components/studio/guide-handles.generated.ts — the RENDERED-part
 * catalog the Guide points with.
 *
 * WHY A GENERATED CATALOG RATHER THAN A `querySelector` PER COMPONENT IN THE GUIDE.
 * Round three refused the second on the grounds that "a `querySelector` per component
 * would be Guide learning the component catalog by heart". That objection is about the
 * Guide HOLDING the catalog; it is not an objection to the Guide READING a generated
 * one, and the repo already does exactly that elsewhere —
 * tools/build-axis-dom-catalog.js projects `density.domSelector` into
 * lib/runtime/axis-dom-catalog.generated.js for the Fix-Me overlay's drill-down.
 * Same shape, different consumer.
 *
 * WHY NOT `slots`, AND WHY NOT `density.domSelector`.
 * `slots` is an AUTHORING contract — it describes the Markdown an author writes — and
 * 25% of slot x component pairs never match the rendered DOM, concentrated on exactly
 * the components that need this. `density.domSelector` IS rendered and accurate, but it
 * names the collection the WORD BUDGET counts, which is a different question from "what
 * token names this part": kanban declares one and narrates no card at all.
 * See engineering/decisions/2026-09-21-manifest-handles.md.
 *
 * THE SELECTOR IS SECTION-SCOPED HERE, once, rather than at every call site: a part
 * class is only unique within its own component, and the consumer matches elements in a
 * document that holds every slide of the deck.
 *
 * Usage:
 *   node tools/build-guide-handles.js            regenerate
 *   node tools/build-guide-handles.js --check    freshness gate (CI)
 */

const fs = require('node:fs');
const path = require('node:path');
const { loadAll } = require('../lib/components');
const { ARCHETYPES, ARCHETYPE_NAMES, gestureOf } = require('../lib/core/gesture');

const ROOT = path.join(__dirname, '..');
const OUT_FILE = path.join(ROOT, 'docs', 'src', 'components', 'studio', 'guide-handles.generated.ts');

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const silent = argv.includes('--silent') || check;

function build() {
  const rows = [];
  for (const m of loadAll()) {
    if (!Array.isArray(m.handles)) continue;
    for (const h of m.handles) {
      rows.push({ component: m.name, part: `section.${m.name} ${h.part}`, names: h.names });
    }
  }
  rows.sort((a, b) => a.component.localeCompare(b.component) || a.part.localeCompare(b.part));
  // THE GESTURES ride the same projection, keyed by the component name the slide's section
  // carries as a class. They ship as the archetypes once and each component's own block, not 71 merged
  // copies of the same selectors (which cost the player 13.6 KB, measured 2026-09-28). The Guide
  // merges on lookup with `mergeGesture`, the function `lib/core/gesture.js` calls.
  const gestures = {};
  for (const m of [...loadAll()].sort((a, b) => a.name.localeCompare(b.name))) {
    if (gestureOf(m)) gestures[m.name] = m.gesture;
  }
  const archetypes = Object.fromEntries(ARCHETYPE_NAMES.map((n) => [n, ARCHETYPES[n]]));
  return (
    '/* Auto-generated by tools/build-guide-handles.js — DO NOT EDIT.\n' +
    '   Source: every component manifest\'s `handles` block (lib/components/).\n' +
    '   Rebuild: node tools/build-guide-handles.js */\n\n' +
    '/** One rendered part a narrated sentence can name, and the token that names it. */\n' +
    'export type GuideHandle = {\n' +
    '\t/** The component that declared it — attribution for the sweep, not used for matching. */\n' +
    '\tcomponent: string;\n' +
    '\t/** The repeated part, already scoped to its own section. */\n' +
    '\tpart: string;\n' +
    '\t/** The naming token, scoped within `part`. */\n' +
    '\tnames: string;\n' +
    '};\n\n' +
    'export const GUIDE_HANDLES: readonly GuideHandle[] = ' +
    JSON.stringify(rows, null, '\t') +
    ';\n\n' +
    '/** A component\'s gesture contract, merged (`mergeGesture`): the units a bound sentence names,\n' +
    ' *  and the key beat. engineering/decisions/2026-09-27-guide-storyboards.md §7. */\n' +
    'export type GuideScene = {\n' +
    '\tarchetype: string;\n' +
    '\tunits: Record<string, GuideUnit>;\n' +
    '\tkey: string;\n' +
    '};\n\n' +
    'export type GuideUnit = { select: string | readonly string[]; fallback?: string; labels?: string };\n\n' +
    '/** A manifest\'s own `gesture` block: its archetype and only what its render does differently. */\n' +
    'export type GuideGesture = { archetype: string; units?: Record<string, GuideUnit>; key?: string };\n\n' +
    '/** The ten archetypes\' defaults (lib/core/gesture-archetypes.json). */\n' +
    'export const GUIDE_ARCHETYPES: Readonly<Record<string, { units: Record<string, GuideUnit>; key: string }>> = ' +
    JSON.stringify(archetypes) +
    ';\n\n' +
    'export const GUIDE_GESTURES: Readonly<Record<string, GuideGesture>> = ' +
    JSON.stringify(gestures) +
    ';\n'
  );
}

function main() {
  const out = build();
  const entryCount = (out.match(/"component":/g) || []).length;
  if (check) {
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : '';
    if (current !== out) {
      console.error('[build-guide-handles] STALE — run `node tools/build-guide-handles.js` and commit docs/src/components/studio/guide-handles.generated.ts');
      process.exit(1);
    }
    if (!silent) console.log('[build-guide-handles] up to date.');
    return;
  }
  fs.writeFileSync(OUT_FILE, out);
  if (!silent) console.log(`[build-guide-handles] wrote ${path.relative(ROOT, OUT_FILE)} (${entryCount} entries)`);
}

main();
