#!/usr/bin/env node
/**
 * Bundle the Guide kernel for the exported HTML player, as one injectable IIFE string.
 *
 *   docs/src/components/studio/guide-player.ts  (+ guide-kernel.ts and what it imports)
 *     →  lib/export/guide-player.generated.mjs   (export const GUIDE_PLAYER_JS = "…")
 *
 * WHY a string: the player is one self-contained HTML file whose script is pinned by a sha256
 * CSP, so it cannot `import`. `lib/export/player-core.mjs` appends this string to that script
 * when a deck sets `delivery:` (owner ruling 2026-09-25, Fork 3a), the way it appends the Anima
 * bundles. The kernel's source stays in `docs/src`, where the Studio runs it through Vite: one
 * source, two surfaces (HARD RULE #1; engineering/decisions/2026-09-25-vetrina-delivery-presets.md §7.2).
 *
 * ONE REDIRECT. The kernel imports `spokenValue` from the docs site's read-along bundle, which is
 * the whole chart narrator (~248 KB) wrapped as CommonJS, so esbuild cannot drop the rest of it.
 * That bundle is itself built from `lib/core/chart-values.js`, so the player bundle reads the same
 * function from its source instead.
 *
 * Flags:
 *   --check    Build to a temp buffer and diff against the committed file (the freshness gate).
 *   --silent   Suppress the success log line.
 */
const esbuild = require('esbuild');
const path = require('node:path');
const fs = require('node:fs');

const ROOT = path.resolve(__dirname, '..');
const DOCS_SRC = path.join(ROOT, 'docs', 'src');
const OUT_FILE = path.join(ROOT, 'lib', 'export', 'guide-player.generated.mjs');
const argv = process.argv.slice(2);
const check = argv.includes('--check');
const silent = argv.includes('--silent') || check;

// The player reads `window.__latticeGuide.create(look)` once, when the bundle is appended.
const ENTRY_CONTENTS = `
import { createPlayerGuide } from './components/studio/guide-player';
window.__latticeGuide = { create: createPlayerGuide };
`;

const spokenValueFromSource = {
	name: 'spoken-value-from-source',
	setup(build) {
		build.onResolve({ filter: /read-along-core\.generated\.js$/ }, () => ({ path: 'spoken-value', namespace: 'guide-shim' }));
		build.onLoad({ filter: /.*/, namespace: 'guide-shim' }, () => ({
			contents: "export { spokenValue } from './lib/core/chart-values.js';",
			resolveDir: ROOT,
			loader: 'js',
		}));
	},
};

const BUILD_OPTIONS = {
	stdin: { contents: ENTRY_CONTENTS, resolveDir: DOCS_SRC, loader: 'ts', sourcefile: 'guide-player.entry.ts' },
	bundle: true,
	format: 'iife',
	platform: 'browser',
	target: ['chrome109'],
	minify: true, // the player embeds this verbatim; keep the export small
	legalComments: 'none',
	alias: { '@': DOCS_SRC },
	plugins: [spokenValueFromSource],
};

function moduleSource(iife) {
	return (
		'// Auto-generated by tools/build-guide-player.js — DO NOT EDIT.\n' +
		'// Source: docs/src/components/studio/guide-player.ts over guide-kernel.ts, the Guide kernel the\n' +
		"// Studio's Present runs. Inlined into the exported player only when a deck sets `delivery:`.\n" +
		'// Rebuild: npm run guide-player:build\n' +
		`export const GUIDE_PLAYER_JS = ${JSON.stringify(iife)};\n`
	);
}

async function main() {
	const result = await esbuild.build({ ...BUILD_OPTIONS, write: false });
	const out = moduleSource(result.outputFiles[0].text);
	if (check) {
		const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : '';
		if (current !== out) {
			process.stderr.write(`[build-guide-player] ${path.relative(ROOT, OUT_FILE)} is stale — run: npm run guide-player:build\n`);
			process.exit(1);
		}
		return;
	}
	fs.writeFileSync(OUT_FILE, out);
	if (!silent) process.stdout.write(`[build-guide-player] wrote ${path.relative(ROOT, OUT_FILE)} (${out.length} bytes)\n`);
}

main().catch((err) => {
	process.stderr.write(`${err.stack || err}\n`);
	process.exit(1);
});
