#!/usr/bin/env node
/**
 * Bundle the Guide — the resolver, the per-sentence conductor and Vetrina's hand — into ONE
 * self-contained IIFE string, for injection into a narrated `.html` export whose deck declares
 * `delivery:` (the owner's fork 3a).
 *
 *   docs/src/components/studio/guide-player.ts
 *     (+ present-guide.ts, guide-conductor.ts, Vetrina's stage, Cadenza's spoken text)
 *     →  lib/export/guide-player-bundle.generated.mjs
 *        (`export const GUIDE_PLAYER_JS = "<iife source>"`)
 *
 * WHY a string constant: the player's runtime is a single CSP-hashed inline <script>
 * (`player-core.mjs`), so it cannot `import`. The same shape as `build-anima-player.js`, for
 * the same reason. `player-core` injects it only when the deck is narrated and declares
 * `delivery:`, so every other export stays byte-identical. Decision record:
 * engineering/decisions/2026-09-27-guide-in-the-exported-player.md.
 *
 * SOURCES, NOT DISTS. `@/lib/vetrina`, `@/lib/cadenza` and `@laticent/ltt` resolve to their
 * TypeScript sources here, not to the `dist/` builds the docs site uses. Those dists are built
 * in the BACKGROUND by tools/build.js, and this step runs ahead of the emulator, which inlines
 * its output; reading a dist would race a child process that may be rewriting it (the
 * JOIN_BEFORE_SCRIPTS note in tools/build.js records that race once already). The code is the
 * same code either way: each dist is a compile of the source named here.
 *
 * ONE SUBSTITUTION. `present-guide.ts` takes `spokenValue` from the docs site's
 * read-along-core bundle, which is 120 KB of the whole narration kernel. Its source is
 * `lib/core/chart-values.js` (dependency-free, and the module that bundle inlines), so the
 * import resolves there: 85 KB against 204 KB, and the same function.
 *
 * Flags: --check (freshness gate, exit 1 on drift), --silent.
 */

const esbuild = require('esbuild');
const path = require('node:path');
const fs = require('node:fs');

const ROOT = path.resolve(__dirname, '..');
const DOCS_SRC = path.join(ROOT, 'docs', 'src');
const OUT_FILE = path.join(ROOT, 'lib', 'export', 'guide-player-bundle.generated.mjs');

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const silent = argv.includes('--silent') || check;

const SOURCES = {
  '@/lib/vetrina': path.join(DOCS_SRC, 'lib', 'vetrina', 'index.ts'),
  '@/lib/cadenza': path.join(DOCS_SRC, 'lib', 'cadenza', 'index.ts'),
  '@laticent/ltt': path.join(DOCS_SRC, 'lib', 'ltt', 'index.ts'),
};

const sourcesNotDists = {
  name: 'guide-player-sources',
  setup(build) {
    build.onResolve({ filter: /^(@\/lib\/(vetrina|cadenza)|@laticent\/ltt)$/ }, (args) => ({ path: SOURCES[args.path] }));
    build.onResolve({ filter: /read-along-core\.generated\.js$/ }, () => ({ path: path.join(ROOT, 'lib', 'core', 'chart-values.js') }));
  },
};

const BUILD_OPTIONS = {
  entryPoints: [path.join(DOCS_SRC, 'components', 'studio', 'guide-player.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome109'],
  minify: true, // the player embeds this verbatim; keep the export small
  legalComments: 'none',
  alias: { '@': DOCS_SRC },
  // The compile options, pinned here rather than read from docs/tsconfig.json. That file extends
  // `astro/tsconfigs/strict`, which resolves only when the docs site's dependencies are installed;
  // CI's lint job does not install them, so there esbuild fell back to its own defaults (class
  // fields as assignments, not `defineProperty`) and `build:check` called a fresh bundle stale.
  // These are the values the Astro base sets, so the bundle is the same bytes either way.
  tsconfigRaw: {
    compilerOptions: {
      target: 'ESNext',
      useDefineForClassFields: true,
      verbatimModuleSyntax: true,
      jsx: 'react-jsx',
      jsxImportSource: 'react',
    },
  },
  plugins: [sourcesNotDists],
  logLevel: 'silent',
};

async function buildIife() {
  const result = await esbuild.build({ ...BUILD_OPTIONS, write: false });
  // The Astro base's `strict` made esbuild open the bundle with this directive. It is written here
  // instead: `strict` in `tsconfigRaw` would reach lib/core/chart-values.js as well, and esbuild's
  // `banner` adds a line break the directive never had.
  return `"use strict";${result.outputFiles[0].text}`;
}

function moduleSource(iife) {
  return (
    '// Auto-generated by tools/build-guide-player.js — DO NOT EDIT.\n' +
    '// Source: docs/src/components/studio/guide-player.ts (+ present-guide.ts, guide-conductor.ts,\n' +
    "// Vetrina's stage). Inlined into narrated exports only. Rebuild: npm run guide-player:build\n" +
    `export const GUIDE_PLAYER_JS = ${JSON.stringify(iife)};\n`
  );
}

async function main() {
  const out = moduleSource(await buildIife());
  if (check) {
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : '';
    if (current !== out) {
      console.error('[build-guide-player] STALE — run `npm run guide-player:build` and commit lib/export/guide-player-bundle.generated.mjs');
      process.exit(1);
    }
    if (!silent) console.log('[build-guide-player] up to date.');
    return;
  }
  fs.writeFileSync(OUT_FILE, out);
  if (!silent) console.log(`[build-guide-player] wrote ${path.relative(ROOT, OUT_FILE)} (${(out.length / 1024).toFixed(1)} KB).`);
}

main().catch((err) => {
  console.error('[build-guide-player]', err);
  process.exit(1);
});
