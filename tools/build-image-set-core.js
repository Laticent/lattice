#!/usr/bin/env node
/**
 * Bundle the shared image-set contract for the browser.
 *
 *   lib/export/image-set.js
 *     →  docs/src/playground/image-set-core.generated.js   (ESM, named exports)
 *
 * Same rationale as the other cores (tools/build-*-core.js): the lib module is
 * CommonJS (so the CLI lattice-emulator.js and the Node unit tests share it), which
 * Vite's dev server can't transform in an arbitrary source file. esbuild resolves it
 * into one ESM module with named exports for docs/src/playground/drawing-board-export.js's
 * "Images" (image-set ZIP) export. ONE source (the same the unit tests run) — this is
 * only a packaging step. The kernel is pure + dependency-free, so the bundle is tiny.
 *
 * Flags: --check (freshness gate, exit 1 on drift), --silent.
 */

const esbuild = require('esbuild');
const path = require('path');
const fs = require('fs');

const ROOT = path.resolve(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'lib', 'export');
const OUT_FILE = path.join(ROOT, 'docs', 'src', 'playground', 'image-set-core.generated.js');

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const silent = argv.includes('--silent') || check;

// Re-export the CJS module's members as ESM named exports (mirrors the other
// *-core entries). Keep this list in step with lib/export/image-set.js's exports.
const ENTRY_CONTENTS = `
import core from './image-set.js';
export const {
  IMAGE_FORMATS, FORMAT_META, SIZE_PRESETS, RASTER_MAX_EDGE,
  COLOR_MODES, SVG_BACKGROUNDS, SVG_BACKGROUND_FILL, SVG_LOOK_MODE, DEFAULTS,
  normalizeImageSetOptions, resolveRasterScale, resolveThumbScale, svgBackgroundFill, svgLookMode,
  padWidth, deckSlug, slideEntryName, thumbEntryName, assetEntryName,
  buildImageSetManifest, assembleImageSetPlan, addPlanToZip,
} = core;
`;

const BUILD_OPTIONS = {
  stdin: { contents: ENTRY_CONTENTS, resolveDir: SRC_DIR, loader: 'js', sourcefile: 'image-set-core.entry.js' },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['chrome109'],
  minify: false,
  legalComments: 'none',
  banner: {
    js: '/* Auto-generated by tools/build-image-set-core.js — DO NOT EDIT.\n   Source: lib/export/image-set.js. Rebuild: npm run image-set-core:build */',
  },
};

async function build() {
  const result = await esbuild.build({ ...BUILD_OPTIONS, write: false });
  return result.outputFiles[0].text;
}

async function main() {
  const out = await build();
  if (check) {
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : '';
    if (current !== out) {
      console.error('[build-image-set-core] STALE — run `npm run image-set-core:build` and commit docs/src/playground/image-set-core.generated.js');
      process.exit(1);
    }
    if (!silent) console.log('[build-image-set-core] up to date.');
    return;
  }
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, out);
  if (!silent) console.log(`[build-image-set-core] wrote ${path.relative(ROOT, OUT_FILE)} (${out.length} bytes)`);
}

main().catch(e => {
  console.error('[build-image-set-core] failed:', e.message);
  process.exit(1);
});
