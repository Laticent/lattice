#!/usr/bin/env node
/**
 * Build the on-demand KaTeX provider bundle.
 *
 *   lib/playground/katex-provider.js  →  docs/public/playground/lattice-katex.js
 *
 * The real KaTeX library, split out of lattice-playground.js (see
 * tools/build-playground.js's `alias`) so decks without math never pay for
 * it. docs/src/lib/render-engine.ts loads this bundle as a classic <script>
 * only when a source pre-scan finds math syntax — see
 * engineering/decisions/2026-07-10-landing-perf-katex-defer.md §4.
 *
 * Flags:
 *   --watch    Rebuild on source change.
 *   --check    Build to a temp file and diff against the committed bundle.
 *              Exits 1 on drift.
 *   --silent   Suppress the success log line.
 */

const esbuild = require('esbuild');
const path = require('path');
const fs = require('fs');
const { execSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const ENTRY = path.join(ROOT, 'lib', 'playground', 'katex-provider.js');
const OUT_FILE = path.join(ROOT, 'docs', 'public', 'playground', 'lattice-katex.js');

const argv = process.argv.slice(2);
const watch = argv.includes('--watch');
const check = argv.includes('--check');
const silent = argv.includes('--silent') || check;

const BUILD_OPTIONS = {
  entryPoints: [ENTRY],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome109'],
  minify: true,
  legalComments: 'none',
  banner: {
    js: '/* Auto-generated by tools/build-katex-provider.js — DO NOT EDIT. Source: lib/playground/katex-provider.js. Rebuild: npm run katex-provider:build */',
  },
};

async function buildOnce(outFile) {
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  await esbuild.build({ ...BUILD_OPTIONS, outfile: outFile });
}

async function main() {
  if (watch) {
    const ctx = await esbuild.context({ ...BUILD_OPTIONS, outfile: OUT_FILE });
    await ctx.watch();
    if (!silent) console.log(`[build-katex-provider] watching lib/playground/katex-provider.js → ${path.relative(ROOT, OUT_FILE)}`);
    return;
  }

  if (check) {
    const tmp = `${OUT_FILE}.check.tmp`;
    let exitCode = 0;
    try {
      await buildOnce(tmp);
      try {
        execSync(`diff -q "${OUT_FILE}" "${tmp}"`, { stdio: 'pipe' });
      } catch (_e) {
        console.error('✗ docs/public/playground/lattice-katex.js is stale relative to lib/playground/katex-provider.js');
        console.error('  Run: npm run katex-provider:build');
        exitCode = 1;
      }
    } finally {
      try {
        fs.unlinkSync(tmp);
      } catch (_e) {
        /* best effort */
      }
    }
    process.exit(exitCode);
  }

  await buildOnce(OUT_FILE);
  if (!silent) {
    const bytes = fs.statSync(OUT_FILE).size;
    console.log(`[build-katex-provider] ${path.relative(ROOT, OUT_FILE)}  (${(bytes / 1024).toFixed(1)} KB)`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
