#!/usr/bin/env node
/**
 * Build the Lastra image library's consumable dist/: the ESM entry, the CJS entry and type declarations.
 *
 *   docs/src/lib/lastra/*.ts  →  docs/src/lib/lastra/dist/index.{mjs,cjs,d.ts}
 *
 * WHY: Lattice reads it from both module systems. lib/core/image-dimensions.js (CommonJS) reads picture headers with
 * `require('@laticent/lastra')`; the export spine's ES modules (lib/core/image-recode.mjs, canvas-encode.mjs,
 * slide-camera.mjs, pdf-compose/write-pdf.mjs) import it; and the bundles that inline those (the CLI, the PDF writer,
 * the player core) resolve it here (engineering/decisions/2026-11-13-image-library.md §5). The docs site's tests read
 * the TypeScript source through the `@laticent/source` condition.
 *
 * `createJpegEncoder` ships into a browser page as `toString()` source (lib/export/chrome-recode.js), so the bundle
 * keeps es2022, the builder's default: nothing in it is lowered into a helper outside the function.
 *
 * Flags:
 *   --check    Rebuild into a temp dir and diff against dist/. Exits 1 on drift.
 *   --silent   Suppress the success log line.
 */

const { defineLibraryBuild } = require('./lib/build-workspace-lib.js');

defineLibraryBuild({
  name: 'lastra',
  entries: [{ entry: 'index.ts', out: 'index' }],
  external: [],
  banner: (entry) => `/* Auto-generated by tools/build-lastra-lib.js — DO NOT EDIT.\n   Source: docs/src/lib/lastra/${entry}. Rebuild: npm run lastra-lib:build */`,
}).run();
