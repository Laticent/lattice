#!/usr/bin/env node
/**
 * Build the Lente library's node-consumable dist/ — the CJS entry + type
 * declarations that let ROOT CJS code `require('@slidewright/lente')`.
 *
 *   docs/src/lib/lente/*.ts  (source, docs-side ESM/TS)
 *     →  docs/src/lib/lente/dist/index.cjs   (bundled CJS, esbuild)
 *     →  docs/src/lib/lente/dist/*.d.ts      (declarations, tsc)
 *
 * WHY: Lente's package.json already declares `main`/`require` → ./dist/index.cjs
 * and it is an npm-workspace member, but no build ever produced that dist/ — so
 * `require('@slidewright/lente')` (and any npm publish) resolves a missing file.
 * This completes the library-shape recipe the Lente ADR always called for
 * (2026-07-13-lente-reader-lenses.md, following 2026-07-08-library-shape-cadenza-vetrina.md):
 * the `exports` map sends `require` here to dist/index.cjs while docs + Vitest keep
 * importing the TS SOURCE (the `import`/`types` conditions point at ./index.ts) — so
 * the docs runtime is unaffected. Lente is the fourth spin-off sibling; this makes it
 * node-consumable and publishable like Cadenza and Vetrina.
 *
 * Bundler = the in-tree esbuild (engineering/capabilities.md names it the house
 * bundler); declarations = `tsc --emitDeclarationOnly` (esbuild can't emit .d.ts).
 * No new bundler dependency (HARD RULE #15).
 *
 * Flags:
 *   --check    Rebuild into a temp dir and diff the whole tree against the
 *              committed dist/. Exits 1 on drift (the freshness gate).
 *   --silent   Suppress the success log line.
 */

const esbuild = require('esbuild');
const { spawnSync } = require('node:child_process');
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');

const ROOT = path.resolve(__dirname, '..');
const LIB_DIR = path.join(ROOT, 'docs', 'src', 'lib', 'lente');
const DIST_DIR = path.join(LIB_DIR, 'dist');
const ENTRY = path.join(LIB_DIR, 'index.ts');
const TSC = path.join(ROOT, 'node_modules', '.bin', 'tsc');

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const silent = argv.includes('--silent') || check;

const CJS_BANNER =
  '/* Auto-generated by tools/build-lente-lib.js — DO NOT EDIT.\n' +
  '   Source: docs/src/lib/lente/*.ts. Rebuild: npm run lente-lib:build */';

/** The non-test source files whose declarations we emit (tests never ship). */
function sourceFiles() {
  return fs
    .readdirSync(LIB_DIR)
    .filter(
      (f) =>
        (f.endsWith('.ts') || f.endsWith('.tsx')) && !f.endsWith('.test.ts') && !f.endsWith('.d.ts'),
    )
    .sort()
    .map((f) => path.join(LIB_DIR, f));
}

/** Bundle the barrel into one CJS file (zero-dep → everything inlines). */
async function buildCjs(outDir) {
  await esbuild.build({
    entryPoints: [ENTRY],
    outfile: path.join(outDir, 'index.cjs'),
    bundle: true,
    format: 'cjs',
    platform: 'node',
    target: ['node18'],
    minify: false, // committed, human-readable source
    legalComments: 'none',
    // Pin the TS config INLINE so esbuild never auto-discovers docs/tsconfig.json
    // walking up from the entry. That ambient config `extends astro/tsconfigs/strict`,
    // which resolves in some environments and not others (astro is a docs-only dep) —
    // making the emitted bytes environment-dependent and flapping the freshness gate
    // in CI. An empty raw config makes the output deterministic everywhere.
    tsconfigRaw: '{}',
    banner: { js: CJS_BANNER },
  });
}

/** Emit .d.ts for every non-test source via tsc (no JS, declarations only). */
function buildTypes(outDir) {
  const r = spawnSync(
    TSC,
    [
      '--declaration',
      '--emitDeclarationOnly',
      '--outDir',
      outDir,
      '--rootDir',
      LIB_DIR,
      '--module',
      'esnext',
      '--moduleResolution',
      'bundler',
      '--target',
      'es2022',
      '--strict',
      '--skipLibCheck',
      ...sourceFiles(),
    ],
    { cwd: ROOT, stdio: 'inherit' },
  );
  if (r.status !== 0) throw new Error('tsc declaration emit failed');
}

/** Build both artifacts into `outDir` (esbuild CJS + tsc declarations). */
async function buildInto(outDir) {
  fs.mkdirSync(outDir, { recursive: true });
  await buildCjs(outDir);
  buildTypes(outDir);
}

/**
 * Every file under `dir` as [relPath → contents], recursing subdirs. dist/ is
 * flat today, but recursing means a future nested emit can't slip past the
 * freshness diff as a silent false-negative.
 */
function readTree(dir, base = dir) {
  const out = new Map();
  if (!fs.existsSync(dir)) return out;
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) {
      for (const [rel, contents] of readTree(full, base)) out.set(rel, contents);
    } else {
      out.set(path.relative(base, full), fs.readFileSync(full, 'utf8'));
    }
  }
  return out;
}

function diffTrees(want, have) {
  const drift = [];
  for (const [name, contents] of want) {
    if (!have.has(name)) drift.push(`missing: ${name}`);
    else if (have.get(name) !== contents) drift.push(`changed: ${name}`);
  }
  for (const name of have.keys()) if (!want.has(name)) drift.push(`extra: ${name}`);
  return drift;
}

async function main() {
  if (check) {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'lente-lib-'));
    try {
      await buildInto(tmp);
      const drift = diffTrees(readTree(tmp), readTree(DIST_DIR));
      if (drift.length) {
        console.error(
          '[build-lente-lib] STALE — run `npm run lente-lib:build` and commit docs/src/lib/lente/dist:\n  ' +
            drift.join('\n  '),
        );
        process.exit(1);
      }
      if (!silent) console.log('[build-lente-lib] up to date.');
    } finally {
      fs.rmSync(tmp, { recursive: true, force: true });
    }
    return;
  }

  // Build into a sibling temp dir and swap in only on success — a failed build
  // (e.g. a source type error) must never leave the committed dist/ deleted.
  // Sibling (not os.tmpdir()) keeps the rename on one filesystem (no EXDEV).
  const staging = `${DIST_DIR}.tmp`;
  fs.rmSync(staging, { recursive: true, force: true });
  try {
    await buildInto(staging);
    fs.rmSync(DIST_DIR, { recursive: true, force: true });
    fs.renameSync(staging, DIST_DIR);
  } finally {
    fs.rmSync(staging, { recursive: true, force: true });
  }
  if (!silent) {
    const files = [...readTree(DIST_DIR).keys()];
    console.log(`[build-lente-lib] wrote ${path.relative(ROOT, DIST_DIR)}/ (${files.join(', ')})`);
  }
}

main().catch((e) => {
  console.error('[build-lente-lib] failed:', e.message);
  process.exit(1);
});
