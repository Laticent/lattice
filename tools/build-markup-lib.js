#!/usr/bin/env node
/**
 * Build the Markup library's consumable dist/: the ESM entry, the CJS entry and type declarations.
 *
 *   docs/src/lib/markup/*.ts  →  docs/src/lib/markup/dist/index.{mjs,cjs,d.ts}
 *
 * WHY: root CJS reads it. The engine's `_focus` and `_build` transformers and the code plugin both
 * `require('@laticent/markup')` for the code-line split, so the plugin and the engine agree without the plugin
 * importing the engine (engineering/decisions/2026-11-01-plugin-contract-hollywood.md §5). The docs runtime resolves
 * the TypeScript source through the `@laticent/source` condition, so nothing there waits on this build.
 *
 * The build itself is tools/lib/build-workspace-lib.js, one builder for every workspace library.
 *
 * Flags:
 *   --check    Rebuild into a temp dir and diff against dist/. Exits 1 on drift.
 *   --silent   Suppress the success log line.
 */

const { defineLibraryBuild } = require('./lib/build-workspace-lib.js');

defineLibraryBuild({
  name: 'markup',
  entries: [{ entry: 'index.ts', out: 'index' }],
  external: [],
  banner: (entry) => `/* Auto-generated by tools/build-markup-lib.js — DO NOT EDIT.\n   Source: docs/src/lib/markup/${entry}. Rebuild: npm run markup-lib:build */`,
}).run();
