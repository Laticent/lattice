#!/usr/bin/env node
/**
 * Bundle the package spine for the browser.
 *
 *   lib/packages/{kinds,read,write,index}.js
 *     →  docs/src/playground/packages-core.generated.js   (ESM, named exports)
 *
 * WHY a bundle: the spine is CommonJS that `require()`s itself and lib/theme/parse.js,
 * and the docs DEV server can't serve a CommonJS module with a `require` over /@fs
 * (astro.config.mjs; the same reason theme-core and layout-core are bundles). esbuild
 * resolves the graph and emits one ESM module that Vite serves in dev AND Rollup ships.
 * The Studio's zip import/export (docs/src/components/studio/package-zip.ts) loads it
 * on demand, so the same spine the build uses reads and writes a Studio zip
 * (engineering/decisions/2026-09-23-portable-packages.md §3.4).
 *
 * lib/packages/fs.js is NOT bundled: it is the build's filesystem walk.
 *
 * Flags:
 *   --check    Build to a buffer and diff against the file on disk. Exit 1 on drift.
 *   --silent   Suppress the success log line.
 */

const esbuild = require('esbuild');
const path = require('node:path');
const fs = require('node:fs');

const ROOT = path.resolve(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'lib', 'packages');
const OUT_FILE = path.join(ROOT, 'docs', 'src', 'playground', 'packages-core.generated.js');

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const silent = argv.includes('--silent') || check;

// Default-import the CJS entry and re-export its public symbols by name (esbuild can't
// enumerate CommonJS exports for `export *`).
const ENTRY_CONTENTS = `
import spine from './index.js';
export const {
  FORMAT, MANIFEST_ROLE, KINDS, TYPES, NAME_RE, RESERVED_SUFFIX,
  kindOf, fileName, rolesOf, roleOf,
  readPackage, writePackage, stampManifest, buildIndex, createRegistry,
} = spine;
`;

const BUILD_OPTIONS = {
  stdin: { contents: ENTRY_CONTENTS, resolveDir: SRC_DIR, loader: 'js', sourcefile: 'packages-core.entry.js' },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['chrome109'],
  minify: false,
  legalComments: 'none',
  banner: {
    js: '/* Auto-generated by tools/build-packages-core.js — DO NOT EDIT.\n   Source: lib/packages/*.js. Rebuild: node tools/build-packages-core.js */',
  },
};

async function main() {
  const result = await esbuild.build({ ...BUILD_OPTIONS, write: false });
  const out = result.outputFiles[0].text;
  if (check) {
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : '';
    if (current !== out) {
      console.error('[build-packages-core] STALE — run `node tools/build-packages-core.js`');
      process.exit(1);
    }
    if (!silent) console.log('[build-packages-core] up to date.');
    return;
  }
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, out);
  if (!silent) console.log(`[build-packages-core] wrote ${path.relative(ROOT, OUT_FILE)} (${out.length} bytes)`);
}

main().catch((e) => {
  console.error('[build-packages-core] failed:', e.message);
  process.exit(1);
});
