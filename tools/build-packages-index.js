#!/usr/bin/env node
/**
 * build-packages-index — the ONE generated index of every shipped package
 * (engineering/decisions/2026-09-23-portable-packages.md §3.4).
 *
 * Walks the repo through the package spine (lib/packages/fs.js), reads every package
 * strictly, and writes lib/packages/packages.generated.json: type, name, repo path,
 * the role files present, and whether it carries code. The spine's registry reads its
 * reserved names from this file (§3.7), and later phases replace the hand-kept finish
 * register and theme catalog with it.
 *
 * A package the spine can't read fails the build and names the file, rather than being
 * left out of the index. `checkPackageIdentity` (tools/check-ownership.js) reports the
 * same errors earlier in the build.
 *
 *   node tools/build-packages-index.js           write
 *   node tools/build-packages-index.js --check   exit 1 when the committed file is stale
 */
const fs = require('node:fs');
const path = require('node:path');
const { discoverPackages, ROOT } = require('../lib/packages/fs.js');
const { buildIndex } = require('../lib/packages/index.js');

const OUT = path.join(ROOT, 'lib', 'packages', 'packages.generated.json');
// The finish presets, as a module the engine bundle, the linter and the Studio can all
// require. It replaces three hand-kept copies of the preset list: FINISH_REGISTER,
// the Studio's finish-catalog.ts entries and its PRESET_RECIPES (portable-packages §3.6).
const FINISHES_OUT = path.join(ROOT, 'lib', 'finishes', 'presets.generated.js');

function discover() {
  const found = discoverPackages();
  const bad = found.filter((f) => !f.result.ok);
  if (bad.length) {
    throw new Error(`packages-index: unreadable package(s):\n${bad.map((b) => `  ${b.path}: ${b.result.errors.join('; ')}`).join('\n')}`);
  }
  return found;
}

function render(found = discover()) {
  const index = buildIndex(found.map((f) => ({ pkg: f.result.pkg, path: f.path })));
  return `${JSON.stringify({ _generated: 'by tools/build-packages-index.js from the repo packages — DO NOT EDIT', ...index }, null, 2)}\n`;
}

/** lib/finishes/presets.generated.js: every finish package, in manifest `order`. */
function renderFinishes(found = discover()) {
  const presets = found
    .filter((f) => f.type === 'finish')
    .map(({ path: where, result: { pkg } }) => {
      const recipePath = path.join(ROOT, where, pkg.roles['recipe.json']);
      let recipe;
      try {
        recipe = JSON.parse(fs.readFileSync(recipePath, 'utf8'));
      } catch (e) {
        throw new Error(`packages-index: ${path.relative(ROOT, recipePath)} is not valid JSON: ${e.message}`);
      }
      const { label, blurb, order, swatch } = pkg.manifest;
      return { name: pkg.name, label, blurb, order, swatch, recipe };
    })
    .sort((a, b) => a.order - b.order);
  const orders = presets.map((p) => p.order);
  if (new Set(orders).size !== orders.length) throw new Error(`packages-index: two finishes share an "order" (${orders.join(', ')})`);
  const rows = presets.map(({ order: _o, ...p }) => `  ${JSON.stringify(p)},`).join('\n');
  return `/* Auto-generated by tools/build-packages-index.js from lib/finishes/<name>/ — DO NOT EDIT.
   Each finish is a package: <name>.manifest.json (name, label, blurb, picker swatch,
   order) + <name>.recipe.json (the look). Add a finish by adding a folder.
   Rebuild: node tools/build-packages-index.js */
const FINISH_PRESETS = Object.freeze([
${rows}
].map((p) => Object.freeze(p)));

module.exports = { FINISH_PRESETS };
`;
}

const OUTPUTS = [
  [OUT, render],
  [FINISHES_OUT, renderFinishes],
];

function main(argv) {
  const found = discover();
  const next = OUTPUTS.map(([file, fn]) => [file, fn(found)]);
  if (argv.includes('--check')) {
    const stale = next.filter(([file, text]) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null) !== text).map(([file]) => path.relative(ROOT, file));
    if (stale.length) {
      process.stderr.write(`packages-index STALE — ${stale.join(' + ')} does not match the repo packages.\nRun \`node tools/build-packages-index.js\` and commit the result.\n`);
      return 1;
    }
    process.stdout.write('packages-index OK — packages.generated.json + finishes/presets.generated.js match the repo packages.\n');
    return 0;
  }
  for (const [file, text] of next) fs.writeFileSync(file, text);
  const { counts } = JSON.parse(next[0][1]);
  process.stdout.write(`packages-index: wrote ${next.map(([f]) => path.relative(ROOT, f)).join(' + ')} (${Object.entries(counts).map(([t, n]) => `${n} ${t}`).join(', ')})\n`);
  return 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));

module.exports = { render, renderFinishes, OUT, FINISHES_OUT };
