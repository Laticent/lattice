#!/usr/bin/env node
/**
 * Bundle the pure HTML-player assembly core for the browser.
 *
 *   lib/export/player-core.mjs  (+ lib/core/lattice-doc.js,
 *     lib/core/present-transport.mjs, lib/transformers/prose-projection.mjs)
 *     →  docs/src/playground/player-core.generated.js   (ESM, named exports)
 *
 * WHY a bundle: `player-core.mjs` imports `buildEnvelope` from the CJS
 * `lib/core/lattice-doc.js` and dynamic-imports `present-transport.mjs` +
 * `prose-projection.mjs`. Vite's dev server doesn't transform CJS `require` in
 * arbitrary source, so esbuild resolves the whole graph into one browser ESM
 * module the Studio's "Download as webpage" export imports. Same packaging step
 * as tools/build-theme-core.js — the assembly LOGIC has exactly one source
 * (lib/export/player-core.mjs, shared byte-identically with the CLI adapter);
 * this only makes it reachable from the browser.
 *
 * Flags:
 *   --check    Build to a temp buffer and diff against the committed file.
 *              Exits 1 on drift (the freshness gate).
 *   --silent   Suppress the success log line.
 */

const esbuild = require('esbuild');
const path = require('path');
const fs = require('fs');

const ROOT = path.resolve(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'lib', 'export');
const OUT_FILE = path.join(ROOT, 'docs', 'src', 'playground', 'player-core.generated.js');

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const silent = argv.includes('--silent') || check;

// player-core.mjs is already ESM with named exports, so re-export them directly.
// esbuild's bundler pulls in the CJS lattice-doc and the two dynamically-imported
// ESM deps (present-transport, prose-projection) — all pure — into one module.
// prose-projection's projectDeckTo{Prose,Speech} are ALSO named-exported at the top
// level (they were already bundled, only reachable internally via buildArticle) so
// the browser can run the same DOM speech projection live — the Studio Present
// read-aloud path, not just the CLI export (2026-07-11-manifest-speech-contract).
const ENTRY_CONTENTS = `
export {
  assemblePlayer, playerCss, playerJs, buildArticle, minifyCss, escapeText, escapeAttr,
} from './player-core.mjs';
export { projectDeckToProse, projectDeckToSpeech } from '../transformers/prose-projection.mjs';
`;

const BUILD_OPTIONS = {
  stdin: { contents: ENTRY_CONTENTS, resolveDir: SRC_DIR, loader: 'js', sourcefile: 'player-core.entry.js' },
  bundle: true,
  // Pin the TS config INLINE so esbuild never auto-discovers docs/tsconfig.json — the SAME
  // hazard tools/build-read-along-core.js and tools/build-cadenza-lib.js already guard, reached
  // here through a third path: player-core.mjs now imports @slidewright/cadenza (for the caption
  // cursor the exported player inlines), so esbuild's tsconfig walk-up from the resolved
  // docs/src/lib/cadenza/dist/index.mjs can reach docs/tsconfig.json, whose
  // `extends: astro/tsconfigs/strict` resolves only where the DOCS workspace is installed.
  //
  // Left unpinned the emitted bytes are environment-dependent, and the failure is remote: CI's
  // lint job runs `npm ci` at the root only, so it emits one `"use strict"` fewer than every
  // developer machine and calls the committed artifact STALE — eighteen bytes, green locally,
  // red on CI, pointing at the wrong file. Nothing in this graph is TypeScript, so there is no
  // tsconfig setting this bundle legitimately needs.
  tsconfigRaw: '{}',
  format: 'esm',
  platform: 'browser',
  target: ['chrome109'],
  minify: false, // readable: this is committed source the docs build serves
  legalComments: 'none',
  banner: {
    js: '/* Auto-generated by tools/build-player-core.js — DO NOT EDIT.\n   Source: lib/export/player-core.mjs. Rebuild: npm run player-core:build */',
  },
};

async function build() {
  const result = await esbuild.build({ ...BUILD_OPTIONS, write: false });
  return result.outputFiles[0].text;
}

async function main() {
  const out = await build();
  if (check) {
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : '';
    if (current !== out) {
      console.error('[build-player-core] STALE — run `npm run player-core:build` and commit docs/src/playground/player-core.generated.js');
      process.exit(1);
    }
    if (!silent) console.log('[build-player-core] up to date.');
    return;
  }
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, out);
  if (!silent) console.log(`[build-player-core] wrote ${path.relative(ROOT, OUT_FILE)} (${out.length} bytes)`);
}

main().catch((e) => {
  console.error('[build-player-core] failed:', e.message);
  process.exit(1);
});
