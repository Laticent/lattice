#!/usr/bin/env node
/**
 * Bundle the used-selector / used-family PRUNE kernel for the browser.
 *
 *   lib/export/player-prune.js  (+ css-tree's browser build)
 *     →  docs/src/playground/player-prune.generated.js   (ESM, named exports)
 *
 * WHY a bundle: `player-prune.js` is CJS and `require('css-tree')`. esbuild resolves
 * css-tree's `browser` build and inlines the whole graph into one ESM module the
 * Studio's Webpage export loads on demand (docs/src/…/player-prune-browser.ts) to
 * prune CSS + fonts against an offscreen full-deck iframe — the SAME kernel the CLI
 * emulator runs in headless Chromium (HARD RULE #1; the prune logic has one source).
 * css-tree is sizeable, so this is a dynamic-import chunk (only math for the export
 * pays it), never part of the initial Studio load. The Studio's reading-view warm-up
 * fetches it after the first slide and a pause in input (docs/src/components/studio/first-slide.ts).
 *
 * Flags:
 *   --check    Build to a temp buffer and diff against the committed file.
 *              Exits 1 on drift (the freshness gate).
 *   --silent   Suppress the success log line.
 */

const esbuild = require('esbuild');
const path = require('path');
const fs = require('fs');

const ROOT = path.resolve(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'lib', 'export');
const OUT_FILE = path.join(ROOT, 'docs', 'src', 'playground', 'player-prune.generated.js');

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const silent = argv.includes('--silent') || check;

// player-prune.js is CJS — default-import binds the default to module.exports, then
// re-export each public symbol as a named ESM export (`export *` can't enumerate CJS).
//
// It also carries the glyph SUBSETTER (player-fonts.js), so the Studio subsets with the same
// code as the CLI: `subset-font`, HarfBuzz's glue and the woff2 codec (wawoff2, whose wasm is
// embedded in its glue). The Studio fetches HarfBuzz's own wasm and passes it to
// `setSubsetWasm` (tools/lib/player-pack-shims/fs.js). Both run on every Webpage export, so one
// on-demand chunk costs one fetch (decisions/2026-10-16-player-as-library-audit.md §11).
const ENTRY_CONTENTS = `
import prune from './player-prune.js';
import fonts from './player-fonts.js';
export const {
  GATE_PROPS, DYNAMIC_PSEUDO_CLASSES, DYNAMIC_PSEUDO_RE, PLAYER_PRUNE_SAFELIST,
  baseSelectorString, collectBaseSelectors, prunePlayerCss, normalizeFamily, prunePlayerFontFaces, scopeReHostedCss,
  PRUNE_SKIP_STYLE_IDS, isPruneSkippedStyle, fontFaceFamilies, literalFontWeights, mergeIdenticalFontFaces,
  PLAYER_VIEWS, LATTICE_CONNECTOR, probeFontUse, probeUsedSelectors, probeGate, prunePlayerHtml,
} = prune;
export const { subsetEmbeddedFonts } = fonts;
export { setSubsetWasm } from '../../tools/lib/player-pack-shims/fs.js';
export { setColorWasm } from '../fonts/subset-color.js';
`;

const SHIMS = path.join(ROOT, 'tools', 'lib', 'player-pack-shims');

// wawoff2's emscripten glue assigns `module.exports = Module` only on its Node branch, so in a
// page the bundled module exported `{}` and every woff2 conversion waited forever on an
// `onRuntimeInitialized` nobody could set. Export the module on every branch.
const wawoff2WebExport = {
  name: 'wawoff2-web-export',
  setup(b) {
    b.onLoad({ filter: /wawoff2[\\/]build[\\/]\w+_binding\.js$/ }, (args) => ({
      contents: `${fs.readFileSync(args.path, 'utf8')}\nmodule.exports = Module;\n`,
      loader: 'js',
    }));
  },
};

const BUILD_OPTIONS = {
  stdin: { contents: ENTRY_CONTENTS, resolveDir: SRC_DIR, loader: 'js', sourcefile: 'player-prune.entry.js' },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['chrome109'],
  alias: { fs: path.join(SHIMS, 'fs.js'), path: path.join(SHIMS, 'path.js') },
  inject: [path.join(SHIMS, 'globals.js')],
  define: { 'require.resolve': '__lpRequireResolve' },
  plugins: [wawoff2WebExport],
  minify: false, // readable: the docs build serves it
  legalComments: 'none',
  banner: {
    js: '/* Auto-generated by tools/build-player-prune.js — DO NOT EDIT.\n   Source: lib/export/player-prune.js (+ css-tree). Rebuild: npm run player-prune:build */',
  },
};

async function build() {
  const result = await esbuild.build({ ...BUILD_OPTIONS, write: false });
  return result.outputFiles[0].text;
}

async function main() {
  const out = await build();
  if (check) {
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : '';
    if (current !== out) {
      console.error('[build-player-prune] STALE — run `npm run player-prune:build` and commit docs/src/playground/player-prune.generated.js');
      process.exit(1);
    }
    if (!silent) console.log('[build-player-prune] up to date.');
    return;
  }
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, out);
  if (!silent) console.log(`[build-player-prune] wrote ${path.relative(ROOT, OUT_FILE)} (${out.length} bytes)`);
}

main().catch((e) => {
  console.error('[build-player-prune] failed:', e.message);
  process.exit(1);
});
