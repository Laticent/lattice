#!/usr/bin/env node
/**
 * Bundle the pure read-along CAPTIONS producer for the browser.
 *
 *   lib/core/read-along-build.js (+ lib/core/read-along-vtt.js, which
 *     require('@slidewright/cadenza') — the built workspace package)
 *     →  docs/src/playground/read-along-core.generated.js   (ESM, named exports)
 *
 * WHY a bundle: both source modules are CJS (`require`/`module.exports`), and
 * Vite's dev server doesn't transform CJS `require` in arbitrary source. esbuild
 * resolves the whole graph (including the `require('@slidewright/cadenza')` →
 * its built `dist/index.cjs`) into one browser ESM module the Studio's "Captions
 * (.vtt)" export imports. Same packaging step as tools/build-player-core.js — the
 * PRODUCER logic has exactly one source (lib/core/read-along-build.js +
 * read-along-vtt.js, shared byte-identically with the CLI `--captions` flag);
 * this only makes it reachable from the browser (HARD RULE #1 — no re-derived
 * offset/serialization logic in a second, docs-side copy).
 *
 * Flags:
 *   --check    Build to a temp buffer and diff against the committed file.
 *              Exits 1 on drift (the freshness gate).
 *   --silent   Suppress the success log line.
 */

const esbuild = require('esbuild');
const path = require('path');
const fs = require('fs');

const ROOT = path.resolve(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'lib', 'core');
const OUT_FILE = path.join(ROOT, 'docs', 'src', 'playground', 'read-along-core.generated.js');

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const silent = argv.includes('--silent') || check;

// Both source modules are CJS — re-export their named exports as ESM. esbuild's
// bundler resolves `require('@slidewright/cadenza')` through the workspace
// package's `require` condition (its built dist/index.cjs), inlining the whole
// (zero-dep) engine into this one file.
const ENTRY_CONTENTS = `
const { buildReadAlong } = require('./read-along-build.js');
const { readAlongToVtt, readAlongToVttParts } = require('./read-along-vtt.js');
export { buildReadAlong, readAlongToVtt, readAlongToVttParts };
`;

const BUILD_OPTIONS = {
  stdin: { contents: ENTRY_CONTENTS, resolveDir: SRC_DIR, loader: 'js', sourcefile: 'read-along-core.entry.js' },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['chrome109'],
  minify: false, // readable: this is committed source the docs build serves
  legalComments: 'none',
  // Pin the TS config INLINE so esbuild never auto-discovers docs/tsconfig.json —
  // the require() chain resolves into docs/src/lib/cadenza/dist/index.cjs (the
  // Cadenza workspace package), and esbuild's tsconfig walk-up from THAT resolved
  // path can reach docs/tsconfig.json (whose `extends: astro/tsconfigs/strict`
  // resolves unevenly across environments — astro is a docs-only dep). Left
  // unpinned this makes the emitted bytes environment-dependent and flaps the
  // freshness gate in CI (the exact hazard tools/build-cadenza-lib.js already
  // guards against — this bundle reaches the same file through a different path).
  tsconfigRaw: '{}',
  banner: {
    js: '/* Auto-generated by tools/build-read-along-core.js — DO NOT EDIT.\n   Source: lib/core/read-along-build.js + lib/core/read-along-vtt.js. Rebuild: npm run read-along-core:build */',
  },
};

async function build() {
  const result = await esbuild.build({ ...BUILD_OPTIONS, write: false });
  return result.outputFiles[0].text;
}

async function main() {
  const out = await build();
  if (check) {
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : '';
    if (current !== out) {
      console.error('[build-read-along-core] STALE — run `npm run read-along-core:build` and commit docs/src/playground/read-along-core.generated.js');
      process.exit(1);
    }
    if (!silent) console.log('[build-read-along-core] up to date.');
    return;
  }
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, out);
  if (!silent) console.log(`[build-read-along-core] wrote ${path.relative(ROOT, OUT_FILE)} (${out.length} bytes)`);
}

main().catch((e) => {
  console.error('[build-read-along-core] failed:', e.message);
  process.exit(1);
});
