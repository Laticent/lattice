#!/usr/bin/env node
/**
 * Build the browser runtime bundle.
 *
 *   lib/runtime/index.js  →  dist/lattice-runtime.js
 *   lib/runtime/index.js  →  dist/lattice-runtime-min.js   (minified, no map)
 *
 * The unminified file carries an inline source map for DevTools / preview
 * debugging; the -min.js is the production/CDN drop-in — minified with no
 * source map to keep it lean. Both are deterministic esbuild outputs, so
 * --check diffs them byte-for-byte.
 *
 * The output path is a public API — committed decks embed
 * <script src="…/dist/lattice-runtime.js">, the README documents it, and
 * external consumers reference it via raw GitHub / jsdelivr URLs.
 * Changing the output path is a breaking change. See
 * engineering/decisions/2026-05-17-shared-transformer-registry.md (esbuild section)
 * for the rationale.
 *
 * Default build:  unminified IIFE + inline source map. Suitable for
 *                 marp-vscode preview, web export, and human inspection
 *                 in DevTools.
 *
 * Flags:
 *   --watch       Rebuild on source change. Used by npm run preview:watch.
 *   --check       Build to a temp file and diff against the committed
 *                 lattice-runtime.js. Exits 1 on drift. Used by the
 *                 bundle-freshness pre-commit hook.
 *   --silent      Suppress success log line (used by --check + hooks).
 *
 * Target: chrome91+. The marp-vscode preview webview runs on a Chromium
 * version a few major releases behind stable; we keep the bundle below
 * features that have caused trouble there (see engineering/gotchas.md
 * for the ":not(:has(...))" case).
 */

const esbuild = require('esbuild');
const path    = require('path');
const fs      = require('fs');
const { execSync } = require('child_process');

const ROOT       = path.resolve(__dirname, '..');
const ENTRY      = path.join(ROOT, 'lib', 'runtime', 'index.js');
const OUT_FILE   = path.join(ROOT, 'dist', 'lattice-runtime.js');
const MIN_FILE   = path.join(ROOT, 'dist', 'lattice-runtime-min.js');
// The docs site's PREVIEW runtime: the minified build with the fluid viewer's chart readers stubbed out. Only an
// export made with `lattice --fluid` boots the fluid view (`data-lattice-fluid-capable`, set by lattice.js and nowhere
// else), and only the fluid view redraws a chart; a preview never does, so the readers (about 14KB gzipped of every
// chart kind's read-back) were dead bytes on every docs page that loads the engine, and put the route budget's
// engineJsGz past its ceiling (PR #3088). The full runtime stays the one exports inline.
const PREVIEW_FILE = path.join(ROOT, 'dist', 'lattice-runtime-preview-min.js');

const argv    = process.argv.slice(2);
const watch   = argv.includes('--watch');
const check   = argv.includes('--check');
const silent  = argv.includes('--silent') || check;

const BUILD_OPTIONS = {
  entryPoints: [ENTRY],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome91'],
  // Sourcemap inlined so a single committed file covers debugging in
  // DevTools without needing a separate .map artifact in the repo.
  sourcemap: 'inline',
  // Deterministic output — bundle freshness hook relies on byte-identical
  // rebuilds from identical sources. esbuild is deterministic by default;
  // skipping minification keeps the bundle human-readable for diff review.
  minify: false,
  legalComments: 'inline',
  // Banner pins the bundle to its source — reviewers spot a stale bundle
  // by comparing the SHA to the working tree.
  banner: { js: `/* Auto-generated by tools/build-runtime.js — DO NOT EDIT.\n   Source: lib/runtime/index.js (and lib/transformers/*).\n   Rebuild: npm run runtime:build\n   SPDX-License-Identifier: AGPL-3.0-only\n   Copyright (c) 2025-2026 Laticent\n*/` },
};

// Minified twin: same bundle, compressed, no source map (the unminified
// file is the debug surface). Banner kept short — esbuild preserves it
// even under minify so the artifact stays traceable.
const MIN_OPTIONS = {
  ...BUILD_OPTIONS,
  sourcemap: false,
  minify: true,
  legalComments: 'none',
  banner: { js: `/*! lattice-runtime-min.js — generated by tools/build-runtime.js, do not edit. SPDX-License-Identifier: AGPL-3.0-only. (c) 2025-2026 Laticent */` },
};

// Resolves the chart readers to an empty table: chart-redraw.js then has no reader for any kind, which it already
// treats as "keep the exported drawing". The preview runtime never reaches it (see PREVIEW_FILE).
const NO_READERS = {
  name: 'no-chart-readers',
  setup(build) {
    build.onResolve({ filter: /^\.\/chart-readers$/ }, (args) => (
      /[\\/]lib[\\/]runtime$/.test(args.resolveDir) ? { path: 'no-chart-readers', namespace: 'lattice-stub' } : undefined));
    build.onLoad({ filter: /.*/, namespace: 'lattice-stub' }, () => ({ contents: 'module.exports = {};', loader: 'js' }));
  },
};
// The placed-picture rule (lib/core/plugin-ctx.js `ctx.pictures`) is read only by the image plugin's Export-to-Marp writer and
// its lint, neither of which runs in a page: the runtime would carry it (about 1.2KB gzipped, with decl-value-safe) for nothing,
// and it put the route budget's engineJsGz past its ceiling (#3132). Every runtime build resolves it to a stub that says so.
const NO_PICTURE_RULE = {
  name: 'no-placed-picture-rule',
  setup(build) {
    build.onResolve({ filter: /^\.\/placed-picture\.js$/ }, (args) => (
      /[\\/]lib[\\/]core$/.test(args.resolveDir) ? { path: 'no-placed-picture-rule', namespace: 'lattice-stub-pictures' } : undefined));
    build.onLoad({ filter: /.*/, namespace: 'lattice-stub-pictures' }, () => ({
      contents: "module.exports = new Proxy({}, { get(_t, k) { throw new Error(`ctx.pictures.${String(k)}: the placed-picture rule is not in the runtime`); } });",
      loader: 'js',
    }));
  },
};
// ONE COPY OF EACH WORKSPACE PACKAGE. A `@laticent/*` package ships both builds (`exports`: `import` → `.mjs`, `require` →
// `.cjs`), so an ES module that imports one (lib/core/meta-door.mjs, `@laticent/segno/read`) and a CommonJS file that requires
// it bundled two copies of the same code: 55KB minified of segno's reader alone, and two copies of any state it keeps. Every
// runtime build resolves an `import` of a workspace package the way a `require` resolves it, so the CommonJS copy the rest of
// the runtime already carries serves both. Found when this PR's bleed-ink pass put engineJsGz past its ceiling (#3132).
const ONE_COPY = {
  name: 'one-copy-of-workspace-packages',
  setup(build) {
    build.onResolve({ filter: /^@laticent\// }, (args) => {
      if (args.kind !== 'import-statement' || args.pluginData?.oneCopy) return undefined;
      return build.resolve(args.path, { kind: 'require-call', resolveDir: args.resolveDir, importer: args.importer, pluginData: { oneCopy: true } });
    });
  },
};
BUILD_OPTIONS.plugins = [NO_PICTURE_RULE, ONE_COPY];
MIN_OPTIONS.plugins = [NO_PICTURE_RULE, ONE_COPY];
const PREVIEW_OPTIONS = {
  ...MIN_OPTIONS,
  plugins: [NO_READERS, NO_PICTURE_RULE, ONE_COPY],
  banner: { js: `/*! lattice-runtime-preview-min.js — generated by tools/build-runtime.js, do not edit. The docs preview runtime: no fluid-view chart readers. SPDX-License-Identifier: AGPL-3.0-only. (c) 2025-2026 Laticent */` },
};

async function buildOnce(outFile, minFile, previewFile) {
  await esbuild.build({ ...BUILD_OPTIONS, outfile: outFile });
  await esbuild.build({ ...MIN_OPTIONS, outfile: minFile });
  await esbuild.build({ ...PREVIEW_OPTIONS, outfile: previewFile });
}

async function main() {
  if (watch) {
    const ctx = await esbuild.context({ ...BUILD_OPTIONS, outfile: OUT_FILE });
    await ctx.watch();
    if (!silent) console.log(`[build-runtime] watching lib/runtime/ → ${path.relative(ROOT, OUT_FILE)}`);
    // ctx stays alive; process holds open via the active watcher
    return;
  }

  if (check) {
    // esbuild encodes source paths in the inline sourcemap RELATIVE TO the
    // outfile location, so a tmp-file build in /tmp produces different
    // sourcemap paths than the in-place build — even when the JS is
    // byte-identical. Writing the check tempfile next to the real output
    // keeps the relative-path encoding stable so diff only reports real drift.
    const tmp = `${OUT_FILE}.check.tmp`;
    const minTmp = `${MIN_FILE}.check.tmp`;
    const previewTmp = `${PREVIEW_FILE}.check.tmp`;
    let exitCode = 0;
    try {
      await buildOnce(tmp, minTmp, previewTmp);
      for (const [real, fresh] of [[OUT_FILE, tmp], [MIN_FILE, minTmp], [PREVIEW_FILE, previewTmp]]) {
        try {
          execSync(`diff -q "${real}" "${fresh}"`, { stdio: 'pipe' });
          // Identical — bundle is fresh.
        } catch (_e) {
          console.error(`✗ ${path.basename(real)} is stale relative to lib/runtime/`);
          console.error('  Run: npm run runtime:build');
          console.error('  Bypass (last resort): git commit --no-verify');
          exitCode = 1;
        }
      }
    } finally {
      for (const f of [tmp, minTmp, previewTmp]) { try { fs.unlinkSync(f); } catch (_e) { /* best effort */ } }
    }
    process.exit(exitCode);
  }

  await buildOnce(OUT_FILE, MIN_FILE, PREVIEW_FILE);
  if (!silent) {
    const bytes = fs.statSync(OUT_FILE).size;
    const minBytes = fs.statSync(MIN_FILE).size;
    console.log(
      `[build-runtime] ${path.relative(ROOT, OUT_FILE)} (${(bytes / 1024).toFixed(1)} KB) + ` +
        `${path.relative(ROOT, MIN_FILE)} (${(minBytes / 1024).toFixed(1)} KB)`,
    );
  }
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
