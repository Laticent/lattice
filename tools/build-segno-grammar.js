#!/usr/bin/env node
/**
 * build-segno-grammar — write the parsers Segno's code generator makes from a grammar.
 *
 *   docs/src/lib/segno/notation-grammar.ts  (the notation, as data)
 *     →  docs/src/lib/segno/notation.generated.ts  (straight-line TypeScript, committed)
 *   lib/core/flowchart-row-grammar.js  (the flowchart row, as data; Segno phase 3b)
 *     →  lib/core/flowchart-row.generated.js  (the same, as CommonJS for lib/, committed)
 *   lib/core/list-text-grammar.js  (leading markers, matrix-grid cells, `_track`; Segno phase 3)
 *     →  lib/core/list-text.generated.js  (the same, as CommonJS for lib/, committed)
 *
 * The flowchart row and the list text are Lattice's grammars, not Segno's, so their parsers live
 * in lib/core beside the readers that walk them (`splitRow` in flowchart-grammar.js; state-marks.js,
 * matrix-grid-cells.js and track-spec.js). They are plain JavaScript because lib/ is CommonJS that
 * runs untranspiled in Node and is bundled as-is for the browser.
 *
 * The generated files are SOURCE: the docs site and Vitest import it, so git tracks it and
 * build:check must compare it. That is why this is its own step rather than part of
 * build-segno-lib.js: the library build writes only the gitignored dist/, and a step whose
 * write set mixes a tracked file with an ignored one can be classified neither way
 * (test/unit/tools/uncommitted-steps.test.js). The library build refuses to run on a stale
 * generated file, so the two cannot disagree.
 *
 * The grammar is compiled by Segno's own code generator (codegen.ts), bundled on the fly with
 * esbuild — the same toolchain the library build uses — and run in-process.
 *
 * Flags:
 *   --check    Fail (exit 1) if the committed file differs from what the grammar generates.
 *   --silent   Suppress the success log line.
 *
 * Design: engineering/decisions/2026-09-28-segno-unified-inline-notation.md § The engine.
 */
const esbuild = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const LIB_DIR = path.join(ROOT, 'docs', 'src', 'lib', 'segno');
const GENERATED = path.join(LIB_DIR, 'notation.generated.ts');
const ROW_GENERATED = path.join(ROOT, 'lib', 'core', 'flowchart-row.generated.js');
const BANNER =
  "// Generated by tools/build-segno-grammar.js from notation-grammar.ts with Segno's code generator\n" +
  '// (codegen.ts). DO NOT EDIT — change the grammar and run `npm run segno-lib:build`.\n\n';
const LIST_GENERATED = path.join(ROOT, 'lib', 'core', 'list-text.generated.js');
const libBanner = (from, readers) =>
  `// Generated by tools/build-segno-grammar.js from lib/core/${from} with Segno's code\n` +
  '// generator (docs/src/lib/segno/codegen.ts). DO NOT EDIT — change the grammar and run\n' +
  `// \`npm run segno-lib:build\`. ${readers}\n`;
const ROW_BANNER = libBanner('flowchart-row-grammar.js', '`splitRow` in flowchart-grammar.js reads it.');
const LIST_BANNER = libBanner('list-text-grammar.js', 'leading-marker.js, matrix-grid-cells.js and track-spec.js read it.');

/** Segno's code generator and the Segno API, bundled from source and loaded in-process. */
async function segnoSource() {
  const r = await esbuild.build({
    stdin: {
      contents: "export { generate } from './codegen.ts'; export { notationSpec } from './notation-grammar.ts'; export * from './index.ts';",
      resolveDir: LIB_DIR,
      loader: 'ts',
    },
    bundle: true, write: false, format: 'cjs', platform: 'node', tsconfigRaw: '{}', logLevel: 'silent',
  });
  const mod = { exports: {} };
  new Function('module', 'exports', r.outputFiles[0].text)(mod, mod.exports);
  return mod.exports;
}

/** The source the notation grammar generates today. */
async function generatedNotation() {
  const S = await segnoSource();
  return S.generate(S.notationSpec, { banner: BANNER });
}

/** The parser a lib/core grammar generates today, as CommonJS. */
function generatedLib(S, spec, banner) {
  const ts = S.generate(spec);
  // Types stripped, the module left as written: esbuild's own CommonJS wrapper would tie the
  // committed file to esbuild's helper text, so a dependency bump could stale it. The generator
  // exports one function, and the export is rewritten by hand.
  const js = esbuild.transformSync(ts, { loader: 'ts', target: 'es2022', tsconfigRaw: '{}' }).code;
  const exported = /^export function parse\(/m;
  if (!exported.test(js) || /^export /m.test(js.replace(exported, ''))) throw new Error('the generated parser exports something other than parse()');
  return `${banner}${js.replace(exported, 'function parse(')}\nmodule.exports = { parse };\n`;
}

/** The flowchart row parser the row grammar generates today. */
async function generatedRow() {
  const S = await segnoSource();
  const { makeRowGrammar } = require('../lib/core/flowchart-row-grammar.js');
  return generatedLib(S, makeRowGrammar(S).rowSpec, ROW_BANNER);
}

/** The list-text parser the list-text grammar generates today. */
async function generatedListText() {
  const S = await segnoSource();
  const { makeListTextGrammar } = require('../lib/core/list-text-grammar.js');
  return generatedLib(S, makeListTextGrammar(S).listTextSpec, LIST_BANNER);
}

/** Does the committed file at `file` (the notation's by default) match `source`? */
const isFresh = (source, file = GENERATED) => fs.existsSync(file) && fs.readFileSync(file, 'utf8') === source;

module.exports = { generatedNotation, generatedRow, generatedListText, isFresh, GENERATED, ROW_GENERATED, LIST_GENERATED };

if (require.main === module) {
  const argv = process.argv.slice(2);
  const check = argv.includes('--check');
  const silent = argv.includes('--silent') || check;
  const outputs = [
    [GENERATED, generatedNotation, 'notation-grammar.ts'],
    [ROW_GENERATED, generatedRow, 'lib/core/flowchart-row-grammar.js'],
    [LIST_GENERATED, generatedListText, 'lib/core/list-text-grammar.js'],
  ];
  (async () => {
    let stale = false;
    for (const [file, make, from] of outputs) {
      const source = await make();
      const rel = path.relative(ROOT, file);
      if (isFresh(source, file)) {
        if (!silent) console.log(`[build-segno-grammar] ${rel} up to date.`);
        continue;
      }
      if (check) {
        console.error(`[build-segno-grammar] STALE — ${rel} does not match ${from}; run \`npm run segno-lib:build\` and commit it.`);
        stale = true;
        continue;
      }
      fs.writeFileSync(file, source);
      if (!silent) console.log(`[build-segno-grammar] wrote ${rel}`);
    }
    if (stale) process.exit(1);
  })()
    .catch((e) => {
      console.error('[build-segno-grammar] failed:', e.message);
      process.exit(1);
    });
}
