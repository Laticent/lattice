#!/usr/bin/env node
/**
 * Build the Segno-markdown library's consumable dist/: the ESM + CJS entry + type declarations.
 *   docs/src/lib/segno-markdown/*.ts  →  dist/index.{mjs,cjs} + dist/*.d.ts
 * Segno-markdown is the deck model, S0 and S1 of the Segno deck pipeline
 * (engineering/decisions/2026-10-22-segno-deck-pipeline.md §Plan, P2): zero dependencies, no DOM, no Node.
 * Flags:
 *   --check    Rebuild into a temp dir and diff against dist/. Exits 1 on drift.
 *   --silent   Suppress the success log line.
 */

const { defineLibraryBuild } = require('./lib/build-workspace-lib.js');

defineLibraryBuild({
  name: 'segno-markdown',
  entries: [{ entry: 'index.ts', out: 'index' }],
  external: [],
  banner: (entry) => `/* Auto-generated by tools/build-segno-markdown-lib.js — DO NOT EDIT.\n   Source: docs/src/lib/segno-markdown/${entry}. Rebuild: npm run segno-markdown-lib:build */`,
}).run();
