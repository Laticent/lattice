#!/usr/bin/env node
/**
 * Verify the `deck` lint ruleset and write its stamps: compile every rule in lib/authoring/rules/ against its own
 * fixtures, strictly (a rule that does not fire on its bad examples, fires on its good ones, or whose fix does not
 * give its fixed example fails the build), then write lib/authoring/rules/verified.generated.json.
 *
 * The file holds two records per rule (engineering/decisions/2026-11-13-squadra-replaces-lint-core.md §3.4):
 *   digests  what `@laticent/squadra/runtime` checks in the browser before it runs a rule (`digestRuleset`): the
 *            rule's declaration, the vocabulary it reads and the language version, which a bundler leaves alone.
 *   stamps   the full stamp (`stampRuleset`): the rule's function source and its fixtures too. Nothing reads it at
 *            run time. It is here so `--check` goes red when a rule's code or fixtures change without a rebuild,
 *            which the digest alone cannot see.
 *
 * The vocabulary is lint's (`buildVocab` over the live manifests) through the vocab bridge
 * (lib/authoring/squadra/vocab.js), the one the Studio and `lint:deck` hand the entry.
 *
 * Flags:
 *   --check    Compile strictly and compare with the committed file. Exits 1 when a rule is refused or the file is
 *              stale.
 *   --silent   Suppress the success log line.
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'lib', 'authoring', 'rules', 'verified.generated.json');

/** The ruleset input as the build compiles it: rules, fixtures, the language and the bridged vocabulary. */
function rulesetInput() {
  const { NAME, RULES, VERSION } = require('../lib/authoring/rules');
  const { ruleExamples } = require('../lib/authoring/rules/examples');
  const { latticeDeck } = require('../lib/authoring/squadra/lattice-deck');
  const { squadraVocab } = require('../lib/authoring/squadra/vocab');
  const { buildVocab } = require('../lib/authoring/lint');
  return { name: NAME, version: VERSION, languages: [latticeDeck], rules: RULES, examples: ruleExamples(), vocab: squadraVocab(buildVocab()) };
}

/** The generated file's text. Throws a RulesetError listing every refused rule. */
function render(input = rulesetInput()) {
  const { compileRuleset, digestRuleset, stampRuleset } = require('@laticent/squadra');
  compileRuleset(input); // strict: every rule runs its examples, or the build stops here
  const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : 1)));
  const lang = input.languages[0];
  const body = {
    $comment: 'Generated by tools/build-squadra-stamps.js from lib/authoring/rules/. Do not edit: run `npm run build`.',
    ruleset: `${input.name}@${input.version}`,
    language: `${lang.id}@${lang.version}`,
    rules: input.rules.length,
    digests: sorted(digestRuleset(input)),
    stamps: sorted(stampRuleset(input)),
  };
  return `${JSON.stringify(body, null, 2)}\n`;
}

function main(argv) {
  const check = argv.includes('--check');
  const silent = argv.includes('--silent');
  let text;
  try {
    text = render();
  } catch (e) {
    console.error(`[build-squadra-stamps] the deck ruleset does not compile:\n${e.message}`);
    return 1;
  }
  const rel = path.relative(ROOT, OUT);
  if (check) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) {
      console.error(`[build-squadra-stamps] STALE — a deck rule, its fixtures or the vocabulary changed. Run \`npm run build\` and commit ${rel}`);
      return 1;
    }
    if (!silent) console.log(`[build-squadra-stamps] ${rel} is current`);
    return 0;
  }
  fs.writeFileSync(OUT, text);
  if (!silent) console.log(`[build-squadra-stamps] wrote ${rel}`);
  return 0;
}

if (require.main === module) process.exitCode = main(process.argv.slice(2));

module.exports = { render, rulesetInput };
