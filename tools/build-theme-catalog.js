#!/usr/bin/env node
/**
 * Generates docs/src/components/studio/palettes.generated.ts — the palette picker's
 * name groups and swatches, derived from the theme manifests.
 *
 * WHY THIS IS GENERATED
 * `themes/<name>.manifest.json` is the single declaration of which palettes exist and
 * what each one is (`role`, `family`, `tier`, `swatch`). The docs bundle can't
 * `fs`-load 32 JSON files at runtime — the same constraint that forces
 * build-stage-catalog.js — so the declaration is baked here at build time.
 *
 * It replaces two hand-maintained lists that had to be kept in lockstep BY A TEST:
 *   · palettes.ts's CURATED / MORE_THEMES / A11Y_THEMES groupings
 *   · ThemePicker's PALETTE_DOTS swatch map
 * The test existed because adding a palette to one and forgetting the other shipped
 * either a dot-less menu item or a stale entry. Neither can happen now: both come
 * from the same manifest field, and `checkThemeRoles` fails the build if a
 * picker-listed theme declares no swatch.
 *
 * WHICH THEMES THE PICKER LISTS, and why it is derived rather than a fourth list:
 * a theme is listed when it is a `base` palette (a brand palette you can pick) or
 * when it names a `cvd` (one of the curated color-vision palettes). `a11y-base` is
 * neither — it is the shared machinery the CVD palettes extend — and the `-dark`
 * wrappers are reached through their base's dark mode, not picked directly.
 *
 * See engineering/decisions/2026-08-09-theme-token-contract.md.
 *
 * Usage:
 *   node tools/build-theme-catalog.js            regenerate
 *   node tools/build-theme-catalog.js --check    freshness gate (CI)
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const THEMES_DIR = path.join(ROOT, 'themes');
const OUT = path.join(ROOT, 'docs', 'src', 'lib', 'theme-catalog.generated.ts');
// The theme GRAPH lives beside the pure resolver that consumes it, not in the docs
// bundle: the Node CLI, the unit suite and the browser all import it by relative path,
// and a docs-only home is unreachable from the first two. EVERY manifest, not just the
// picker-listed bases — the `*-dark` variants are precisely the ones that have a parent.
const EDGES_OUT = path.join(ROOT, 'lib', 'theme', 'edges.generated.js');
function renderEdges() {
  const lines = manifests()
    .filter((m) => m.extends)
    .map((m) => `  ${/^[a-z][a-z0-9]*$/.test(m.name) ? m.name : `'${m.name}'`}: '${m.extends}',`)
    .join('\n');
  return `// GENERATED by tools/build-theme-catalog.js from themes/*.manifest.json — DO NOT EDIT.
//
// THE theme graph: name → the theme it extends (manifest \`extends\`). Every Lattice path
// resolves a palette's chain from THIS, via lib/theme/chain.js — never by regexing
// \`@import\` out of a stylesheet. The CSS import is MARP's copy of the same edge, and
// \`checkThemeGraph\` keeps the two equal.
// See engineering/decisions/2026-08-16-manifest-is-the-theme-contract.md.
const THEME_EDGES = Object.freeze({
${lines}
});

module.exports = { THEME_EDGES };
`;
}

function manifests() {
  return fs.readdirSync(THEMES_DIR)
    .filter((f) => f.endsWith('.manifest.json'))
    .map((f) => JSON.parse(fs.readFileSync(path.join(THEMES_DIR, f), 'utf8')))
    .sort((a, b) => a.name.localeCompare(b.name));
}

/** The picker's own order: curated first, then the rest, then the a11y group. */
function render() {
  const all = manifests();
  // Ordered by the manifest's declared `order`, NOT alphabetically: the curated group
  // deliberately leads with indaco, and sorting by name would silently reshuffle the
  // picker menu.
  const group = (pred) => all.filter(pred).sort((a, b) => a.order - b.order).map((m) => m.name);
  const curated = group((m) => m.role === 'base' && m.tier === 'curated');
  const more = group((m) => m.role === 'base' && m.tier === 'more');
  const a11y = group((m) => Boolean(m.cvd));
  const listed = [...curated, ...more, ...a11y];
  const dots = Object.fromEntries(listed.map((n) => [n, all.find((m) => m.name === n).swatch]));

  const key = (n) => (/^[a-z][a-z0-9]*$/.test(n) ? n : `'${n}'`);
  const arr = (xs) => `[${xs.map((x) => `'${x}'`).join(', ')}]`;
  const familyLines = listed
    .map((n) => `\t${key(n)}: '${all.find((m) => m.name === n).family}',`)
    .join('\n');
  const dotLines = listed.map((n) => `\t${key(n)}: '${dots[n]}',`).join('\n');

  return `// GENERATED by tools/build-theme-catalog.js from themes/*.manifest.json — DO NOT EDIT.
// Run \`npm run build\` (or \`node tools/build-theme-catalog.js\`) to regenerate;
// \`theme-catalog:check\` fails the build when this drifts from the manifests.
//
// The manifests are the single declaration of which palettes exist and what each one
// is. See engineering/decisions/2026-08-09-theme-token-contract.md.

/** Brand palettes the picker surfaces first (manifest \`tier: "curated"\`). */
export const CURATED = ${arr(curated)};

/** The remaining brand palettes (manifest \`tier: "more"\`). */
export const MORE_THEMES = ${arr(more)};

/** The curated color-vision palettes (manifest \`cvd\`). */
export const A11Y_THEMES = ${arr(a11y)};

/** Every palette the Studio can drive via \`data-palette\` — curated + more + the AA color-blind set. */
export const BUILTIN_PALETTES = [...CURATED, ...MORE_THEMES, ...A11Y_THEMES];

/** Each listed palette's picker dot (manifest \`swatch\`). */
export const PALETTE_DOTS: Record<string, string> = {
${dotLines}
};

/**
 * Each listed palette's FAMILY (manifest \`family\`) — what the site chrome groups by.
 *
 * This replaced \`name.startsWith('a11y-')\`. A filename prefix is a naming convention,
 * not a declaration: it silently mis-groups any user theme whose name happens to begin
 * \`a11y-\`, and it cannot be checked against anything. \`family\` is declared in the
 * manifest and proved against the file by \`checkThemeRoles\`.
 */
export const THEME_FAMILY: Record<string, 'brand' | 'a11y'> = {
${familyLines}
};

/** True for the curated color-vision palettes. Unknown names (a user's own theme) are
 *  NOT a11y — the group is the curated set, not everything named like it. */
export const isA11yPalette = (name: string): boolean => THEME_FAMILY[name] === 'a11y';
`;
}

function main(argv) {
  const check = argv.includes('--check');
  const next = render();
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  const nextEdges = renderEdges();
  const prevEdges = fs.existsSync(EDGES_OUT) ? fs.readFileSync(EDGES_OUT, 'utf8') : null;
  if (check) {
    if (prev !== next || prevEdges !== nextEdges) {
      process.stderr.write(
        'theme-catalog STALE — docs/src/lib/theme-catalog.generated.ts does not match themes/*.manifest.json.\n' +
        'Run `node tools/build-theme-catalog.js` and commit the result.\n',
      );
      return 1;
    }
    process.stdout.write('theme-catalog OK — theme-catalog.generated.ts matches the manifests.\n');
    return 0;
  }
  fs.writeFileSync(OUT, next);
  fs.writeFileSync(EDGES_OUT, nextEdges);
  process.stdout.write(`theme-catalog: wrote ${path.relative(ROOT, OUT)}\n`);
  return 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));

module.exports = { render };
