#!/usr/bin/env node
/**
 * Build the Veduta library's consumable dist/ — the ESM + CJS entry + type declarations that
 * make it a publishable unit (engineering/decisions/2026-10-16-preview-as-library-audit.md).
 *   docs/src/lib/veduta/*.ts  →  dist/index.{mjs,cjs} + dist/*.d.ts
 * Fuoco's recipe (tools/build-fuoco-lib.js) with ONE entrypoint: Veduta is a framework-free,
 * dependency-free core. A host plugs in its own focus source and its own connectors, so there is
 * no React adapter yet; add `react.ts` here the day one exists.
 * Flags:
 *   --check    Rebuild into a temp dir and diff against dist/. Exits 1 on drift.
 *   --silent   Suppress the success log line.
 */

const { defineLibraryBuild } = require('./lib/build-workspace-lib.js');

defineLibraryBuild({
  name: 'veduta',
  entries: [{ entry: 'index.ts', out: 'index' }],
  external: [],
  banner: (entry) => `/* Auto-generated by tools/build-veduta-lib.js — DO NOT EDIT.\n   Source: docs/src/lib/veduta/${entry}. Rebuild: npm run veduta-lib:build */`,
  platform: 'browser',
}).run();
