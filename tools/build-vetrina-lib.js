#!/usr/bin/env node
/**
 * Build the Vetrina library's consumable dist/ — the ESM + CJS entries + type
 * declarations that make it a publishable unit (2026-07-08-library-shape-cadenza-vetrina.md).
 *
 *   docs/src/lib/vetrina/*.ts  (source, docs-side ESM/TS)
 *     →  dist/index.mjs + dist/react.mjs   (bundled ESM, esbuild)
 *     →  dist/index.cjs + dist/react.cjs   (bundled CJS, esbuild)
 *     →  dist/*.d.ts                        (declarations, tsc)
 *
 * Same recipe as tools/build-cadenza-lib.js, with Vetrina's two differences:
 *   - TWO entrypoints — the framework-free core (`.` → index.ts) and the React
 *     adapter (`./react` → react.ts).
 *   - `react` is a PEER dependency: it's marked EXTERNAL for esbuild (never bundled
 *     — the consumer brings their own React) and resolved for the .d.ts emit via
 *     @types/react (a root devDep). react-dom is externalized too (the boundary gate
 *     sanctions it in the adapter), though the adapter imports only react today.
 *
 * Bundler = the in-tree esbuild; declarations = `tsc --emitDeclarationOnly`. Docs +
 * Vitest import the TS SOURCE through the `@/lib/*` path ALIAS (not the package name);
 * this dist/ is what an external consumer resolves — `require` → dist/*.cjs, `import`
 * → dist/*.mjs (the `import` condition used to point at raw ./index.ts and crashed a
 * plain Node-ESM consumer), + future npm publish.
 *
 * The build itself is tools/lib/build-workspace-lib.js, one builder for every workspace
 * library; this script states only what is particular to this one.
 *
 * Flags:
 *   --check    Rebuild into a temp dir and diff the whole tree against the
 *              committed dist/. Exits 1 on drift (the freshness gate).
 *   --silent   Suppress the success log line.
 */

const path = require('node:path');
const { defineLibraryBuild } = require('./lib/build-workspace-lib.js');

// `.` (core) + `./react` (adapter); react and react-dom are peer deps, never bundled.
// Vetrina's one dependency: the LTT format package (LTT step 4 opened the gate to it, exactly as
// Cadenza's), inlined from SOURCE: through the package's `exports` map esbuild would read
// docs/src/lib/ltt/dist/index.mjs, and tools/build.js runs the library builders in parallel, so
// this build must never wait for build-ltt-lib.js.
defineLibraryBuild({
  name: 'vetrina',
  entries: [
    { entry: 'index.ts', out: 'index' },
    { entry: 'react.ts', out: 'react' },
  ],
  external: ['react', 'react-dom'],
  alias: { '@laticent/ltt': path.join(__dirname, '..', 'docs', 'src', 'lib', 'ltt', 'index.ts') },
  // One banner per entry, naming its own source file.
  banner: (entry) => `/* Auto-generated by tools/build-vetrina-lib.js — DO NOT EDIT.\n   Source: docs/src/lib/vetrina/${entry}. Rebuild: npm run vetrina-lib:build */`,
  target: 'node18',
  // As this library has always built: the node platform and bundler-mode declarations.
  platform: 'node',
  types: { module: 'esnext', moduleResolution: 'bundler', lib: null },
  outfile: true,
}).run();
