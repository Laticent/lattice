#!/usr/bin/env node
/**
 * Build the Vetrina library's node-consumable dist/ — the CJS entries + type
 * declarations that make it a publishable unit (2026-07-08-library-shape-cadenza-vetrina.md).
 *
 *   docs/src/lib/vetrina/*.ts  (source, docs-side ESM/TS)
 *     →  dist/index.cjs + dist/react.cjs   (bundled CJS, esbuild)
 *     →  dist/*.d.ts                        (declarations, tsc)
 *
 * Same recipe as tools/build-cadenza-lib.js, with Vetrina's two differences:
 *   - TWO entrypoints — the framework-free core (`.` → index.ts) and the React
 *     adapter (`./react` → react.ts).
 *   - `react` is a PEER dependency: it's marked EXTERNAL for esbuild (never bundled
 *     — the consumer brings their own React) and resolved for the .d.ts emit via
 *     @types/react (a root devDep). react-dom is externalized too (the boundary gate
 *     sanctions it in the adapter), though the adapter imports only react today.
 *
 * Bundler = the in-tree esbuild; declarations = `tsc --emitDeclarationOnly`. Docs +
 * Vitest keep importing the TS SOURCE (the package's `import`/`types` conditions point
 * at ./index.ts / ./react.ts); this dist/ is for the `require` condition + future publish.
 *
 * Flags:
 *   --check    Rebuild into a temp dir and diff the whole tree against the
 *              committed dist/. Exits 1 on drift (the freshness gate).
 *   --silent   Suppress the success log line.
 */

const esbuild = require('esbuild');
const { spawnSync } = require('node:child_process');
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');

const ROOT = path.resolve(__dirname, '..');
const LIB_DIR = path.join(ROOT, 'docs', 'src', 'lib', 'vetrina');
const DIST_DIR = path.join(LIB_DIR, 'dist');
const TSC = path.join(ROOT, 'node_modules', '.bin', 'tsc');
const ENTRIES = ['index.ts', 'react.ts']; // `.` (core) + `./react` (adapter)
const EXTERNAL = ['react', 'react-dom']; // peer deps — never bundled

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const silent = argv.includes('--silent') || check;

function banner(entry) {
  return (
    `/* Auto-generated by tools/build-vetrina-lib.js — DO NOT EDIT.\n` +
    `   Source: docs/src/lib/vetrina/${entry}. Rebuild: npm run vetrina-lib:build */`
  );
}

/** The non-test source files whose declarations we emit (tests never ship). */
function sourceFiles() {
  return fs
    .readdirSync(LIB_DIR)
    .filter(
      (f) =>
        (f.endsWith('.ts') || f.endsWith('.tsx')) && !f.endsWith('.test.ts') && !f.endsWith('.d.ts'),
    )
    .sort()
    .map((f) => path.join(LIB_DIR, f));
}

/** Bundle each entrypoint into its own CJS file; react stays external. */
async function buildCjs(outDir) {
  for (const entry of ENTRIES) {
    const out = `${path.basename(entry, '.ts')}.cjs`;
    await esbuild.build({
      entryPoints: [path.join(LIB_DIR, entry)],
      outfile: path.join(outDir, out),
      bundle: true,
      format: 'cjs',
      platform: 'node',
      target: ['node18'],
      external: EXTERNAL,
      minify: false, // committed, human-readable source
      legalComments: 'none',
      // Pin the TS config INLINE so esbuild never auto-discovers docs/tsconfig.json,
      // whose `extends astro/tsconfigs/strict` resolves unevenly across environments and
      // would flap the freshness gate. See tools/build-cadenza-lib.js for the full note.
      tsconfigRaw: '{}',
      banner: { js: banner(entry) },
    });
  }
}

/** Emit .d.ts for every non-test source via tsc (react resolved via @types/react). */
function buildTypes(outDir) {
  const r = spawnSync(
    TSC,
    [
      '--declaration',
      '--emitDeclarationOnly',
      '--outDir',
      outDir,
      '--rootDir',
      LIB_DIR,
      '--module',
      'esnext',
      '--moduleResolution',
      'bundler',
      '--target',
      'es2022',
      '--strict',
      '--skipLibCheck',
      ...sourceFiles(),
    ],
    { cwd: ROOT, stdio: 'inherit' },
  );
  if (r.status !== 0) throw new Error('tsc declaration emit failed');
}

/** Build both artifact kinds into `outDir`. */
async function buildInto(outDir) {
  fs.mkdirSync(outDir, { recursive: true });
  await buildCjs(outDir);
  buildTypes(outDir);
}

/** Every file under `dir` as [relPath → contents], recursing subdirs (dist/ is flat today). */
function readTree(dir, base = dir) {
  const out = new Map();
  if (!fs.existsSync(dir)) return out;
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) {
      for (const [rel, contents] of readTree(full, base)) out.set(rel, contents);
    } else {
      out.set(path.relative(base, full), fs.readFileSync(full, 'utf8'));
    }
  }
  return out;
}

function diffTrees(want, have) {
  const drift = [];
  for (const [name, contents] of want) {
    if (!have.has(name)) drift.push(`missing: ${name}`);
    else if (have.get(name) !== contents) drift.push(`changed: ${name}`);
  }
  for (const name of have.keys()) if (!want.has(name)) drift.push(`extra: ${name}`);
  return drift;
}

async function main() {
  if (check) {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'vetrina-lib-'));
    try {
      await buildInto(tmp);
      const drift = diffTrees(readTree(tmp), readTree(DIST_DIR));
      if (drift.length) {
        console.error(
          '[build-vetrina-lib] STALE — run `npm run vetrina-lib:build` and commit docs/src/lib/vetrina/dist:\n  ' +
            drift.join('\n  '),
        );
        process.exit(1);
      }
      if (!silent) console.log('[build-vetrina-lib] up to date.');
    } finally {
      fs.rmSync(tmp, { recursive: true, force: true });
    }
    return;
  }

  // Build into a sibling temp dir and swap in only on success — a failed build must
  // never leave the committed dist/ deleted. Sibling keeps the rename on one filesystem.
  const staging = `${DIST_DIR}.tmp`;
  fs.rmSync(staging, { recursive: true, force: true });
  try {
    await buildInto(staging);
    fs.rmSync(DIST_DIR, { recursive: true, force: true });
    fs.renameSync(staging, DIST_DIR);
  } finally {
    fs.rmSync(staging, { recursive: true, force: true });
  }
  if (!silent) {
    const files = [...readTree(DIST_DIR).keys()];
    console.log(`[build-vetrina-lib] wrote ${path.relative(ROOT, DIST_DIR)}/ (${files.join(', ')})`);
  }
}

main().catch((e) => {
  console.error('[build-vetrina-lib] failed:', e.message);
  process.exit(1);
});
