#!/usr/bin/env node
/**
 * Generate the curated `--chart-cat1-ink … --chart-cat8-ink` block for every
 * palette that owns a chart categorical cycle.
 *
 * THE SAME PROBLEM, THE SECOND TIER. `tools/derive-cat-ink.js` records why the
 * theme cycle's ink is generated rather than derived in CSS: a render-time
 * `color-mix(… 65%, var(--text-heading))` is contrast-correct and measurably OFF
 * BRAND, because the mix pole has to track the canvas and `--text-heading` is
 * itself chromatic on several palettes (indaco navy, mustard brown, burgundy
 * plum). The chart cycle kept that mix — three copies of it, at
 * quadrant.styles.css and matrix-grid.styles.css — long after the `--cat-*` tier
 * retired it. Measured over 15 palettes x 2 modes x 8 slots (240 pairs, 166 of
 * them chromatic at source chroma >= 0.05):
 *
 *   worst hue shift   18.9deg   (crepuscolo light, slot 8)
 *   mean chroma kept  66%       (a third of it mixed away)
 *   worst chroma kept 45%
 *   contrast vs --bg  4.99:1 … 18.58:1, nothing below AA
 *
 * NOT a contrast defect — nothing failed AA, and `check-viz-render` gated that.
 * Over-correction: the mix sat as high as 18.6:1 against a 4.5 floor and paid up
 * to 55% of the chroma and 19deg of hue for headroom it did not need. The theme
 * author curates a hue; the reader saw it sheared toward the heading ink,
 * unevenly across slots. See #1536 and
 * engineering/decisions/2026-07-15-categorical-token-contract.md Track 4.
 *
 * ONE RECIPE, NOT TWO. The solve is `solveInkArm` from lib/theme/cat-ink.js —
 * the same function `derive-cat-ink.js` and the Studio's browser generator call.
 * Keep the mark's hue and chroma exactly; move only lightness, by binary search,
 * until it clears AA against BOTH slide surfaces (`--bg` and `--bg-alt`) with a
 * margin; direction decided per mode from the canvas itself, so a palette that is
 * dark in both modes (`carbone`) comes out right where a fixed pole could not.
 * Two copies of the solve is precisely the drift this card exists to prevent, so
 * this file owns only the FILE half: which palettes get a block, how it is spliced
 * in, and the fidelity report.
 *
 * WHY A SEED NAME (`--chart-cat1-ink`) AND NOT THE CONSUMED NAME
 * (`--chart-cat-1-ink`): the chart family owns the consumed token and reads the
 * seed through it —
 *   --chart-cat-1-ink: var(--chart-cat1-ink, <the old CSS derivation>);
 * exactly as it already does for `--chart-cat1` -> `--chart-cat-1-hue`. A palette
 * with no chart cycle keeps the engine default untouched, and the committed value
 * wins wherever one exists.
 *
 * STRICT. An unsolvable palette here is a fact about tracked source, so this
 * caller takes the throw that names the theme and the slot rather than writing a
 * best-effort value into a committed file. (`lib/theme/cat-ink.js` documents the
 * other half of that policy, for the Studio.)
 *
 * NOTE ON HAND-TUNING: `npm run build` runs this in WRITE mode, so a hand-edited
 * value is not merely flagged — it is regenerated over. Change the seed hue, or
 * change the recipe; editing the output does not stick.
 *
 * Usage:
 *   node tools/derive-chart-cat-ink.js            # rewrite the ink block in every palette
 *   node tools/derive-chart-cat-ink.js --check    # verify committed values match (CI)
 *   node tools/derive-chart-cat-ink.js --report   # print fidelity stats, write nothing
 */

const fs = require('node:fs');
const path = require('node:path');
const { resolveTokenExpr } = require('../lib/core/resolve-token-expr');
const { hexToOklch, contrastRatio } = require('../lib/theme/color.js');
const { solveInkArm, solveHeatmapRamp } = require('../lib/theme/cat-ink.js');
const { themeChain } = require('../lib/theme/chain.mjs');
const { THEME_EDGES } = require('../lib/theme/edges.generated.mjs');

const ROOT = path.join(__dirname, '..');
const THEMES_DIR = path.join(ROOT, 'themes');
const SLOTS = 8;

const BEGIN = '/* ── CHART CATEGORICAL INK — generated by tools/derive-chart-cat-ink.js ──';
const END = '  /* ── end chart categorical ink ── */';

/**
 * Every palette file in `name`'s chain, base tokens first (cascade order).
 *
 * The chain comes from the MANIFEST (`extends`, baked into `THEME_EDGES`), not from
 * regexing `@import` out of the stylesheet — the CSS directive is Marp's copy of the
 * same edge. See engineering/decisions/2026-08-16-manifest-is-the-theme-contract.md.
 *
 * `lattice` is the ENGINE base, not a theme edge, so it is absent from the graph and
 * prepended explicitly — from SOURCE, not dist/ (see `inkFor`).
 */
function paletteSource(name) {
	const base = fs.readFileSync(path.join(ROOT, 'lib', 'base', 'base.tokens.css'), 'utf8');
	const chain = themeChain(name, THEME_EDGES)
		.map((n) => path.join(THEMES_DIR, `${n}.css`))
		.filter((f) => fs.existsSync(f))
		.map((f) => fs.readFileSync(f, 'utf8'));
	return [base, ...chain].join('\n');
}
function stripComments(s) {
	return s.replace(/\/\*[\s\S]*?\*\//g, '');
}
function declaredVars(css) {
	const vars = {};
	for (const m of stripComments(css).matchAll(/--([a-zA-Z0-9-]+)\s*:\s*([^;}]+)[;}]/g)) vars[m[1]] = m[2].trim();
	return vars;
}
const isHex = (v) => typeof v === 'string' && /^#[0-9a-fA-F]{6}$/.test(String(v).trim());

/** The 8 `light-dark(...)` ink values for one palette, plus fidelity stats. */
function inkFor(theme) {
	// Base tokens from SOURCE, not dist/ — this generator runs inside `npm run build`,
	// so depending on a built artifact would make it order-sensitive against the very
	// bundle it helps produce.
	const raw = declaredVars(paletteSource(theme));
	const arms = {};
	const seeds = {};
	const stats = { shift: 0, chroma: [], repaired: 0, total: 0, collapsed: [], chromaLost: [] };
	for (const dark of [false, true]) {
		const key = dark ? 'dark' : 'light';
		const R = (t) => resolveTokenExpr(raw[t], raw, dark);
		const bg = R('bg');
		const bgAlt = R('bg-alt');
		if (!isHex(bg) || !isHex(bgAlt)) throw new Error(`${theme}: --bg/--bg-alt did not resolve`);
		const armSeeds = [];
		for (let n = 1; n <= SLOTS; n += 1) {
			const seed = R(`chart-cat${n}`);
			if (!isHex(seed)) throw new Error(`${theme}: --chart-cat${n} did not resolve (${key})`);
			armSeeds.push(seed);
			seeds[n] = seed;
		}
		const { inks, collapsed } = solveInkArm({ marks: armSeeds, bg, bgAlt, strict: true, label: theme, arm: key });
		for (let n = 1; n <= SLOTS; n += 1) (arms[n] ??= {})[key] = inks[n - 1];
		if (collapsed) stats.collapsed.push(key);

		// Fidelity is measured AFTER any anti-collapse pass, over the values actually
		// written — measuring the per-slot solve would describe colors the guard had
		// already replaced. Same reasoning as derive-cat-ink.js.
		for (let n = 1; n <= SLOTS; n += 1) {
			const S = hexToOklch(seeds[n]);
			const I = hexToOklch(arms[n][key]);
			stats.total += 1;
			if (arms[n][key].toLowerCase() !== seeds[n].toLowerCase()) stats.repaired += 1;
			if (S.C > 0.02) {
				let d = Math.abs(S.h - I.h) % 360;
				if (d > 180) d = 360 - d;
				if (I.C > 0.02) stats.shift = Math.max(stats.shift, d);
				else stats.chromaLost.push(`chart-cat${n}-${key}`);
			}
			if (S.C > 0.001) stats.chroma.push(I.C / S.C);
		}
	}
	return { arms, stats };
}

/**
 * GATING, on top of the staleness check.
 *
 * `--check` already proves the committed block equals a fresh solve, and the solve
 * is strict at AA + margin against both surfaces — so equality transitively proves
 * contrast. This asserts it DIRECTLY anyway, because that chain is only as good as
 * the reader's willingness to follow it, and a future edit to the solver could keep
 * the two sides equal while lowering the floor for both.
 *
 * SCOPE, stated because it is the part that bit: this gates the ink on the SLIDE
 * SURFACES (`--bg`, `--bg-alt`), which is where the cycle paints text today (the
 * matrix-grid row label). It does NOT gate it against `--chart-cat-N-fill`, the
 * quadrant/matrix-grid TINT — a different and much closer surface, on which the raw
 * ink fails AA in 77 of 240 combinations. Those two call sites keep their mix toward
 * the heading ink for that reason; see #1536.
 */
function contrastFailures(theme) {
	const raw = declaredVars(paletteSource(theme));
	const bad = [];
	for (const dark of [false, true]) {
		const key = dark ? 'dark' : 'light';
		const R = (t) => resolveTokenExpr(raw[t], raw, dark);
		const bg = R('bg');
		const bgAlt = R('bg-alt');
		for (let n = 1; n <= SLOTS; n += 1) {
			const ink = R(`chart-cat${n}-ink`);
			if (!isHex(ink)) {
				bad.push(`${theme} ${key} slot ${n}: --chart-cat${n}-ink did not resolve`);
				continue;
			}
			const worst = Math.min(contrastRatio(ink, bg), contrastRatio(ink, bgAlt));
			if (worst < 4.5) bad.push(`${theme} ${key} slot ${n}: ${worst.toFixed(2)}:1 against --bg / --bg-alt`);
		}
	}
	return bad;
}

function renderBlock(arms) {
	const lines = [
		'  /* ── CHART CATEGORICAL INK — generated by tools/derive-chart-cat-ink.js ──',
		'   * The chart categorical hue as TEXT on --bg / --bg-alt, one per slot. Same hue',
		'   * and chroma as --chart-catN; lightness solved until it clears AA on both slide',
		'   * surfaces. Read via --chart-cat-N-ink in the chart family, which falls back to',
		'   * its own derivation for a palette with no chart cycle. Do not hand-edit: re-run',
		'   * the generator after re-hueing a seed. Gated by `derive-chart-cat-ink.js --check` (inside build:check). */',
	];
	for (let n = 1; n <= SLOTS; n += 1) {
		lines.push(`  --chart-cat${n}-ink: light-dark(${arms[n].light.toUpperCase()}, ${arms[n].dark.toUpperCase()});`);
	}
	lines.push(END);
	return `${lines.join('\n')}\n`;
}

/** Splice the generated block into a palette, replacing any previous one. */
function writeBlock(file, block) {
	let css = fs.readFileSync(file, 'utf8');
	const at = css.indexOf(BEGIN.trim());
	if (at !== -1) {
		const endAt = css.indexOf(END, at);
		const lineStart = css.lastIndexOf('\n', at) + 1;
		css = css.slice(0, lineStart) + block + css.slice(endAt + END.length + 1);
	} else {
		// Land it directly after the chart cycle, where a reader looks for it. Anchored
		// on the LAST line mentioning --chart-cat8, not on a line that starts with it.
		const m = [...css.matchAll(/^[^\n]*--chart-cat8\s*:[^\n]*\n/gm)].pop();
		if (!m) throw new Error(`${file}: no --chart-cat8 to anchor the ink block to`);
		const insertAt = m.index + m[0].length;
		css = `${css.slice(0, insertAt)}\n${block}${css.slice(insertAt)}`;
	}
	fs.writeFileSync(file, css);
}

/** Palettes that OWN a chart cycle. A theme without one keeps the engine default. */
function chartCyclePalettes() {
	return fs
		.readdirSync(THEMES_DIR)
		.filter((f) => f.endsWith('.manifest.json'))
		.map((f) => JSON.parse(fs.readFileSync(path.join(THEMES_DIR, f), 'utf8')))
		.filter((m) => m.role !== 'variant-dark') // a variant-dark is a color-scheme flip over its base
		.map((m) => m.name)
		.filter((t) => {
			const file = path.join(THEMES_DIR, `${t}.css`);
			return fs.existsSync(file) && /--chart-cat1\s*:/.test(stripComments(fs.readFileSync(file, 'utf8')));
		})
		.sort();
}

/* ── The heatmap ramp ────────────────────────────────────────────────────────
 *
 * A SECOND TIER IN THIS FILE, not a second generator. The recipe is
 * `solveHeatmapRamp` in lib/theme/cat-ink.js, which documents WHY the ramp is
 * quantized and why one set of step positions has to serve both canvases. This
 * half owns only the file work: which palettes get a block, how it is spliced,
 * and the gate.
 *
 * WHY IT LIVES HERE rather than in a sibling script. It needs exactly what this
 * file already builds — the resolved palette source, both canvases, and the
 * splice/check/report skeleton — and a `tools/derive-heatmap-ramp-ink.js` would
 * be a second entry in build.js that every future PR pays for, to re-derive the
 * same three inputs. One generator, two blocks, one `--check`.
 */
const RAMP_STEPS = 5;
// The ramp's ends, MIRRORING heatmap.transform.js's MIX_FLOOR / MIX_TOP. Its
// docblock carries why the floor is not zero; test/unit/components/heatmap.test.js
// fails when the two drift.
const RAMP_LO = 18;
const RAMP_HI = 92;
const RAMP_BEGIN = '/* ── HEATMAP RAMP — generated by tools/derive-chart-cat-ink.js ──';
const RAMP_END = '  /* ── end heatmap ramp ── */';

/** The heatmap's neutral anchor, mirroring heatmap.styles.css `--heatmap-base`. */
function heatmapAnchor(raw, dark) {
	const muted = resolveTokenExpr(raw['muted-mark'], raw, dark);
	const bg = resolveTokenExpr(raw.bg, raw, dark);
	if (!isHex(muted) || !isHex(bg)) return null;
	const anchor = resolveTokenExpr(`color-mix(in oklab, ${muted} 16%, ${bg})`, raw, dark);
	return isHex(anchor) ? anchor : null;
}

/** One canvas's three inputs: the ramp hue, the neutral it mixes into, the ink's source. */
function rampSide(raw, dark) {
	// `--chart-cat-1-hue` is `var(--chart-cat1, <engine default>)`, and this runs
	// only over palettes that own a cycle, so the seed is the theme's own.
	const hue = resolveTokenExpr(raw['chart-cat1'], raw, dark);
	const seed = resolveTokenExpr(raw['text-body'], raw, dark);
	const anchor = heatmapAnchor(raw, dark);
	if (!isHex(hue) || !isHex(seed) || !anchor) return null;
	return { hue, anchor, seed };
}

/**
 * Palettes that get a ramp block: EVERY base palette, not only the cycle owners.
 *
 * WIDER THAN `chartCyclePalettes` ON PURPOSE, and the four extra are the reason.
 * A categorical ink block is meaningless without a cycle — no slots, nothing to
 * ink. A heatmap ramp is not: every palette renders heatmaps, and the ramp's hue
 * resolves for all of them (`--chart-cat-1-hue` falls back to the engine's own
 * blue when a theme names no cycle). The four palettes with no cycle are the CVD
 * set — a11y-achromatopsia, -deuteranopia, -protanopia, -tritanopia — which are
 * exactly the palettes where an ungenerated fallback would be least excusable.
 * All four solve, none needs a nudge.
 */
function rampPalettes() {
	return fs
		.readdirSync(THEMES_DIR)
		.filter((f) => f.endsWith('.manifest.json'))
		.map((f) => JSON.parse(fs.readFileSync(path.join(THEMES_DIR, f), 'utf8')))
		.filter((m) => m.role !== 'variant-dark') // a variant-dark is a color-scheme flip over its base
		.map((m) => m.name)
		.filter((t) => fs.existsSync(path.join(THEMES_DIR, `${t}.css`)))
		.sort();
}

/** The 5 step positions and their `light-dark(...)` inks for one palette. */
function rampFor(theme) {
	const raw = declaredVars(paletteSource(theme));
	const light = rampSide(raw, false);
	const dark = rampSide(raw, true);
	if (!light || !dark) throw new Error(`${theme}: --chart-cat1 / --text-body / --muted-mark did not resolve`);
	// Mixing in oklab is the CSS engine's job; `solveHeatmapRamp` stays fs-free and
	// browser-safe by taking it injected (see its docblock).
	const fillAt = (hue, anchor, mix, isDark) => {
		const f = resolveTokenExpr(`color-mix(in oklab, ${hue} ${mix}%, ${anchor})`, raw, isDark);
		return isHex(f) ? f : null;
	};
	return solveHeatmapRamp({ light, dark, fillAt, lo: RAMP_LO, hi: RAMP_HI, steps: RAMP_STEPS, strict: true, label: theme });
}

function renderRampBlock({ mixes, inks }) {
	const lines = [
		'  /* ── HEATMAP RAMP — generated by tools/derive-chart-cat-ink.js ──',
		'   * The heatmap prints a value INSIDE each cell, which is text on a colored fill —',
		'   * the one placement the chart family does not otherwise guarantee contrast for.',
		'   * It can here because the ramp is QUANTIZED: five chosen stops rather than a',
		'   * continuum, so each stop carries an ink solved against the fill that actually',
		'   * appears under it. A stop sits at its even position unless the fill there is one',
		'   * no ink can reach, in which case it is nudged (at most 2% in the shipped set).',
		'   * The positions are plain numbers because they serve BOTH canvases; only the ink',
		"   * is a light-dark() pair. Do not hand-edit: `npm run build` regenerates over it.",
		'   * Gated by `derive-chart-cat-ink.js --check` (inside build:check). */',
	];
	for (let n = 0; n < mixes.length; n += 1) {
		lines.push(`  --heatmap-step${n + 1}: ${Number(mixes[n].toFixed(2))}%;`);
		lines.push(`  --heatmap-step${n + 1}-ink: light-dark(${inks[n].light.toUpperCase()}, ${inks[n].dark.toUpperCase()});`);
	}
	lines.push(RAMP_END);
	return `${lines.join('\n')}\n`;
}

/**
 * GATING, directly rather than transitively — the same argument the categorical
 * gate above makes for itself, and the same reason: `--check` proving the block
 * equals a fresh solve is only as good as the solver, and a future edit could
 * keep both sides equal while lowering the floor.
 *
 * This one gates the pair that actually paints: the committed `--heatmap-stepN-ink`
 * against the fill the committed `--heatmap-stepN` produces, on each canvas.
 */
function rampContrastFailures(theme) {
	const raw = declaredVars(paletteSource(theme));
	const bad = [];
	for (const dark of [false, true]) {
		const key = dark ? 'dark' : 'light';
		const side = rampSide(raw, dark);
		if (!side) {
			bad.push(`${theme} ${key}: the ramp inputs did not resolve`);
			continue;
		}
		for (let n = 1; n <= RAMP_STEPS; n += 1) {
			const mix = String(raw[`heatmap-step${n}`] || '').trim();
			const ink = resolveTokenExpr(raw[`heatmap-step${n}-ink`], raw, dark);
			if (!/^[\d.]+%$/.test(mix) || !isHex(ink)) {
				bad.push(`${theme} ${key} step ${n}: --heatmap-step${n} / --heatmap-step${n}-ink did not resolve`);
				continue;
			}
			const fill = resolveTokenExpr(
				`color-mix(in oklab, ${side.hue} ${Number.parseFloat(mix)}%, ${side.anchor})`,
				raw,
				dark,
			);
			if (!isHex(fill)) {
				bad.push(`${theme} ${key} step ${n}: the fill did not resolve`);
				continue;
			}
			const r = contrastRatio(ink, fill);
			if (r < 4.5) bad.push(`${theme} ${key} step ${n}: ${r.toFixed(2)}:1 of ink on its own cell`);
		}
	}
	return bad;
}

/** Splice the ramp block in, directly after the categorical ink block. */
function writeRampBlock(file, block) {
	let css = fs.readFileSync(file, 'utf8');
	const at = css.indexOf(RAMP_BEGIN.trim());
	if (at !== -1) {
		const endAt = css.indexOf(RAMP_END, at);
		const lineStart = css.lastIndexOf('\n', at) + 1;
		css = css.slice(0, lineStart) + block + css.slice(endAt + RAMP_END.length + 1);
	} else {
		// After the categorical ink block, which writeBlock has already placed, so the
		// two generated tiers sit together and a reader finds them in one place.
		const anchorAt = css.indexOf(END);
		if (anchorAt !== -1) {
			const insertAt = anchorAt + END.length + 1;
			css = `${css.slice(0, insertAt)}\n${block}${css.slice(insertAt)}`;
		} else {
			// A palette with NO chart cycle has no ink block to sit under — the CVD set.
			// Land it at the end of the first `:root` block, which is where a palette
			// declares its tokens and where the theme's values must sit to beat the
			// engine's component-scoped defaults by source order.
			const rootAt = css.indexOf(':root {');
			const closeAt = rootAt === -1 ? -1 : css.indexOf('\n}', rootAt);
			if (closeAt === -1) throw new Error(`${file}: no :root block to anchor the heatmap ramp to`);
			css = `${css.slice(0, closeAt + 1)}\n${block}${css.slice(closeAt + 1)}`;
		}
	}
	fs.writeFileSync(file, css);
}

function main() {
	const mode = process.argv.includes('--check') ? 'check' : process.argv.includes('--report') ? 'report' : 'write';
	const themes = chartCyclePalettes();
	const rampThemes = rampPalettes();

	const stale = [];
	const rampStale = [];
	let rampNudged = 0;
	let rampTotal = 0;
	let worstShift = 0;
	let chroma = [];
	for (const theme of themes) {
		const { arms, stats } = inkFor(theme);
		worstShift = Math.max(worstShift, stats.shift);
		chroma = chroma.concat(stats.chroma);
		const block = renderBlock(arms);
		const file = path.join(THEMES_DIR, `${theme}.css`);
		const current = fs.readFileSync(file, 'utf8');
		const at = current.indexOf(BEGIN.trim());
		const has = at !== -1 && current.slice(current.lastIndexOf('\n', at) + 1).startsWith(block);
		if (mode === 'write') writeBlock(file, block);
		else if (mode === 'check' && !has) stale.push(theme);
		if (mode === 'report') {
			const mean = (a) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 1);
			console.log(
				`${theme.padEnd(20)} repaired ${String(stats.repaired).padStart(2)}/${stats.total}  max hue shift ${stats.shift.toFixed(2)}deg  chroma kept ${(100 * mean(stats.chroma)).toFixed(0)}%${stats.collapsed.length ? `  [anti-collapse: ${stats.collapsed.join(',')}]` : ''}`,
			);
		}
	}
	// The ramp runs over a WIDER set than the ink — see rampPalettes. Separate loop
	// rather than a widened one, because the ink block genuinely has nothing to say
	// about a palette with no cycle and must not be written there.
	for (const theme of rampThemes) {
		const ramp = rampFor(theme);
		const rampBlock = renderRampBlock(ramp);
		rampNudged += ramp.mixes.filter(
			(m, k) => Math.abs(m - (RAMP_LO + ((RAMP_HI - RAMP_LO) * k) / (RAMP_STEPS - 1))) > 0.001,
		).length;
		rampTotal += ramp.mixes.length;
		const file = path.join(THEMES_DIR, `${theme}.css`);
		const current = fs.readFileSync(file, 'utf8');
		const rampAt = current.indexOf(RAMP_BEGIN.trim());
		const hasRamp =
			rampAt !== -1 && current.slice(current.lastIndexOf('\n', rampAt) + 1).startsWith(rampBlock);
		// Written AFTER the ink loop, so writeRampBlock finds the ink block to sit
		// under on a palette gaining both at once.
		if (mode === 'write') writeRampBlock(file, rampBlock);
		else if (mode === 'check' && !hasRamp) rampStale.push(theme);
	}

	const mean = (a) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 1);
	if (mode === 'check') {
		const failures = themes.flatMap(contrastFailures);
		if (failures.length) {
			console.error(
				`derive-chart-cat-ink: ${failures.length} committed ink value(s) do not clear AA on both slide surfaces:\n  ${failures.join('\n  ')}`,
			);
			process.exit(1);
		}
		if (stale.length) {
			console.error(
				`derive-chart-cat-ink: ${stale.length} palette(s) have a stale --chart-catN-ink block: ${stale.join(', ')}.\nRun \`node tools/derive-chart-cat-ink.js\` and commit.`,
			);
			process.exit(1);
		}
		const rampFailures = rampThemes.flatMap(rampContrastFailures);
		if (rampFailures.length) {
			console.error(
				`derive-chart-cat-ink: ${rampFailures.length} committed heatmap ramp pair(s) do not clear AA on their own cell:\n  ${rampFailures.join('\n  ')}`,
			);
			process.exit(1);
		}
		if (rampStale.length) {
			console.error(
				`derive-chart-cat-ink: ${rampStale.length} palette(s) have a stale heatmap ramp block: ${rampStale.join(', ')}.\nRun \`node tools/derive-chart-cat-ink.js\` and commit.`,
			);
			process.exit(1);
		}
		console.log(
			`derive-chart-cat-ink: ${themes.length} palettes up to date · all ${themes.length * SLOTS * 2} inks clear AA on --bg and --bg-alt · ` +
				`all ${rampThemes.length * RAMP_STEPS * 2} heatmap ramp pairs clear AA on their own cell across ${rampThemes.length} palettes.`,
		);
	} else if (mode === 'write') {
		console.log(
			`derive-chart-cat-ink: wrote ${themes.length} palettes · max hue shift ${worstShift.toFixed(2)}deg · chroma kept ${(100 * mean(chroma)).toFixed(0)}% · ` +
				`heatmap ramp ${rampNudged}/${rampTotal} steps nudged off even spacing`,
		);
	} else {
		console.log(`\nALL: max hue shift ${worstShift.toFixed(2)}deg · chroma kept ${(100 * mean(chroma)).toFixed(0)}%`);
	}
}

