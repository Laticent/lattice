// Generates proto.css: the LAYOUT half of the responsive-table prototype (Frame Lab). Pure CSS.
// Usage: node gen-css.js <out.css>. Not shipped: lib/base/base.table-reflow.css is the engine's version.
// Every switch is a container query on the table's own wrapper (`.rt`), measured in em of the
// table's text, so a table in a half pane switches exactly as one on a phone does.
// Container query conditions cannot read attributes, so one rule is generated per column count.
const fs = require('fs');
const out = [];
const ON = 'html[data-proto="on"]';

// The width (em) below which each type's wide form no longer reads. d = data columns.
const NEED = {
  records: (d) => (d + 1) * 9,
  prose: (d) => (d + 1) * 15,
  ranked: (d) => (d + 1) * 8.5,
  schedule: (d) => (d + 1) * 9,
  keyvalue: () => 30,
  lists: (d) => (d + 1) * 13,
  options: (d) => 11 + d * 9,
  periods: (d, t) => 8 + (d + t) * 4.2,
  crosstab: (d, t) => 8 + (d + t) * 4.5,
};

out.push(`/* generated by gen-css.js */
.rt-alt { display: none; }
${ON} .rt { container: rt / inline-size; width: 100%; min-width: 0; }
${ON} .rt table td, ${ON} .rt table th { overflow-wrap: break-word; }
${ON} .rt .rt-mini { width: 100%; margin: 0; }
`);

// Wide form → narrow form, per type and column count.
const narrowRule = {
  // Row becomes a card.
  card: (sel) => `
  ${sel} > table.rt-wide, ${sel} > table.rt-wide > tbody { display: block; }
  ${sel} > table.rt-wide > thead { display: none; }
  ${sel} > table.rt-wide > tbody { display: grid; gap: var(--sp-sm); grid-template-columns: repeat(auto-fit, minmax(min(16em, 100%), 1fr)); }
  ${sel} > table.rt-wide > tbody > tr { display: flex; flex-direction: column; gap: .3em; padding: var(--sp-sm) var(--sp-md); border: 1px solid var(--border); border-radius: var(--radius-md); background: var(--bg-alt) !important; }
  ${sel} > table.rt-wide > tbody > tr > td { display: block; padding: 0 !important; border: 0 !important; text-align: left !important; background: none !important; }
  ${sel} > table.rt-wide > tbody > tr > td:first-child { font-weight: 600; color: var(--text-heading); }
  ${sel} > table.rt-wide > tbody > tr > td:not(:first-child)::before { content: attr(data-lat-col) ": "; color: var(--text-secondary); }`,
  // Prose: card with labeled paragraphs.
  prose: (sel) => narrowRule.card(sel) + `
  ${sel} > table.rt-wide > tbody { grid-template-columns: 1fr; }
  ${sel} > table.rt-wide > tbody > tr > td:not(:first-child)::before { content: attr(data-lat-col); display: block; font-size: .72em; letter-spacing: .06em; text-transform: uppercase; }`,
  // Two-line row: lead cell, name, value on line 1; the rest small beneath the name.
  ranked: (sel) => `
  ${sel} > table.rt-wide, ${sel} > table.rt-wide > tbody { display: block; }
  ${sel} > table.rt-wide > thead { display: block; }
  ${sel} > table.rt-wide > thead > tr { display: grid; grid-template-columns: 2.2em 1fr auto; column-gap: var(--sp-sm); border-bottom: 1px solid var(--border); background: none !important; }
  ${sel} > table.rt-wide > thead > tr > th { display: block; padding: 0 0 var(--sp-2xs) !important; border: 0 !important; background: none !important; font-size: .75em; color: var(--text-secondary); }
  ${sel} > table.rt-wide > thead > tr > th:nth-child(1) { grid-column: 1; text-align: right !important; }
  ${sel} > table.rt-wide > thead > tr > th:nth-child(2) { grid-column: 2; text-align: left !important; }
  ${sel} > table.rt-wide > thead > tr > th:last-child { grid-column: 3; text-align: right !important; }
  ${sel} > table.rt-wide > thead > tr > th:not(:nth-child(1)):not(:nth-child(2)):not(:last-child) { display: none; }
  ${sel} > table.rt-wide > tbody > tr { display: grid; grid-template-columns: 2.2em 1fr auto; column-gap: var(--sp-sm); align-items: baseline; padding: var(--sp-xs) 0; border-bottom: 1px solid var(--border); background: none !important; }
  ${sel} > table.rt-wide > tbody > tr > td { display: block; padding: 0 !important; border: 0 !important; background: none !important; }
  ${sel} > table.rt-wide > tbody > tr > td:nth-child(1) { grid-column: 1; color: var(--text-secondary); text-align: right !important; }
  ${sel} > table.rt-wide > tbody > tr > td:nth-child(2) { grid-column: 2; font-weight: 600; color: var(--text-heading); text-align: left !important; }
  ${sel} > table.rt-wide > tbody > tr > td:last-child { grid-column: 3; grid-row: 1; text-align: right !important; font-variant-numeric: tabular-nums; }
  ${sel} > table.rt-wide > tbody > tr > td:not(:nth-child(1)):not(:nth-child(2)):not(:last-child) { grid-column: 2 / 4; font-size: .85em; color: var(--text-secondary); text-align: left !important; }`,
  // Schedule: date as a small eyebrow, item, then the rest as labeled meta.
  schedule: (sel) => `
  ${sel} > table.rt-wide, ${sel} > table.rt-wide > tbody { display: block; }
  ${sel} > table.rt-wide > thead { display: none; }
  ${sel} > table.rt-wide > tbody > tr { display: flex; flex-direction: column; gap: .15em; padding: var(--sp-xs) 0 var(--sp-sm); border-bottom: 1px solid var(--border); background: none !important; }
  ${sel} > table.rt-wide > tbody > tr > td { display: block; padding: 0 !important; border: 0 !important; background: none !important; text-align: left !important; }
  ${sel} > table.rt-wide > tbody > tr > td:nth-child(1) { font-size: .75em; letter-spacing: .06em; text-transform: uppercase; color: var(--accent); font-weight: 600; }
  ${sel} > table.rt-wide > tbody > tr > td:nth-child(2) { font-weight: 600; color: var(--text-heading); }
  ${sel} > table.rt-wide > tbody > tr > td:nth-child(n+3) { font-size: .85em; color: var(--text-secondary); }
  ${sel} > table.rt-wide > tbody > tr > td:nth-child(n+3)::before { content: attr(data-lat-col) ": "; }`,
  // Key-value: label above value.
  keyvalue: (sel) => `
  ${sel} > table.rt-wide, ${sel} > table.rt-wide > tbody, ${sel} > table.rt-wide > tbody > tr { display: block; }
  ${sel} > table.rt-wide > thead { display: none; }
  ${sel} > table.rt-wide > tbody > tr { padding: var(--sp-xs) 0; border-bottom: 1px solid var(--border); background: none !important; }
  ${sel} > table.rt-wide > tbody > tr > td { display: block; padding: 0 !important; border: 0 !important; background: none !important; text-align: left !important; }
  ${sel} > table.rt-wide > tbody > tr > td:first-child { font-size: .8em; color: var(--text-secondary); font-weight: 600; }`,
  // Lists: hide the table, show one block per column.
  lists: (sel) => `
  ${sel} > table.rt-wide { display: none; }
  ${sel} > .rt-cols { display: grid; gap: var(--sp-md); grid-template-columns: repeat(auto-fit, minmax(min(14em, 100%), 1fr)); }`,
  // Labels + one column per block (options: recommended first; blocks sit side by side when they fit).
  k1: (sel) => `
  ${sel} > table.rt-wide, ${sel} > .rt-k2 { display: none !important; }
  ${sel} > .rt-k1 { display: grid; gap: var(--sp-md); grid-template-columns: repeat(auto-fit, minmax(min(17em, 100%), 1fr)); }`,
  // Labels + two columns per block.
  k2: (sel) => `
  ${sel} > table.rt-wide { display: none; }
  ${sel} > .rt-k2 { display: grid; gap: var(--sp-md); grid-template-columns: 1fr; }`,
};

const FORM = { records: 'card', prose: 'prose', ranked: 'ranked', schedule: 'schedule', keyvalue: 'keyvalue', lists: 'lists', options: 'k1' };
for (let d = 1; d <= 8; d++) {
  for (const [type, form] of Object.entries(FORM)) {
    const sel = `${ON} .rt[data-rt="${type}"][data-d="${type === 'keyvalue' || type === 'lists' || type === 'records' || type === 'prose' || type === 'ranked' || type === 'schedule' ? d : d}"]`;
    out.push(`@container rt (width < ${NEED[type](d, 0)}em) {${narrowRule[form](sel)}\n}`);
  }
  for (const type of ['periods', 'crosstab']) {
    for (const t of [0, 1]) {
      const sel = `${ON} .rt[data-rt="${type}"][data-d="${d}"][data-tot="${t}"]`;
      // Full table → labels + two columns per block → labels + one column per block.
      if (d > 2) out.push(`@container rt (width < ${NEED[type](d, t)}em) {${narrowRule.k2(sel)}\n}`);
      out.push(`@container rt (width < ${NEED[type](2, t)}em) {${narrowRule.k1(sel)}\n}`);
    }
  }
}

// Shared looks for the generated blocks.
out.push(`
${ON} .rt-list { display: flex; flex-direction: column; gap: var(--sp-2xs); padding: var(--sp-sm) var(--sp-md); border: 1px solid var(--border); border-radius: var(--radius-md); }
${ON} .rt-list-head { font-weight: 600; color: var(--text-heading); padding-bottom: var(--sp-2xs); border-bottom: 1px solid var(--border); }
${ON} .rt-list ul { display: flex; flex-direction: column; gap: var(--sp-2xs); padding: 0 0 0 1.1em; margin: 0; }
${ON} .rt-mini.rt-pick { outline: 2px solid var(--accent); outline-offset: 4px; border-radius: 2px; }
`);
// The output path is the one argument; the Frame Lab build passes its own output folder.
fs.writeFileSync(process.argv[2] || require('path').join(__dirname, 'proto.css'), out.join('\n'));
