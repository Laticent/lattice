"""
Matrix/TRC ICC v4 display profiles, built from primaries and a white point, for the corpus's tagged
fixtures (generate.py). Self-generated, so licensing is ours: no vendor profile is copied.

The colorimetry is the published one for each space (Display P3: DCI-P3 primaries, D65, the sRGB curve;
Adobe RGB (1998): its primaries, D65, gamma 563/256), adapted to the D50 profile connection space with
the Bradford transform, as ICC.1:2022 requires for v4 display profiles (with a `chad` tag recording it).
"""

import struct

import numpy as np

D50 = np.array([0.9642, 1.0, 0.8249])
BRADFORD = np.array([[0.8951, 0.2664, -0.1614], [-0.7502, 1.7135, 0.0367], [0.0389, -0.0685, 1.0296]])


def xyz(x, y):
    return np.array([x / y, 1.0, (1 - x - y) / y])


def rgb_to_xyz(prims, white):
    m = np.stack([xyz(*p) for p in prims], 1)
    s = np.linalg.solve(m, xyz(*white))
    return m * s


def bradford(src_white, dst_white):
    a = BRADFORD @ src_white
    b = BRADFORD @ dst_white
    return np.linalg.inv(BRADFORD) @ np.diag(b / a) @ BRADFORD


def s15(v):
    return struct.pack('>i', int(round(v * 65536)))


def xyz_tag(v):
    return b'XYZ ' + b'\0' * 4 + b''.join(s15(c) for c in v)


def mluc(text):
    data = text.encode('utf-16-be')
    return b'mluc' + b'\0' * 4 + struct.pack('>II', 1, 12) + b'enUS' + struct.pack('>II', len(data), 28) + data


def para_srgb():
    # Function type 3: Y = (aX + b)^g for X >= d, else cX.
    vals = [2.4, 1 / 1.055, 0.055 / 1.055, 1 / 12.92, 0.04045]
    return b'para' + b'\0' * 4 + struct.pack('>HH', 3, 0) + b''.join(s15(v) for v in vals)


def para_gamma(g):
    return b'para' + b'\0' * 4 + struct.pack('>HH', 0, 0) + s15(g)


def sf32(m):
    return b'sf32' + b'\0' * 4 + b''.join(s15(v) for v in m.flatten())


def profile(name, prims, white, trc):
    m = bradford(xyz(*white), D50) @ rgb_to_xyz(prims, white)
    tags = [
        (b'desc', mluc(name)),
        (b'cprt', mluc('No copyright, use freely (generated by the lastra corpus tool)')),
        (b'wtpt', xyz_tag(D50)),
        (b'chad', sf32(bradford(xyz(*white), D50))),
        (b'rXYZ', xyz_tag(m[:, 0])),
        (b'gXYZ', xyz_tag(m[:, 1])),
        (b'bXYZ', xyz_tag(m[:, 2])),
        (b'rTRC', trc),
        (b'gTRC', trc),
        (b'bTRC', trc),
    ]
    table = struct.pack('>I', len(tags))
    body = b''
    offset = 128 + 4 + 12 * len(tags)
    shared = {}
    for sig, data in tags:
        if data in shared:
            table += sig + struct.pack('>II', *shared[data])
            continue
        while (offset + len(body)) % 4:
            body += b'\0'
        at = offset + len(body)
        shared[data] = (at, len(data))
        table += sig + struct.pack('>II', at, len(data))
        body += data
    size = 128 + len(table) + len(body)
    header = struct.pack('>I', size) + b'\0' * 4 + bytes([4, 0x30, 0, 0]) + b'mntrRGB XYZ '
    header += struct.pack('>6H', 2026, 11, 13, 0, 0, 0) + b'acsp' + b'\0' * 4 + struct.pack('>I', 0)
    header += b'\0' * 8 + b'\0' * 8 + struct.pack('>I', 0) + b''.join(s15(c) for c in D50) + b'\0' * 4
    header += b'\0' * 16 + b'\0' * 28
    assert len(header) == 128, len(header)
    return header + table + body


D65 = (0.3127, 0.3290)
DISPLAY_P3 = profile('Display P3 (lastra corpus)', [(0.680, 0.320), (0.265, 0.690), (0.150, 0.060)], D65, para_srgb())
ADOBE_RGB = profile('Adobe RGB (1998) compatible (lastra corpus)', [(0.64, 0.33), (0.21, 0.71), (0.15, 0.06)], D65, para_gamma(563 / 256))
