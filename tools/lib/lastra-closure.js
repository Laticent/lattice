/**
 * lastra-closure: an esbuild plugin that bundles `@laticent/lastra` as a CommonJS module, built
 * in memory from its TypeScript source, so it stays inside its own function in the bundle.
 *
 * WHY. The CLI bundle (tools/build-cli.js) and the Studio's player core (tools/build-player-core.js)
 * ship functions into a page as `toString()` source. An ES-module build of lastra is scope-hoisted
 * into the bundle, and its top-level names (`info`, `view`, `tag`, `A`, …) make esbuild rename
 * same-named locals across the whole bundle: a player's `info` became `info2`, which changes the
 * bytes of every `--player` file while changing nothing they do
 * (engineering/decisions/2026-11-13-image-library.md). Both bundlers used to alias lastra to its
 * built `dist/index.cjs` for that reason. The libraries are ES modules only since 2026-11-23
 * (first-npm-release §9), so there is no such file any more: this plugin builds the same CommonJS
 * bytes in memory instead, with the options the library builder used, and serves them under that
 * same path, so the bundles, their comments and their inlined source maps stay byte-identical.
 *
 * Only these two bundlers need it. Every other bundle reads lastra's ES build, which is correct.
 */
const esbuild = require('esbuild');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..', '..');
const LIB_DIR = path.join(ROOT, 'docs', 'src', 'lib', 'lastra');
// The path the bundle names the module by: the CommonJS build's old location. Nothing is read
// from or written to it; `onLoad` supplies the contents.
const VIRTUAL = path.join(LIB_DIR, 'dist', 'index.cjs');

/** Lastra's root entry as CommonJS, built exactly as tools/build-lastra-lib.js built it. */
async function lastraCommonJs() {
	const result = await esbuild.build({
		entryPoints: { index: path.join(LIB_DIR, 'index.ts') },
		outdir: path.join(LIB_DIR, 'dist'),
		outExtension: { '.js': '.cjs' },
		bundle: true,
		format: 'cjs',
		platform: 'neutral',
		target: ['es2022'],
		external: ['@laticent/lastra'],
		minify: false,
		legalComments: 'none',
		tsconfigRaw: '{}',
		banner: { js: '/* Auto-generated by tools/build-lastra-lib.js — DO NOT EDIT.\n   Source: docs/src/lib/lastra/index.ts. Rebuild: npm run lastra-lib:build */' },
		logLevel: 'silent',
		write: false,
	});
	return result.outputFiles[0].text;
}

/** The plugin. Put it first in `plugins`, so it answers `@laticent/lastra` before any other. */
function lastraClosure() {
	return {
		name: 'lastra-closure',
		setup(build) {
			build.onResolve({ filter: /^@laticent\/lastra$/ }, () => ({ path: VIRTUAL }));
			build.onLoad({ filter: /[\\/]docs[\\/]src[\\/]lib[\\/]lastra[\\/]dist[\\/]index\.cjs$/ }, async () => ({
				contents: await lastraCommonJs(),
				loader: 'js',
				resolveDir: path.dirname(VIRTUAL),
			}));
		},
	};
}

module.exports = { lastraClosure, lastraCommonJs };
