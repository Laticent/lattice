/**
 * The timing engine's content hash — `inputs.engine` in every LTT a producer writes
 * (engineering/ltt.md §The file). NOT a package version: Cadenza's has never moved, so a version
 * could not tell an engine change from no change (2026-09-24-lattice-timing-track.md §4.5).
 *
 * The hash covers the SOURCE the estimate is computed from: Cadenza's `track.ts` (`buildTrack`)
 * and every file it reaches through relative imports, in name order, each preceded by its
 * repo-relative path. The import graph picks the files, so a new timing module is covered the day
 * `track.ts` reaches it, and an edit to the cursor, the validator or the docs does not mark every
 * measured segment stale (the step-2 inversion pass). Source rather than the bundled build, for two
 * reasons: the Studio runs Cadenza from source through a path alias and never sees the bundle, and
 * a bundler upgrade that reprints the same code should not mark every measured segment stale.
 *
 * `docs/src/lib/cadenza/engine-hash.ts` carries the result as a constant, because a browser
 * cannot read the files back. `npm run engine-hash:build` rewrites it, and
 * test/unit/tools/timing-engine-hash.test.js fails when it is stale.
 *
 * DELIBERATELY NOT A STEP OF `npm run build`. CI's `npm ci` runs the build (`prepare`) before the
 * unit tests, so a build step that rewrote this file would repair a stale commit before the test
 * could see it, and a PR that forgot to regenerate it would merge green (red team, step 2). As its
 * own script, the committed file is what the test reads, and staleness fails the PR.
 */
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..', '..');
const ENTRY = 'docs/src/lib/cadenza/track.ts';
const OUT = path.join(ROOT, 'docs', 'src', 'lib', 'cadenza', 'engine-hash.ts');
/** Every relative module specifier in a source file: `from './x'`, `import './x'`, `import('./x')`. */
const RELATIVE_IMPORT = /(?:\bfrom\s*|\bimport\s*\(?\s*)['"](\.{1,2}\/[^'"]+)['"]/g;

/** The files the estimate is computed from: `ENTRY` and its relative-import closure, sorted. */
function engineSources() {
  const seen = new Set();
  const visit = (rel) => {
    if (seen.has(rel)) return;
    seen.add(rel);
    const src = fs.readFileSync(path.join(ROOT, rel), 'utf8');
    for (const m of src.matchAll(RELATIVE_IMPORT)) {
      const base = path.posix.join(path.posix.dirname(rel), m[1]).replace(/\.js$/, '');
      const next = [`${base}.ts`, `${base}/index.ts`].find((c) => fs.existsSync(path.join(ROOT, c)));
      // Loud, not skipped: an import this walker cannot resolve (a .json, an .mjs) would leave a
      // file the estimate depends on out of the hash, and nothing would say so.
      if (!next) throw new Error(`timing-engine-hash: ${rel} imports '${m[1]}', which is not a .ts module this hash can cover`);
      visit(next);
    }
  };
  visit(ENTRY);
  return [...seen].sort();
}

function timingEngineHash() {
  const h = crypto.createHash('sha256');
  for (const rel of engineSources()) {
    h.update(`${rel}\n`);
    h.update(fs.readFileSync(path.join(ROOT, rel)));
    h.update('\n');
  }
  return `sha256:${h.digest('hex')}`;
}

function engineHashModule(hash = timingEngineHash()) {
  return (
    '// Auto-generated by tools/lib/timing-engine-hash.js (npm run engine-hash:build) — DO NOT EDIT.\n' +
    '// The timing engine\'s content hash, written into every LTT as `inputs.engine`. It changes\n' +
    '// whenever a file `buildTrack` is computed from does; test/unit/tools/timing-engine-hash.test.js\n' +
    '// fails when this file is stale.\n\n' +
    `export const ENGINE_HASH = '${hash}';\n`
  );
}

function writeEngineHash() {
  const text = engineHashModule();
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) fs.writeFileSync(OUT, text);
  return text;
}

module.exports = { OUT, engineSources, timingEngineHash, engineHashModule, writeEngineHash };

if (require.main === module) {
  writeEngineHash();
  console.log(`[timing-engine-hash] ${path.relative(ROOT, OUT)}: ${timingEngineHash()}`);
}
