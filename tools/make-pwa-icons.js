#!/usr/bin/env node
/**
 * Rasterize the brand mark into the PWA icon set (docs/public/icons/) with the
 * puppeteer-cached Chromium.
 *
 * The installable-app icons can't be the adaptive SVG (manifest icons and
 * apple-touch-icon want fixed-color raster PNGs), so this bakes the LIGHT
 * variant of design/logo/lattice-mark.svg onto the brand cream halo
 * (#FAF7F2, the same surface the mark's halos are cut from) at each size:
 *
 *   icon-192.png            192² · purpose "any"    · mark at 80%
 *   icon-512.png            512² · purpose "any"    · mark at 80%
 *   icon-512-maskable.png   512² · purpose "maskable" · mark at 66% so it sits
 *                           inside the 80%-diameter safe zone every OS mask
 *                           (circle, squircle, rounded square) is cut from
 *   apple-touch-icon.png    180² · iOS home screen (iOS applies its own mask)
 *
 * Icons are committed; re-run after any change to the mark (which itself is
 * regenerated by design/logo/generate.py):
 *
 *   node tools/make-pwa-icons.js
 *
 * Chromium resolution mirrors tools/screenshot.js: CHROME_PATH env wins, then
 * the puppeteer cache. --no-sandbox because the sandbox container runs as root.
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const puppeteer = require('puppeteer');

const ROOT = path.join(__dirname, '..');
const MARK = path.join(ROOT, 'design', 'logo', 'lattice-mark.svg');
const OUT_DIR = path.join(ROOT, 'docs', 'public', 'icons');
const CREAM = '#FAF7F2';

// [file, canvas px, mark fraction of canvas]
const ICONS = [
  ['icon-192.png', 192, 0.8],
  ['icon-512.png', 512, 0.8],
  ['icon-512-maskable.png', 512, 0.66],
  ['apple-touch-icon.png', 180, 0.72],
];

/** Best-effort path to a Chromium the sandbox already has. */
function resolveChrome() {
  if (process.env.CHROME_PATH && fs.existsSync(process.env.CHROME_PATH)) {
    return process.env.CHROME_PATH;
  }
  const cacheRoots = [
    path.join(os.homedir(), '.cache', 'puppeteer', 'chrome'),
    '/root/.cache/puppeteer/chrome',
  ];
  for (const root of cacheRoots) {
    if (!fs.existsSync(root)) continue;
    const builds = fs
      .readdirSync(root)
      .filter(d => d.startsWith('linux-'))
      .sort();
    for (const build of builds.reverse()) {
      const bin = path.join(root, build, 'chrome-linux64', 'chrome');
      if (fs.existsSync(bin)) return bin;
    }
  }
  return undefined;
}

async function main() {
  const svg = fs.readFileSync(MARK, 'utf8');
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const browser = await puppeteer.launch({
    executablePath: resolveChrome(),
    headless: true,
    args: ['--no-sandbox', '--disable-setuid-sandbox'],
  });
  try {
    const page = await browser.newPage();
    // Pin the light variant: the mark's @media(prefers-color-scheme:dark)
    // rules must not fire, whatever the host Chromium defaults to.
    await page.emulateMediaFeatures([{ name: 'prefers-color-scheme', value: 'light' }]);
    for (const [file, size, frac] of ICONS) {
      const markPx = Math.round(size * frac);
      await page.setViewport({ width: size, height: size, deviceScaleFactor: 1 });
      await page.setContent(
        `<!doctype html><html><body style="margin:0;width:${size}px;height:${size}px;` +
          `background:${CREAM};display:grid;place-items:center;">` +
          `<div style="width:${markPx}px;height:${markPx}px;">` +
          svg.replace('<svg ', '<svg style="width:100%;height:100%;display:block" ') +
          `</div></body></html>`,
        { waitUntil: 'load' },
      );
      const out = path.join(OUT_DIR, file);
      await page.screenshot({ path: out });
      console.log(`icon: ${path.relative(ROOT, out)} (${size}x${size}, mark ${markPx}px, ${fs.statSync(out).size} bytes)`);
    }
  } finally {
    await browser.close();
  }
}

main().catch(e => {
  console.error('make-pwa-icons failed:', e.message);
  process.exit(1);
});
