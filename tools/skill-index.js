#!/usr/bin/env node
/**
 * The skill index — one source for every surface that offers a Lattice skill.
 *
 * Each `design/skills/<name>.md` opens with a small front-matter block:
 *
 *   ---
 *   name: deck
 *   description: Use when … (one line: what the skill does and when to load it)
 *   kind: make | operate
 *   studio: true | false     (does the Studio chat's read_guide offer it?)
 *   ---
 *
 * This file reads those blocks and writes the indexes every reader uses, so no reader
 * keeps its own list:
 *
 *   design/skills/index.json          the Studio chat (read_guide topics) and tools
 *   design/skills/README.md           the table between the skill-index markers
 *   .claude/skills/lattice-<name>/    one thin SKILL.md per skill, so Claude Code in this
 *                                     repo can pick a skill from its description alone
 *
 * The agent kit (`tools/build-agent-kit.mjs`) reads the same rows through `readSkills()`.
 * Token counts are bytes / 4, rounded up: an estimate, but the same estimate everywhere,
 * so an agent can see what a skill costs before it opens one.
 *
 * Usage:
 *   node tools/skill-index.js           write the indexes
 *   node tools/skill-index.js --check   exit 1 if a skill lacks valid front matter or an
 *                                       index is stale (run by `npm run build:check`)
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const SKILLS_DIR = path.join(ROOT, 'design', 'skills');
const INDEX_JSON = path.join(SKILLS_DIR, 'index.json');
const README = path.join(SKILLS_DIR, 'README.md');
const CLAUDE_SKILLS = path.join(ROOT, '.claude', 'skills');
const CLAUDE_PREFIX = 'lattice-';
const KINDS = new Set(['make', 'operate']);
const START = '<!-- skill-index:start (generated by tools/skill-index.js; edit the skills\' front matter, not this table) -->';
const END = '<!-- skill-index:end -->';

/** Parse a skill's leading `---` block. Returns { fields, body } or null when absent. */
function parseFrontMatter(text) {
  const src = String(text).replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
  const m = src.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) return null;
  const fields = { $raw: m[1] };
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([a-z][a-z-]*):\s*(.*)$/);
    if (!kv) continue;
    const v = kv[2].trim();
    // Quoted values are JSON strings, which are also valid YAML: Claude Code and external
    // agents parse this block as YAML, where an unquoted "a: b" is an error.
    if (v.startsWith('"')) {
      try { fields[kv[1]] = JSON.parse(v); } catch { fields[kv[1]] = { invalid: v }; }
    } else fields[kv[1]] = v;
  }
  return { fields, body: src.slice(m[0].length) };
}

/** Validate one skill's fields; returns a list of problems (empty when fine). */
function validate(file, fields) {
  const base = file.replace(/\.md$/, '');
  const errs = [];
  if (!fields) return [`design/skills/${file}: no front matter. Open the file with a --- block (name, description, kind, studio); see tools/skill-index.js.`];
  if (fields.name !== base) errs.push(`design/skills/${file}: front-matter name "${fields.name || ''}" must equal the file name "${base}".`);
  if (fields.description && typeof fields.description !== 'string') errs.push(`design/skills/${file}: description is not a valid double-quoted string: ${fields.description.invalid}`);
  else if (!/^description: "/m.test(fields.$raw || '')) errs.push(`design/skills/${file}: quote the description ("…") so YAML readers parse it.`);
  if (typeof fields.description !== 'string' || fields.description.length < 30) errs.push(`design/skills/${file}: description is missing or under 30 characters — it is the only thing an agent reads before choosing.`);
  if (typeof fields.description === 'string' && fields.description.length > 300) errs.push(`design/skills/${file}: description is ${fields.description.length} characters; keep it under 300 (it is sent in every index).`);
  if (!KINDS.has(fields.kind)) errs.push(`design/skills/${file}: kind must be "make" or "operate", got "${fields.kind || ''}".`);
  if (fields.studio !== 'true' && fields.studio !== 'false') errs.push(`design/skills/${file}: studio must be "true" or "false", got "${fields.studio || ''}".`);
  return errs;
}

/** Every skill as an index row. Throws on invalid front matter unless `errors` collects it. */
function readSkills(errors) {
  const rows = [];
  const files = fs.readdirSync(SKILLS_DIR).filter((f) => f.endsWith('.md') && f !== 'README.md').sort();
  for (const file of files) {
    const text = fs.readFileSync(path.join(SKILLS_DIR, file), 'utf8');
    const fm = parseFrontMatter(text);
    const errs = validate(file, fm?.fields);
    if (errs.length) {
      if (errors) { errors.push(...errs); continue; }
      throw new Error(errs.join('\n'));
    }
    const title = (fm.body.match(/^# (?:Skill — )?(.+)$/m) || [])[1] || fm.fields.name;
    rows.push({
      name: fm.fields.name,
      file: `design/skills/${file}`,
      title: title.trim(),
      description: fm.fields.description,
      kind: fm.fields.kind,
      studio: fm.fields.studio === 'true',
      tokens: Math.ceil(Buffer.byteLength(text, 'utf8') / 4),
    });
  }
  return rows;
}

function mdCell(s) {
  return String(s).replace(/\|/g, '\\|');
}

function renderJson(rows) {
  return `${JSON.stringify({ $generated: 'tools/skill-index.js — edit the skills\' front matter, not this file', skills: rows }, null, 2)}\n`;
}

function renderTable(rows) {
  const section = (kind, heading) => {
    const list = rows.filter((r) => r.kind === kind);
    if (!list.length) return [];
    return [
      heading,
      '',
      '| Skill | Use when… | ≈ tokens |',
      '|---|---|---|',
      ...list.map((r) => `| [\`${r.name}\`](./${path.basename(r.file)}) | ${mdCell(r.description)} | ${(r.tokens / 1000).toFixed(1)}k |`),
      '',
    ];
  };
  return [
    START,
    '',
    ...section('make', '### Make something new'),
    ...section('operate', '### Work on a deck you already have'),
    END,
  ].join('\n');
}

function renderReadme(current, rows) {
  const a = current.indexOf(START);
  const b = current.indexOf(END);
  if (a < 0 || b < a) throw new Error('design/skills/README.md lost its skill-index markers; restore them so the table can be generated.');
  return current.slice(0, a) + renderTable(rows) + current.slice(b + END.length);
}

function renderClaudeSkill(r) {
  return [
    '---',
    `name: ${CLAUDE_PREFIX}${r.name}`,
    `description: ${JSON.stringify(r.description)}`,
    '---',
    '',
    `<!-- ${GENERATED_MARK} from the skill's front matter. Edit the skill, not this file. -->`,
    '',
    `Read \`${r.file}\` (≈${(r.tokens / 1000).toFixed(1)}k tokens) and follow it.`,
    'Read it section by section: `grep -n \'^## \' ' + r.file + '`, then open the sections the task needs.',
    'The index of every Lattice skill is `design/skills/index.json`.',
    '',
  ].join('\n');
}

const GENERATED_MARK = 'Generated by tools/skill-index.js';

/** Only a SKILL.md this script wrote is ever removed; a hand-written `lattice-*` skill is left alone. */
function isGenerated(file) {
  return fs.existsSync(file) && fs.readFileSync(file, 'utf8').includes(GENERATED_MARK);
}

/** Every generated file as path → content, plus the stale `.claude/skills/lattice-*` dirs to remove. */
function outputs(rows) {
  const files = new Map();
  files.set(INDEX_JSON, renderJson(rows));
  files.set(README, renderReadme(fs.readFileSync(README, 'utf8'), rows));
  const want = new Set(rows.map((r) => `${CLAUDE_PREFIX}${r.name}`));
  for (const r of rows) files.set(path.join(CLAUDE_SKILLS, `${CLAUDE_PREFIX}${r.name}`, 'SKILL.md'), renderClaudeSkill(r));
  const stale = fs.existsSync(CLAUDE_SKILLS)
    ? fs
        .readdirSync(CLAUDE_SKILLS)
        .filter((d) => d.startsWith(CLAUDE_PREFIX) && !want.has(d) && isGenerated(path.join(CLAUDE_SKILLS, d, 'SKILL.md')))
        .map((d) => path.join(CLAUDE_SKILLS, d))
    : [];
  return { files, stale };
}

function main() {
  const argv = process.argv.slice(2);
  const check = argv.includes('--check');
  const silent = argv.includes('--silent') || check;
  const errors = [];
  const rows = readSkills(errors);
  if (errors.length) {
    console.error(`[skill-index] ${errors.length} skill(s) need front matter fixed:\n${errors.map((e) => `  - ${e}`).join('\n')}`);
    process.exit(1);
  }
  const { files, stale } = outputs(rows);
  if (check) {
    const drift = [...files].filter(([f, c]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== c).map(([f]) => path.relative(ROOT, f));
    drift.push(...stale.map((d) => `${path.relative(ROOT, d)} (stale; no skill by that name)`));
    if (drift.length) {
      console.error(`[skill-index] STALE — run \`node tools/skill-index.js\` and commit:\n${drift.map((d) => `  - ${d}`).join('\n')}`);
      process.exit(1);
    }
    if (!silent) console.log('[skill-index] up to date.');
    return;
  }
  for (const [f, c] of files) {
    fs.mkdirSync(path.dirname(f), { recursive: true });
    if (!fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== c) fs.writeFileSync(f, c);
  }
  for (const d of stale) fs.rmSync(d, { recursive: true, force: true });
  if (!silent) console.log(`[skill-index] ${rows.length} skills indexed.`);
}

module.exports = { parseFrontMatter, validate, readSkills, renderTable, renderClaudeSkill, START, END };

if (require.main === module) main();
